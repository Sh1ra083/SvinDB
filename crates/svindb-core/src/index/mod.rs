/// Таблицы множителей делятся между полями с одной средней длиной.
#[cfg(test)]
mod idf_tests {
    use super::*;

    #[test]
    fn an_ubiquitous_term_uses_df_equal_to_n_not_n_minus_one() {
        for n in [2u64, 6, 500] {
            let expected = (1.0 + 0.5 / (n as f64 + 0.5)).ln();
            assert!((idf_of(n, n) - expected).abs() < 1e-15);
        }
    }

    /// Слово, встречающееся почти во всех документах, обязано весить почти
    /// ничего — **на любом размере корпуса**.
    ///
    /// Здесь ловится обрезка частоты до `u32`. Проверка идёт по обе стороны от
    /// четырёх миллиардов, потому что ниже границы обрезка незаметна, а выше —
    /// переворачивает ответ: частота десять в одиннадцатой обрезалась до
    /// `u32::MAX`, и слово из **каждого** документа получало вес слова,
    /// встреченного в четырёх процентах.
    #[test]
    fn a_word_in_every_document_weighs_nothing_at_any_corpus_size() {
        for n in [1_000u64, 1_000_000, u64::from(u32::MAX), 10_000_000_000, 100_000_000_000] {
            let everywhere = idf_of(n, n);
            assert!(everywhere < 0.05, "корпус {n}: слово из каждого документа весит {everywhere}");
            // И порядок сохраняется: чем реже слово, тем оно важнее.
            let half = idf_of(n, n / 2);
            let rare = idf_of(n, 1);
            assert!(
                everywhere < half && half < rare,
                "корпус {n}: порядок важности нарушен: {everywhere} / {half} / {rare}"
            );
        }
    }

    /// Ровно на границе разрядности и рядом с ней ответ меняется плавно.
    ///
    /// Обрезка выдавала здесь ступеньку: всё, что выше `u32::MAX`, отвечало
    /// одинаково, как будто частота перестала расти.
    #[test]
    fn crossing_the_thirty_two_bit_boundary_changes_nothing_abruptly() {
        let n = 100_000_000_000u64;
        let below = idf_of(n, u64::from(u32::MAX) - 1);
        let at = idf_of(n, u64::from(u32::MAX));
        let above = idf_of(n, u64::from(u32::MAX) + 1);
        let far = idf_of(n, u64::from(u32::MAX) * 4);
        assert!(below >= at && at >= above, "важность обязана убывать с частотой");
        assert!(
            above - far > 1e-9,
            "за границей разрядности важность перестала меняться: {above} против {far}"
        );
    }
}

