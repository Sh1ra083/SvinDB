/// Поле маппинга: своя норма, своя средняя длина, свой вес.
/// Тип поля.
///
/// Типы раздельны **на границе** — в объявлении, разборе и проверке, — а
/// хранятся тремя семействами: текст и ключевое слово идут в словарь и постинги,
/// целые с датой и логическим ложатся в колонку как `i64`, дробные — как `f64`
/// в тех же битах. Разрядность на хранение не влияет вовсе: колонка
/// упаковывается побитово, и ширина выводится из данных, а не из объявления.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Kind {
    /// Разбирается на слова, участвует в ранжировании.
    Text,
    /// Значение целиком одним словом: точное совпадение, без ранжирования.
    Keyword,
    /// То же, но без приведения регистра.
    ///
    /// Elasticsearch `keyword` по умолчанию регистрозависим. Правило хранится
    /// видом поля, чтобы одинаково переживать segment, merge и restart.
    KeywordExact,
    Int32,
    Int64,
    Date,
    /// Дата строкой ISO-8601, а внутри — миллисекунды от начала эпохи.
    ///
    /// ## Почему отдельный вид, а не «date, который умеет и то и другое»
    ///
    /// У обычного `date` в колонке лежит то целое, что прислали, — и это чаще
    /// всего секунды. Научи его разбирать ISO «в миллисекунды» — и поле, где
    /// уже лежат секунды, получит значения, отличающиеся в тысячу раз, а
    /// узнать об этом будет неоткуда: отбор по диапазону просто перестанет
    /// находить. Единица измерения обязана быть частью объявления.
    DateIso,
    /// ISO-8601 либо целое число секунд epoch.
    DateIsoSeconds,
    Bool,
    Float,
    Double,
    /// Плотный вектор заданной размерности. Объявляется `имя:dense_vector:768`.
    ///
    /// Содержимое такого поля не хранится **никогда**: в выдаче вектор не нужен
    /// никому, а стоит он вчетверо больше кода, по которому идёт поиск. См.
    /// [`crate::vector`].
    Dense(u16),
    Sparse,
    /// Непрозрачные байты. Значение приходит и отдаётся в Base64.
    ///
    /// ## Почему свой вид, а не ключевое слово
    ///
    /// У ключевого слова регистр сводится на приёме всегда, а Base64
    /// регистрозначим: `AQAAAB8ABbBc` и `aqaaab8abbbc` — разные значения.
    /// Точное совпадение по байтам варианта опроса сломалось бы молча.
    ///
    /// ## Почему словом словаря становится Base64, а не сами байты
    ///
    /// Слияние строит опоры словаря через `String::from_utf8_lossy`. Сырые
    /// не-UTF-8 байты пережили бы приём и испортились бы при первом же
    /// укрупнении — заменой на U+FFFD, без единого слова. Переписывать весь
    /// путь слов на байты ради одного вида поля нельзя; Base64 же — ASCII, и
    /// проходит его невредимым.
    ///
    /// Хранимое содержимое при этом лежит **сырыми байтами**: это на треть
    /// меньше места и честная длина в описи размеров.
    Binary,
    /// Точка на земле: широта и долгота.
    ///
    /// В колонке лежит ключ дробного числа — широта; долгота хранится
    /// отдельной колонкой поля-спутника. Разбор — в [`crate::geo`].
    Geo,
}

impl Kind {
    pub fn parse(s: &str) -> Option<Kind> {
        Some(match s {
            "text" => Kind::Text,
            "keyword" => Kind::Keyword,
            "keyword:exact" | "case_sensitive_keyword" => Kind::KeywordExact,
            "int32" => Kind::Int32,
            "int64" | "long" => Kind::Int64,
            "date" => Kind::Date,
            "date:iso" => Kind::DateIso,
            "date:iso_seconds" => Kind::DateIsoSeconds,
            "bool" => Kind::Bool,
            "float" => Kind::Float,
            "double" => Kind::Double,
            "sparse_vector" => Kind::Sparse,
            "binary" => Kind::Binary,
            "geo_point" => Kind::Geo,
            _ => {
                let dims = s.strip_prefix("dense_vector:")?;
                let dims: usize = dims.trim().parse().ok()?;
                if dims == 0 || dims > crate::vector::MAX_DIMS {
                    return None;
                }
                Kind::Dense(dims as u16)
            }
        })
    }

    /// Как тип записывается в схеме и в `head.tsv`.
    ///
    /// Отдельно от [`Kind::name`] затем, что у плотного вектора к имени
    /// прибавляется размерность, а `name` обязан оставаться `&'static str`:
    /// он идёт в сообщения и в ответ о схеме, где выделение ни к чему.
    pub fn spec(&self) -> String {
        match self {
            Kind::Dense(d) => format!("dense_vector:{d}"),
            // Единица измерения — часть вида, и в заголовке она обязана быть:
            // прочитав `date` там, где записан `date:iso`, читатель получил бы
            // секунды вместо миллисекунд.
            Kind::DateIso => "date:iso".to_string(),
            Kind::DateIsoSeconds => "date:iso_seconds".to_string(),
            Kind::KeywordExact => "keyword:exact".to_string(),
            other => other.name().to_string(),
        }
    }

    /// Размерность плотного вектора.
    pub fn dims(&self) -> Option<usize> {
        match self {
            Kind::Dense(d) => Some(*d as usize),
            _ => None,
        }
    }

    pub fn name(&self) -> &'static str {
        match self {
            Kind::Text => "text",
            Kind::Keyword => "keyword",
            Kind::KeywordExact => "keyword",
            Kind::Int32 => "int32",
            Kind::Int64 => "int64",
            Kind::Date => "date",
            Kind::DateIso => "date",
            Kind::DateIsoSeconds => "date",
            Kind::Bool => "bool",
            Kind::Float => "float",
            Kind::Double => "double",
            Kind::Dense(_) => "dense_vector",
            Kind::Sparse => "sparse_vector",
            Kind::Binary => "binary",
            Kind::Geo => "geo_point",
        }
    }

    /// Ложится ли поле в колонку значений.
    ///
    /// Плотный вектор — не «числовое поле»: у него своя раскладка, свой отбор и
    /// колонки на 64 бита он не имеет. Спрашивать его диапазоном нельзя.
    pub fn numeric(&self) -> bool {
        !matches!(
            self,
            Kind::Text
                | Kind::Keyword
                | Kind::KeywordExact
                | Kind::Dense(_)
                | Kind::Sparse
                | Kind::Binary
                | Kind::Geo
        )
    }

    /// Считается ли вклад скалярным произведением, а не BM25.
    #[inline(always)]
    pub fn dot(&self) -> bool {
        matches!(self, Kind::Sparse)
    }

    /// Ищется ли поле словами. У вектора слов нет.
    pub fn textual(&self) -> bool {
        matches!(self, Kind::Text | Kind::Keyword | Kind::KeywordExact | Kind::Binary)
    }

    #[inline(always)]
    pub fn keyword(&self) -> bool {
        matches!(self, Kind::Keyword | Kind::KeywordExact)
    }

    #[inline(always)]
    pub fn folds_case(&self) -> bool {
        matches!(self, Kind::Keyword)
    }

    /// Дробное ли: биты `f64` в колонке хранятся порядок-сохраняюще.
    pub fn floating(&self) -> bool {
        matches!(self, Kind::Float | Kind::Double)
    }

    /// Разбирает значение поля в то, что ляжет в колонку.
    ///
    /// `None` — значения нет или оно не разобралось. Это не ноль: документ без
    /// цены не должен попадать в отбор «дешевле ста», и отличает их бит
    /// присутствия.
    pub fn parse_value(&self, text: &str) -> Option<i64> {
        let t = text.trim();
        if t.is_empty() {
            return None;
        }
        match self {
            Kind::Bool => match t {
                "true" | "1" => Some(1),
                "false" | "0" => Some(0),
                _ => None,
            },
            // `NaN` не сравним ни с чем, а бесконечности сравнимы, но в отбор
            // по диапазону не укладываются. Elasticsearch их тоже отвергает;
            // молча положить их в колонку значило бы отдать сортировке значение
            // без порядка.
            Kind::Float | Kind::Double => {
                t.parse::<f64>().ok().filter(|f| f.is_finite()).map(float_key)
            }
            Kind::Int32 => t.parse::<i32>().ok().map(|v| v as i64),
            // Голое целое принимается как миллисекунды: так его и отдают
            // системы, работающие с этим полем, и переводить его было бы
            // догадкой о том, чего клиент не говорил.
            Kind::DateIso => match t.parse::<i64>() {
                Ok(v) => Some(v),
                Err(_) => crate::iso::parse_millis(t),
            },
            Kind::DateIsoSeconds => match t.parse::<i64>() {
                Ok(v) => Some(v),
                Err(_) => crate::iso::parse_millis(t).map(|millis| millis.div_euclid(1_000)),
            },
            _ => t.parse::<i64>().ok(),
        }
    }
}

/// Годится ли имя поля.
///
/// ## Почему это проверка, а не вкус
///
/// Имя поля становится **именем файла** внутри каталога сегмента: `цена.col`,
/// `цена.cmeta`, `цена.sbin`. Не проверялось оно вовсе, и схема
/// `../../ESCAPED:int32` клала файлы двумя каталогами выше сегмента — проверено
/// запуском, а не рассуждением.
///
/// Схему задаёт тот, кто поднимает узел, поэтому снаружи это не достать. Но
/// молчаливая запись мимо каталога — не то поведение, которое стоит оставлять
/// на честном слове: тот же путь ломается от таба (порвёт `head.tsv`, где поля
/// разделены табами) и от переноса строки.
///
/// Точка запрещена отдельно, и это смотрит вперёд: у полей с несколькими
/// внутренними колонками имя части будет `поле.lo`, `поле.hi`, `поле.lat`.
/// Разреши мы точку в объявленном имени — `a.lo` как объявленное поле и `a.lo`
/// как часть поля `a` стали бы одним файлом.
pub fn valid_field_name(name: &str) -> Result<(), String> {
    if name.is_empty() {
        return Err("имя поля пустое".into());
    }
    if name.len() > 64 {
        return Err(format!("имя поля длиннее шестидесяти четырёх байт: {name:?}"));
    }
    for c in name.chars() {
        let ok = c.is_alphanumeric() || c == '_' || c == '-' || c == '@';
        if !ok {
            return Err(format!(
                "имя поля {name:?}: символ {c:?} не годится — имя становится именем файла                  в каталоге сегмента, поэтому в нём только буквы, цифры, `_`, `-` и `@`"
            ));
        }
    }
    Ok(())
}

/// Дробное значение в целое с сохранением порядка.
///
/// ## Почему обычного преобразования мало
///
/// Хрестоматийное «у неотрицательных поднять старший разряд, у отрицательных
/// перевернуть все» даёт правильный порядок **как у `u64`**. Колонка же хранит
/// `i64` и сравнивает со знаком — и от поднятого старшего разряда все
/// положительные числа оказываются отрицательными, то есть **ниже** всех
/// отрицательных. Половины меняются местами целиком.
///
/// Здесь наоборот: у положительных не трогается ничего (биты `f64` и так идут по
/// возрастанию, старший разряд снят), у отрицательных биты переворачиваются и
/// старший разряд снимается — вся половина уходит под ноль.
pub fn float_key(v: f64) -> i64 {
    let b = v.to_bits() as i64;
    if b < 0 {
        !b ^ i64::MIN
    } else {
        // Положительное: биты `f64` и так идут по возрастанию, и старший разряд
        // у них снят. Трогать нечего.
        b
    }
}

/// Обратное к [`float_key`].
pub fn float_of(key: i64) -> f64 {
    let b = if key < 0 { !(key ^ i64::MIN) } else { key };
    f64::from_bits(b as u64)
}

pub struct Field {
    pub name: String,
    pub kind: Kind,
    /// Значения поля по документам. Есть только у числовых.
    pub column: Option<crate::column::Column>,
    /// Массивы чисел, которые не представимы одним scalar column значением.
    pub multi_column: Option<crate::multivalue::MultiColumn>,
    pub multi_entries: usize,
    pub multi_values: usize,
    /// Старый формат содержит (либо не позволяет исключить) числовые массивы
    /// без typed stream. Range/sort/aggregation требуют migration из source.
    pub legacy_multivalue: bool,
    /// До layout 12 keyword arrays и remap при merge не были lossless.
    pub legacy_keyword_values: bool,
    pub store: Option<crate::store::Store>,
    /// Коды плотного вектора. Есть только у полей `dense_vector`, и только если
    /// хоть один документ сегмента вектор принёс.
    pub vectors: Option<crate::vector::Vectors>,
    /// Хранит ли поле позиции слов. Объявляется `имя:text:nopos`.
    ///
    /// Признак нужен именно у поля, а не выводится из пустого блока позиций:
    /// пустой блок бывает и у поля с позициями — например, когда все его слова
    /// стоят на нулевой позиции, — и путать эти два случая значило бы читать на
    /// месте позиций соседние байты.
    pub positioned: bool,
    /// Объявлено ли поле хранимым. Отличается от `store.is_some()` тем, что
    /// говорит про **намерение**, а не про наличие файлов: поле, объявленное
    /// хранимым, но пустое во всём сегменте, файлов не получит.
    pub stored: bool,
    /// Наименьшее и наибольшее значение числового поля в **этом** сегменте.
    ///
    /// `None` — границ нет: поле нечисловое, значений в сегменте не оказалось
    /// или сегмент записан до появления этих столбцов. Во всех трёх случаях
    /// отбор обязан читать сегмент, а не пропускать: «границ не знаем» и
    /// «границы не подходят» — разные вещи, и путать их значит терять документы.
    pub bounds: Option<(i64, i64)>,
    /// Ищется ли по полю. `false` — объявлено `noindex`: содержимое лежит и
    /// отдаётся, но ни списка, ни колонки у поля нет, и запрос по нему
    /// обязан **отказать**, а не вернуть пустоту.
    ///
    /// Разница несущая. Пустая выдача — это ответ «ничего не нашлось», и
    /// клиент, получив её, ищет ошибку в данных, а не в схеме.
    pub searched: bool,
    /// Во сколько раз средний размах блока меньше общего. Считается при сборке.
    ///
    /// Выше [`crate::column::SPREAD_USELESS`] — пропуск по границам блока не
    /// отсекает ничего, и полю нужна надстройка. Ниже — не нужна.
    pub spread: f64,
    pub boost: f64,
    /// Средняя длина **этого сегмента**. Годится только внутри него.
    pub avgdl: f64,
    /// Целая сумма длин поля по сегменту, см. [`crate::norms::FIXED`].
    ///
    /// Складывается точно и в любом порядке, поэтому средняя длина по всему
    /// составу выходит из суммы сумм и не зависит от того, как приём нарезал
    /// корпус. Сама `avgdl` для этого не годится: средние не складываются.
    pub len_fixed: u64,
    /// Документы с хотя бы одним индексируемым токеном корневого Text-поля.
    /// None — legacy/другой scoring профиль, не ноль документов.
    pub scoring_docs: Option<u64>,
    /// Наибольший уровень длины, встреченный в поле.
    ///
    /// Ограничивает подъём потолков: без него пришлось бы считать, что документ
    /// может быть предельной длины, и запас выходил бы во много раз больше
    /// нужного.
    pub lmax: u8,
    /// Где в `norms.bin` начинается полоса этого поля.
    pub norms_at: usize,
    /// Номер полосы длин в `norms.bin`.
    pub norms_band: u32,
    /// Устойчивый номер поля из реестра ([`crate::schema`]).
    pub fid: u32,
    /// Основа имён файлов этого поля в каталоге сегмента.
    ///
    /// Отличается от `name` у путей с точкой: `media.duration` именем файла
    /// стать не может, и основой ему служит `f{fid}` — см.
    /// [`crate::schema::FieldDef::stem`].
    pub stem: String,
    /// Как поле уложено в **этом** сегменте. Выбирается по данным на сбросе.
    pub layout: crate::column::Layout,
    /// Как хранится признак наличия значения в этом сегменте.
    pub presence: crate::column::Presence,
    /// Сколько значений у поля в этом сегменте.
    ///
    /// Разреженной раскладке это число задаёт количество блоков: у неё их
    /// столько, сколько значений, а не сколько документов.
    pub values: usize,
    /// Номер группы. Ноль — корень: одно значение на документ.
    pub group: u32,
    /// Множитель длины на каждый из 256 уровней.
    ///
    /// Длина документа хранится байтом, значит и множителей ровно 256 — считать
    /// их заново на каждый оценённый документ незачем. А считалось именно так:
    /// деление и обращение к таблице длин на **каждый** документ каждого
    /// курсора. Здесь два килобайта на поле закрывают вопрос: скоринг
    /// становится одним обращением в таблицу и одним умножением на вес.
    ///
    /// Таблица **делится** между полями с одной средней длиной. Своя у каждого
    /// стоила четыре килобайта на поле на сегмент: при семидесяти семи полях и
    /// сотне сегментов это тридцать мегабайт памяти процесса, при тысяче путей —
    /// четыреста. И платились они в основном за числовые поля, которые не
    /// оцениваются никогда: у всех у них средняя длина единица, и таблица одна
    /// на всех.
    pub nu_by_level: std::sync::Arc<[f64; 256]>,
    /// Длинная часть знаменателя BM25 по уровню длины.
    ///
    /// Нужна там, где частота больше единицы: вклад это `tf/(tf + d)`, и при
    /// `tf = 1` он равен `nu`. Две таблицы вместо одной — четыре килобайта,
    /// зато частый случай остаётся одним обращением и одним умножением.
    /// Делится так же, как и первая.
    pub d_by_level: std::sync::Arc<[f64; 256]>,
}

impl Field {
    pub fn numeric_values(&self, unit: u32) -> crate::multivalue::NumericValues<'_> {
        match self.multi_column.as_ref().and_then(|c| c.get(unit)) {
            Some(values) => crate::multivalue::NumericValues::Multi(values),
            None => crate::multivalue::NumericValues::Scalar(
                self.column.as_ref().and_then(|c| c.get(unit)).into_iter(),
            ),
        }
    }

    pub fn in_numeric_range(
        &self,
        cache: &mut crate::column::BlockCache,
        unit: u32,
        lo: i64,
        hi: i64,
        guard: Option<&crate::work::Guard>,
    ) -> bool {
        if let Some(values) = self.multi_column.as_ref().and_then(|c| c.get(unit)) {
            for (i, value) in values.enumerate() {
                if i.is_multiple_of(64) && guard.is_some_and(|g| !g.check()) {
                    return false;
                }
                if lo <= value && value <= hi {
                    return true;
                }
            }
            return false;
        }
        // Полный диапазон проверяет наличие, а не значение. Не декодируем
        // packed payload ради exists; multivalue выше сохраняет свой договор.
        if lo == i64::MIN && hi == i64::MAX {
            return self
                .column
                .as_ref()
                .is_some_and(|column| (unit as usize) < column.docs() && column.has(unit));
        }
        self.column
            .as_ref()
            .and_then(|c| c.get_with(cache, unit))
            .is_some_and(|v| lo <= v && v <= hi)
    }

    pub fn sort_value(
        &self,
        unit: u32,
        descending: bool,
        guard: Option<&crate::work::Guard>,
    ) -> Option<i64> {
        if let Some(values) = self.multi_column.as_ref().and_then(|c| c.get(unit)) {
            let mut best: Option<i64> = None;
            for (i, value) in values.enumerate() {
                if i.is_multiple_of(64) && guard.is_some_and(|g| !g.check()) {
                    return None;
                }
                best =
                    Some(
                        best.map_or(
                            value,
                            |b| if descending { b.max(value) } else { b.min(value) },
                        ),
                    );
            }
            return best;
        }
        self.column.as_ref().and_then(|c| c.get(unit))
    }
}

pub struct Index {
    /// Каталог сегмента. Нужен тому, кто читает файлы, не входящие в поиск, —
    /// например слиянию, которому надо перенести идентификаторы.
    pub dir: String,
    /// Откуда сегмент берёт куски: файл на кусок либо один контейнер.
    ///
    /// Держится **после** открытия, а не только на время его: `IdMap` открывает
    /// `ids.bin` по требованию, а слияние читает у источника хранимое и
    /// идентификаторы. Открывать их по имени каталога значило бы завести вторую
    /// область на тот же `seg.dat` — то есть отдать ровно то, ради чего
    /// контейнер и заведён.
    pub src: std::sync::Arc<crate::container::SegmentSource>,
    /// Опознание заголовка на момент открытия: узел и время правки.
    ///
    /// Нужно ровно одному месту — [`crate::segments::Segments::reopen`], которое
    /// переиспользует уже открытый сегмент вместо повторного чтения. Имени
    /// каталога для этого мало: каталог могли снести и завести заново под тем же
    /// именем, и тогда старые отображения продолжают показывать **прежнее**
    /// содержимое отвязанных inode. Поиск отвечал бы из сегмента, которого на
    /// диске уже нет, и ни одна проверка этого бы не заметила.
    ///
    /// Пара «inode и время правки», а не одно: номер узла файловая система
    /// переиспользует, и на быстром цикле «снесли — создали» он совпадает.
    pub head_id: (u64, i64),
    /// Размер сегмента в байтах, снятый **один раз** при открытии.
    ///
    /// ## Почему это можно запомнить
    ///
    /// Сегмент неизменяем: после записи ни один его файл не растёт и не
    /// урезается. Единственное, что в нём меняется, — карта живых, а гашение
    /// правит биты на месте, и длина карты остаётся прежней. Значит записанное
    /// здесь число не устаревает, пока жив сам объект.
    ///
    /// ## Почему это нельзя считать на заходе обслуживания
    ///
    /// Политика укрупнения меряет окно байтами, а зовётся каждые две секунды и
    /// целиком под замком состава. Считать размер там значило бы обходить
    /// каталог каждого сегмента каждый заход: при десяти тысячах сегментов это
    /// десять тысяч обходов в две секунды — ровно та работа, ради снятия
    /// которой заход и перевели на уже открытые сегменты.
    ///
    /// Открытие же происходит только у **изменившихся**:
    /// [`crate::segments::Segments::reopen`] переиспользует прежний объект,
    /// когда опознание заголовка совпало. На установившемся индексе это ноль
    /// работы за заход, а не «один обход вместо многих».
    pub bytes: crate::sums::Bytes,
    /// Подпись схемы: хеш устойчивых номеров полей в порядке объявления.
    ///
    /// Считается тут же, при открытии, и по той же причине: планировщику она
    /// нужна на каждом шаге каждого окна, а зависит только от заголовка. См.
    /// [`crate::merge::schema_sig`].
    pub schema_sig: u64,
    pub post: Region,
    pub fields: Vec<Field>,
    pub docs: usize,
    /// Полосы арности по номеру группы. Нулевая — корневая, файлов не имеет.
    pub slots: Vec<crate::slots::Slots>,
    /// Путь массива по номеру группы. У нулевой пусто — она корень документа.
    ///
    /// Прежде путь читался из заголовка и тут же выбрасывался, а запрос
    /// восстанавливал его отрезанием хвоста у **имени поля**. Точка в имени
    /// запрещена, поэтому путь всегда получался пустым, и всякая группа
    /// подменялась первой попавшейся — молча. Путь обязан доезжать оттуда, где
    /// он записан, а не выводиться из соседних данных.
    pub group_paths: Vec<String>,
    /// Живые документы: обновлённые и удалённые гасятся здесь, а не
    /// перестройкой списков. Списки при этом остаются надмножеством, и это
    /// нормально — лишний кандидат стоит проверки, а не ошибки.
    /// `None` — файла карты нет, а значит живы все.
    ///
    /// Проверка живости — случайное обращение в битовую карту на **каждый**
    /// рассмотренный документ, то есть промах кеша там, где всё остальное уже
    /// сведено к паре обращений. Отсутствие карты снимает и его: отвечать
    /// нечем, ответ известен заранее.
    pub live: Option<crate::live::Live>,
    /// Последняя immutable-копия live bitmap этого сегмента. Поколение берётся
    /// из разделяемой печати `live.bin`; неизменившиеся сегменты делят снимок
    /// между всеми параллельными запросами.
    live_snapshot_cache: std::sync::Mutex<Option<(u64, std::sync::Arc<crate::live::Snapshot>)>>,
    /// Метаданные блоков: на блок последний номер, потолок множителя и длина.
    blocks: Region,
    /// Позиции слов и указатель на них по блокам. Пусто — сегмент без позиций.
    pos: Region,
    pos_idx: Region,
    /// Нормы всех полей подряд: по байту на документ на каждое поле.
    norms: Region,
    /// На список: число документов и номер первого блока. Шестая раскладка.
    terms: Region,
    /// Метаданные слов седьмой раскладки: записи переменной длины с опорами.
    terms7: Option<crate::layout::Terms>,
    /// Версия раскладки этого сегмента. Обе читаются, пишется новая.
    pub layout: u32,
    /// Сколько значений в куске позиций. Ноль — весь прогон одним куском.
    ///
    /// Число сегмента, а не всего движка: чем сильнее разброс длин документов,
    /// тем мельче кусок окупается. Читатель работает с любым, писатель ставит
    /// [`POSBLOCK`]. Смотреть, какой подходит корпусу, — `inspect --positions`.
    pub posblock: usize,
    /// Наибольшая частота среди слов, оставшихся **без позиций**.
    ///
    /// Ноль — позиции есть у всех, и так собраны все сегменты до этой строки.
    ///
    /// Это не настройка, а **наблюдение**, и записано оно именно в таком виде
    /// намеренно. Порог, которым писатель руководствовался, на диске бесполезен:
    /// слияние меняет `df` слова, и слово, законно оставшееся без позиций при
    /// `df = 3 000` в каждом из восьми сегментов, окажется в слитом с `df =
    /// 24 000` — записанный порог перестанет быть правдой в тот же миг.
    /// Наибольшая же наблюдённая частота остаётся правдой у любого писателя.
    ///
    /// И она полезнее: это ровно та величина, которая нужна планировщику.
    /// Фраза, у которой все слова с позициями, идёт позиционным путём. Фраза, у
    /// которой хоть одно без, проверяется по тексту — и кандидатов у неё не
    /// больше `posmin`, потому что кандидатов не больше `df` самого редкого
    /// слова. Третьего случая нет, поэтому граница здесь устройственная.
    ///
    /// Слово без позиций с `df > posmin` — противоречие; `check` его называет.
    pub posmin: u32,
    pub nterms: usize,
    pub dict: Dict,
    /// Отрицательный фильтр по словам всего сегмента, без привязки к полю.
    ///
    /// `None` сохраняет чтение старых сегментов. В таком случае планировщик
    /// обязан считать сегмент кандидатом: отсутствие фильтра не означает
    /// отсутствие слова.
    pub term_filter: Option<crate::bloom::Bloom>,
    /// Идентификатор — в номер документа. Нужно удалению и обновлению.
    pub idmap: crate::ids::IdMap,
    /// Номер последней записи журнала, вошедшей в этот сегмент.
    ///
    /// По нему восстановление понимает, что уже на диске: переигрывать надо
    /// только то, что больше.
    pub seq: u64,
}

/// Версия раскладки, которой пишутся новые сегменты.
///
/// Readers 6–9 сохранены для неизменяемых старых сегментов и экспорта source.
/// Раскладка 10 хранит числовые массивы отдельно от scalar column. Старые
/// неполные numeric columns требуют явной миграции: обычный merge не вправе
/// назвать их раскладкой 10, оставив потерянные значения невосстановленными.
///
/// Восьмая отличается от седьмой одним: номер поля в словаре хранится varint, а
/// не байтом. Байт держал потолок в **256 полей** — на плоской схеме незаметно,
/// на вложенной упирается сразу (у Elasticsearch умолчание — тысяча полей на
/// индекс). Места это не стоит: номер пишется только при смене поля, а у
/// номеров до 128 varint и байт побайтово совпадают.
///
/// ## Почему девятая, если у сегмента с одним словарём не изменился ни байт
///
/// У хранилища поля появилась **таблица словарей** `<поле>.sdix`: укрупнение
/// переносит куски `.sbin` байт в байт, а словари источников складывает в
/// `.sdic` подряд. Пока словарь один, таблицы нет и файлы прежние — казалось бы,
/// бумп не нужен.
///
/// Нужен, и не ради бухгалтерии. Записи в `.sdic` самоописательны, а их разбор
/// идёт от начала файла и **не проверяет**, что файл на этом кончился. Старый
/// двоичный файл, увидев многословарный `.sdic`, молча взял бы запись 0 и стал
/// бы распаковывать ею куски словарей с первого по последний: чаще это отказ,
/// иногда — правдоподобный мусор нужной длины, то есть содержимое документа,
/// которого не было. Бумп превращает это в отказ на открытии, а он единственный
/// здесь честен.
///
/// [`LAYOUT_MIN`] при этом не двинулся: сегмент без таблицы читается той же
/// одной веткой (`K = 1`, отрезок кусков начинается с нуля), и переписывать
/// собранное не нужно.
// Раскладка 10 добавляет numeric multivalue. Старый reader обязан отказать,
// а не молча прочесть только scalar часть и потерять range/aggregation match.
/// Раскладка 13 добавляет явную sparse-адресацию векторных кодов. Старые
/// reader-ы должны отвергать её целиком, а не принимать новое `.qm` за
/// отсутствующее поле. Плотный legacy-кодек остаётся допустимым в новой
/// раскладке; новый reader продолжает читать старые сегменты без перезаписи.
pub const LAYOUT: u32 = 13;

/// Самая старая раскладка, которую этот движок ещё читает.
pub const LAYOUT_MIN: u32 = 6;

/// Байт на блок: последний номер `u32`, потолок `f32`, длина `u16`.
pub const BLOCK_META: usize = 10;

/// Сколько значений в куске позиций у новых сегментов.
pub const POSBLOCK: usize = 32;

/// Байт на список в шестой раскладке: число документов, номер первого блока,
/// смещение его начала, потолок. В седьмой запись переменной длины — см.
/// [`crate::layout`].
pub const TERM_META: usize = 16;

/// Всё о списке слова, разобранное за один раз.
#[derive(Clone, Copy, Debug, Default)]
pub struct Term {
    pub df: u32,
    /// Потолок вклада списка целиком.
    pub max: f64,
    /// Смещение первого куска списка в `postings.bin`.
    pub post: usize,
    /// Смещение куска позиций. Осмыслено там, где своих блоков нет.
    pub pos: usize,
    /// Номер первого блока в `blocks.bin`. Осмыслен при [`Term::meta`].
    pub first: usize,
    /// Сколько блоков у списка. У непустого не меньше одного.
    pub blocks: usize,
    /// Есть ли у списка записи в `blocks.bin` и `pos.idx`.
    ///
    /// У короткого списка седьмой раскладки их нет: он целиком помещается в один
    /// блок, а метаданные такого блока — точная копия метаданных слова.
    pub meta: bool,
    /// Все частоты списка единичны: полосы частот в `postings.bin` нет.
    pub tf_all_one: bool,
    /// Хранит ли **это слово** свои позиции.
    ///
    /// Признак слова, а не поля: при `posmin > 0` позиции есть только у частых.
    /// У шестой раскладки всегда истина — там иначе не бывало.
    ///
    /// Ложь здесь не значит «фразы нет». Она значит «порядок слов надо взять из
    /// текста», и путать эти два случая нельзя: первый молча вернул бы пустоту.
    pub positioned: bool,
    /// `df == 1` со всем содержимым внутри записи.
    pub one: Option<crate::layout::Rec>,
    /// Длина куска списка и куска позиций. Известны только седьмой раскладке —
    /// у шестой их выводят из длин блоков и разностей указателей. Нужны разбору
    /// и проверке, поиску — нет.
    pub post_len: u32,
    pub pos_len: u32,
    /// Сколько байт заняла запись слова. У шестой раскладки постоянна.
    pub rec_len: u32,
}

impl Index {
    /// Уровень длины документа по полю.
    #[inline(always)]
    pub fn level(&self, fld: usize, doc: u32) -> u8 {
        self.norms.u8_at(self.fields[fld].norms_at + doc as usize)
    }

    /// Последний документ блока.
    #[inline(always)]
    pub fn b_last(&self, i: usize) -> u32 {
        self.blocks.u32_at(i * BLOCK_META)
    }

    /// Потолок множителя длины по блоку.
    #[inline(always)]
    pub fn b_max(&self, i: usize) -> f32 {
        f32::from_bits(self.blocks.u32_at(i * BLOCK_META + 4))
    }

    /// Длина блока в байтах вместе с байтом ширины.
    ///
    /// Не больше 513: байт ширины плюс сто двадцать восемь значений по тридцать
    /// два бита. Отсюда и два байта вместо четырёх, которых требовало бы
    /// смещение от начала файла.
    #[inline(always)]
    pub fn b_len(&self, i: usize) -> usize {
        self.blocks.u16_at(i * BLOCK_META + 8) as usize
    }

    /// Где в `pos.bin` начинаются позиции блока.
    #[inline(always)]
    pub fn p_at(&self, i: usize) -> usize {
        self.pos_idx.u32_at(i * 4) as usize
    }

    /// Срез файла позиций.
    #[inline(always)]
    pub fn pos_slice(&self, off: usize, n: usize) -> &[u8] {
        self.pos.slice(off, n)
    }

    /// Есть ли в сегменте позиции вообще.
    ///
    /// У седьмой раскладки об этом нельзя судить по `pos.idx`: указателя там нет
    /// ни у короткого списка, ни у одиночного слова, чьё единственное вхождение
    /// лежит прямо в метаданных. Сегмент, где все слова редкие, имел бы пустой
    /// `pos.idx` и полный набор позиций — и фраза по нему перестала бы искаться.
    pub fn has_positions(&self) -> bool {
        if self.layout >= 7 {
            self.fields.iter().any(|f| f.positioned)
        } else {
            self.pos_idx.len_bytes() >= 4
        }
    }

    /// Число документов в списке.
    ///
    /// Единственная величина, которую спрашивают **не разбирая список целиком**:
    /// по ней выбирается опорное слово запроса и считается обратная частота. У
    /// седьмой раскладки она всё равно достаётся проходом по опорной группе, но
    /// проход недлинный и лежит подряд.
    #[inline]
    pub fn t_df(&self, list: usize) -> u32 {
        match self.terms7.as_ref() {
            Some(t7) => t7.at(list).map_or(0, |l| l.rec.df),
            None => self.terms.u32_at(list * TERM_META),
        }
    }

    /// Сколько всего блоков в сегменте.
    pub fn blocks_count(&self) -> usize {
        self.blocks.len_bytes() / BLOCK_META
    }

    /// Длина файла позиций. Нужна осмотру: объём позиций последнего блока
    /// считается от неё, а указателя за ним уже нет.
    pub fn pos_len(&self) -> usize {
        self.pos.len_bytes()
    }

    /// Затягивает в кеш страниц метаданные — и только их.
    ///
    /// Отдаёт число затянутых байт.
    pub fn warm(&self) -> usize {
        self.warm_within(&mut crate::mmap::WarmBudget::unlimited())
    }

    /// То же под бюджетом и **в порядке важности**.
    ///
    /// ## Зачем порядок
    ///
    /// Прогрев без бюджета на большом индексе вытесняет из кеша страниц всё
    /// подряд, включая то, что нужнее прогретого. Значит греть надо не «сколько
    /// влезет», а сколько отведено, — и тогда становится важно, что именно
    /// попадёт в отведённое.
    ///
    /// Порядок здесь — порядок обращения запроса: словарь разрешает слово,
    /// таблица терминов находит его список, потолки блоков решают, читать ли
    /// его, нормы дают вес. Колонки идут последними: они нужны отбору и
    /// сортировке, а не каждому запросу.
    ///
    /// ## Чего порядок не обещает
    ///
    /// Бюджет проверяется **между** частями, а не внутри: часть греется
    /// целиком или не греется вовсе. Иначе пришлось бы резать отображение на
    /// куски и греть их поштучно, а это ровно то поштучное касание страниц, от
    /// которого ушли в пользу совета ядру.
    pub fn warm_within(&self, left: &mut crate::mmap::WarmBudget) -> usize {
        let mut done = 0usize;
        if let Some(filter) = self.term_filter.as_ref() {
            if !left.take(filter.bytes()) {
                return done;
            }
            done += filter.warm();
        }
        if !left.take(self.dict.bytes()) {
            return done;
        }
        done += self.dict.warm();
        for part in [&self.terms, &self.blocks, &self.norms] {
            if !left.take(part.len_bytes()) {
                return done;
            }
            done += part.warm();
        }
        if let Some(t) = self.terms7.as_ref() {
            if !left.take(t.bytes()) {
                return done;
            }
            done += t.warm();
        }
        // Колонки греются вместе с метаданными поиска, а не с обратным
        // отображением: отбор — часть запроса, а не приёма.
        for c in self.fields.iter().filter_map(|f| f.column.as_ref()) {
            if !left.take(c.bytes()) {
                return done;
            }
            done += c.warm();
        }
        done
    }

    /// Затягивает то, что нужно приёму: обратное отображение и фильтр.
    pub fn warm_ids(&self) -> usize {
        self.idmap.warm()
    }

    /// Множитель длины документа по полю. Верен при частоте, равной единице.
    #[inline(always)]
    pub fn nu(&self, fld: usize, doc: u32) -> f64 {
        self.fields[fld].nu_by_level[self.level(fld, doc) as usize]
    }

    /// Вклад документа при заданной частоте: `tf/(tf + d)`.
    ///
    /// Единица выделена в отдельную ветку не ради красоты: такова подавляющая
    /// часть постингов, и на ней вклад берётся из готовой таблицы одним
    /// обращением, без деления.
    #[inline(always)]
    pub fn sat(&self, fld: usize, doc: u32, tf: u32) -> f64 {
        self.sat_in(fld, doc, tf, None)
    }

    /// То же, но по таблицам, посчитанным для **всего состава**.
    ///
    /// `None` — считать местными таблицами сегмента, как считалось всегда: так
    /// работают самопроверки раскладки, слияние и одиночный сегмент.
    #[inline(always)]
    pub fn sat_in(&self, fld: usize, doc: u32, tf: u32, sc: Option<&FieldScore>) -> f64 {
        let f = &self.fields[fld];
        // Разреженный вектор: частота — это код веса, вклад — само значение.
        // Ни длины документа, ни насыщения здесь нет и быть не должно.
        if f.kind.dot() {
            return f64::from(crate::sparse::decode(tf.min(255) as u8));
        }
        let q = self.level(fld, doc) as usize;
        let (nu, d) = match sc {
            Some(s) => (&s.nu, &s.d),
            None => (&f.nu_by_level, &f.d_by_level),
        };
        if tf <= 1 {
            nu[q]
        } else {
            crate::norms::sat(tf, d[q])
        }
    }

    /// Потолок множителя длины: самый короткий возможный документ.
    #[inline(always)]
    pub fn nu_max(&self, fld: usize) -> f64 {
        norms::nu_max(self.fields[fld].avgdl)
    }

    /// Обратная частота документа по статистике **этого** сегмента.
    ///
    /// Годится там, где сегмент один. Многосегментному запросу нужна общая — см.
    /// `Segments::plan`: числа из разных сегментов сравниваются между собой, и
    /// считать их по разным `N` значит поставить выдачу в зависимость от того,
    /// как приём нарезал корпус.
    pub fn idf(&self, df: u32) -> f64 {
        idf_of(self.docs as u64, u64::from(df))
    }

    #[inline(always)]
    pub fn is_live(&self, doc: u32) -> bool {
        match self.live.as_ref() {
            None => true,
            Some(l) => l.is_live(doc),
        }
    }

    /// Все ли документы сегмента живы.
    #[inline(always)]
    pub fn all_live(&self) -> bool {
        self.live.as_ref().is_none_or(|l| !l.any_dead())
    }

    /// Сколько документов погашено. Величина живая: гашение видно сразу.
    pub fn dead(&self) -> usize {
        self.live.as_ref().map_or(0, |l| l.dead())
    }

    /// Снимает копию карты живых. Разбор — у [`crate::live::Snapshot`].
    pub fn live_copy(&self) -> crate::live::Snapshot {
        match self.live.as_ref() {
            None => crate::live::Snapshot::all(self.docs),
            Some(l) => l.snapshot(),
        }
    }

    /// Гасит документ. `true` — он был жив.
    pub fn kill(&self, doc: u32) -> bool {
        self.live.as_ref().is_some_and(|l| l.kill(doc))
    }

    /// Уносит правки карты живых на диск.
    pub fn sync_live(&self) -> std::io::Result<()> {
        match self.live.as_ref() {
            None => Ok(()),
            Some(l) => l.sync(),
        }
    }

    /// Сколько байт занимает карта живых.
    pub fn live_bytes(&self) -> usize {
        self.live.as_ref().map_or(0, |l| l.bytes())
    }

    /// Байты, которыми владеет memory source этого сегмента. На disk source
    /// возвращается ноль: его page cache учитывается cgroup snapshot, а не
    /// повторно прибавляется к heap admission.
    pub fn memory_source_bytes(&self) -> usize {
        self.src.memory_bytes()
    }

    /// Вес слова в списке: вес поля, обратная частота и насыщение.
    #[inline(always)]
    pub fn weight(&self, field: usize, df: u32) -> f64 {
        let f = &self.fields[field];
        f.boost
            * idf_of(f.scoring_docs.unwrap_or(self.docs as u64), u64::from(df))
            * (norms::K1 + 1.0)
    }

    /// Разбирает список слова. Одна точка входа на обе раскладки.
    ///
    /// Номер поля нужен седьмой: потолок там хранится не числом, а **доводом** —
    /// парой «уровень длины, частота», — и восстанавливается таблицей поля. Это
    /// не экономия трёх байт: восстановленное значение совпадает с тем, что
    /// посчитает скоринг, точно, потому что считается той же формулой.
    pub fn term(&self, list: usize, fld: usize) -> Term {
        match self.terms7.as_ref() {
            Some(t7) => self.term7(t7, list, fld),
            None => self.term6(list),
        }
    }

    fn term6(&self, list: usize) -> Term {
        let df = self.terms.u32_at(list * TERM_META);
        Term {
            df,
            max: f64::from(f32::from_bits(self.terms.u32_at(list * TERM_META + 12))),
            post: self.terms.u32_at(list * TERM_META + 8) as usize,
            pos: 0,
            first: self.terms.u32_at(list * TERM_META + 4) as usize,
            blocks: blocks_of(df) as usize,
            meta: true,
            tf_all_one: false,
            positioned: true,
            one: None,
            post_len: 0,
            pos_len: 0,
            rec_len: TERM_META as u32,
        }
    }

    fn term7(&self, t7: &crate::layout::Terms, list: usize, fld: usize) -> Term {
        // Негодная запись сюда не доходит: [`load`] проходит все и отказывается
        // открывать сегмент, где хоть одна не разобралась. Ноль здесь остаётся
        // только на невозможном пути, и он честнее выдумки.
        let Some(loc) = t7.at(list) else { return Term::default() };
        let r = loc.rec;
        let long = r.df as usize > crate::bits::BLOCK;
        let d = self.fields.get(fld).map(|f| f.d_by_level.as_ref());
        let level = |q: u8| d.map_or(0.0, |t| t[q as usize]);
        // У разреженного вектора потолок — сам наибольший вес: длины документа
        // здесь нет как понятия. Считать его формулой BM25 значило бы получить
        // число НИЖЕ настоящего вклада, а потолок ниже вклада приводит к потере
        // документов: отсечение MaxScore вправе выбросить список, чей потолок
        // не дотягивает до порога.
        let dot = self.fields.get(fld).is_some_and(|f| f.kind.dot());
        let (max, one) = if r.df == 1 {
            // У одиночного слова потолок выводится из его единственного
            // документа: уровень длины лежит в нормах, частота — в записи.
            let q = self.level(fld, r.doc);
            let m = if dot {
                f64::from(crate::sparse::decode(r.tf.min(255) as u8))
            } else {
                crate::norms::sat(r.tf, level(q))
            };
            (m, Some(r))
        } else if dot {
            (f64::from(crate::sparse::decode(r.tfmax.min(255) as u8)), None)
        } else {
            (crate::norms::sat(r.tfmax, level(r.qmax)), None)
        };
        Term {
            df: r.df,
            max,
            post: loc.post,
            pos: loc.pos,
            first: loc.block,
            blocks: (r.df as usize).div_ceil(crate::bits::BLOCK),
            meta: long,
            tf_all_one: r.tf_all_one,
            positioned: r.positioned,
            one,
            post_len: r.post_len,
            pos_len: r.pos_len,
            rec_len: loc.len,
        }
    }

    /// Смещения блоков списка: накопленные суммы длин от начала списка.
    ///
    /// Нужны тому, кто ходит по блокам **не по порядку**. Обычный обход
    /// накапливает смещение сам и в этом не нуждается; обход по убыванию
    /// потолка — нуждается, потому что прыгает.
    pub fn block_offsets(&self, t: &Term, out: &mut Vec<usize>) {
        out.clear();
        if !t.meta {
            // Один блок: смещение у него одно, и складывать нечего. У одиночного
            // слова оно не значит ничего — читатель до файла списков не дойдёт, —
            // но место в ряду занимает, чтобы номер блока оставался номером.
            if t.df > 0 {
                out.push(t.post);
            }
            return;
        }
        let mut at = t.post;
        for i in 0..t.blocks {
            out.push(at);
            at += self.b_len(t.first + i);
        }
    }

    /// Потолок блока `b` — битами `f32`, как их сравнивает куча.
    ///
    /// У короткого списка блок один, и его потолок — потолок списка: максимум по
    /// единственному блоку и есть максимум по списку. Отдельного числа для него
    /// не хранится, и это не приближение, а тождество.
    #[inline(always)]
    pub fn block_max_bits(&self, t: &Term, b: usize) -> u32 {
        if t.meta {
            self.blocks.u32_at((t.first + b) * BLOCK_META + 4)
        } else {
            crate::norms::up_f32(t.max).to_bits()
        }
    }

    /// Распаковывает блок `blk` списка в `out`. Отдаёт число значений.
    ///
    /// Отдельно от курсора: курсор идёт подряд и держит состояние, а здесь
    /// нужен произвольный блок и ничего кроме него.
    pub fn read_block(&self, t: &Term, blk: usize, off: usize, out: &mut [u32]) -> usize {
        self.read_block_tf(t, blk, off, out, None)
    }

    /// То же, но заодно распаковывает частоты, если они нужны.
    ///
    /// Частоты лежат **следом за номерами в том же блоке**, своей упаковкой со
    /// своей шириной. Так их можно не трогать вовсе, когда блок пропускается по
    /// потолку, и распаковать одним проходом, когда он читается.
    ///
    /// У списка, где все частоты единичны, полосы частот нет вовсе — седьмая
    /// раскладка её не пишет. Это не край, а самый частый случай: полоса из
    /// одних нулей занимала байт ширины на блок.
    pub fn read_block_tf(
        &self,
        t: &Term,
        blk: usize,
        off: usize,
        out: &mut [u32],
        tfs: Option<&mut [u32]>,
    ) -> usize {
        // Одиночное слово лежит целиком в своей записи: в файле списков его нет.
        if let Some(r) = t.one {
            if blk > 0 {
                return 0;
            }
            out[0] = r.doc;
            if let Some(tfs) = tfs {
                tfs[0] = r.tf;
            }
            return 1;
        }
        let df = t.df as usize;
        let n = df.saturating_sub(blk * crate::bits::BLOCK).min(crate::bits::BLOCK);
        if n == 0 {
            return 0;
        }
        let width = crate::bits::width_of(self.post.slice(off, 1));
        let src = self.post.slice(off + 1, crate::bits::window_len(n, width));
        let from = if blk == 0 { 0 } else { self.b_last(t.first + blk - 1) };
        crate::bits::unpack_deltas(src, n, width, from, out);
        if let Some(tfs) = tfs {
            if t.tf_all_one {
                tfs[..n].fill(1);
                return n;
            }
            // `packed_len` уже включает байт ширины — прибавлять его ещё раз
            // значило бы читать частоты со сдвигом в байт.
            let fat = off + crate::bits::packed_len(n, width);
            let fw = crate::bits::width_of(self.post.slice(fat, 1));
            let fsrc = self.post.slice(fat + 1, crate::bits::window_len(n, fw));
            crate::bits::unpack_values(fsrc, n, fw, tfs);
            for t in tfs.iter_mut().take(n) {
                *t += 1;
            }
        }
        n
    }

    /// Курсор по списку с готовым весом.
    pub fn cursor(&self, list: u32, fld: usize, w: f64) -> Cursor<'_> {
        Cursor::new(self, list, fld, w, None)
    }

    /// Курсор, считающий по общей статистике состава.
    pub fn cursor_in(&self, list: u32, fld: usize, w: f64, sc: Option<&FieldScore>) -> Cursor<'_> {
        Cursor::new(self, list, fld, w, sc.cloned())
    }
}

/// Сколько слов ушло в мусор при разборе заголовка — для внятной ошибки.
fn bad(msg: &str) -> std::io::Error {
    std::io::Error::new(std::io::ErrorKind::InvalidData, msg.to_string())
}

/// Заголовок сегмента: поля, средние длины, число документов.
///
/// Формат намеренно плоский и разбирается без внешних библиотек: строка на
/// поле, значения через табуляцию. Его пишет индексатор, читает движок, и
/// человек может открыть его глазами — на разборе индекса это окупается.
/// Группа заголовка: путь массива и то, как уложена его полоса арности.
#[derive(Clone, Debug)]
pub struct GroupHead {
    pub id: u32,
    /// Путь массива в документе. Пусто — корневая группа.
    pub path: String,
    pub kind: crate::slots::Kind,
    /// Сколько всего слотов у группы в этом сегменте.
    pub units: usize,
}

pub struct Head {
    pub docs: usize,
    pub blocks: usize,
    pub terms: usize,
    pub layout: u32,
    /// Номер последней записи журнала, вошедшей в сегмент.
    pub seq: u64,
    /// Значений в куске позиций. Ноль — прогон одним куском, как до раздела 49.
    pub posblock: usize,
    /// Наибольшая частота среди слов без позиций. Ноль — позиции есть у всех.
    pub posmin: u32,
    pub fields: Vec<Field>,
    pub groups: Vec<GroupHead>,
    /// Длина контейнера `seg.dat`. `None` — сегмент рассыпан по файлам.
    ///
    /// Признаком готовности сегмента остаётся сам `head.tsv`, а не наличие
    /// контейнера: недописанный `seg.dat` без этой строки просто невидим —
    /// сирота, о которой `check` скажет «лишний файл». Заведи признаком его — и
    /// на новое правило пришлось бы разом согласиться `load`,
    /// `Segments::reopen`, `check` и `manifest::valid_segment_dir`.
    pub container: Option<u64>,
}

/// Узел и время правки `head.tsv` — опознание содержимого каталога сегмента.
///
/// Заголовок пишется **последним** и больше не меняется, поэтому он и служит
/// признаком: совпал — каталог тот же самый, а не тёзка. Нули означают «не
/// опозналось» и никогда не совпадут с настоящим ответом, так что
/// переиспользование в этом случае просто не случится.
pub fn head_ident(dir: &str) -> (u64, i64) {
    use std::os::unix::fs::MetadataExt;
    std::fs::symlink_metadata(format!("{dir}/head.tsv"))
        .map(|m| (m.ino(), m.mtime_nsec() ^ (m.mtime() << 24)))
        .unwrap_or((0, 0))
}

pub fn read_head(dir: &str) -> std::io::Result<Head> {
    let path = format!("{dir}/head.tsv");
    let bytes =
        crate::fs::read_regular_limited(std::path::Path::new(&path), 16 * 1024 * 1024, false)?;
    parse_head(&bytes, &path)
}

/// Заголовок сегмента, собранного в память: он лежит там таким же куском.
///
/// Отдельного разбора у него нет и быть не может — разойдись эти два, и один и
/// тот же заголовок означал бы у диска и у памяти разное.
pub fn head_of(src: &crate::container::SegmentSource) -> std::io::Result<Head> {
    let piece = src.open("head.tsv")?;
    parse_head(piece.slice(0, piece.len_bytes()), &format!("{}/head.tsv", src.dir()))
}

/// Разбирает текст заголовка. `path` — только для сообщений об отказе.
fn parse_head(bytes: &[u8], path: &str) -> std::io::Result<Head> {
    let text = std::str::from_utf8(bytes).map_err(|e| bad(&format!("{path}: не UTF-8: {e}")))?;
    // Восемьдесят два бита нам не нужны, а шестьдесят четыре — умолчание для
    // сегментов, записанных до появления этой строки.
    let mut head = Head {
        docs: 0,
        blocks: 0,
        terms: 0,
        layout: 0,
        seq: 0,
        posblock: 0,
        posmin: 0,
        fields: Vec::new(),
        groups: Vec::new(),
        container: None,
    };
    for line in text.lines() {
        let p: Vec<&str> = line.split('\t').collect();
        match p.first().copied() {
            Some("docs") => head.docs = p.get(1).and_then(|x| x.parse().ok()).unwrap_or(0),
            Some("blocks") => head.blocks = p.get(1).and_then(|x| x.parse().ok()).unwrap_or(0),
            Some("terms") => head.terms = p.get(1).and_then(|x| x.parse().ok()).unwrap_or(0),
            Some("layout") => head.layout = p.get(1).and_then(|x| x.parse().ok()).unwrap_or(0),
            Some("seq") => head.seq = p.get(1).and_then(|x| x.parse().ok()).unwrap_or(0),
            Some("posblock") => head.posblock = p.get(1).and_then(|x| x.parse().ok()).unwrap_or(0),
            Some("posmin") => head.posmin = p.get(1).and_then(|x| x.parse().ok()).unwrap_or(0),
            // Имя контейнера в строке есть, но выбора имени нет: принять чужое
            // значило бы согласиться отобразить что угодно, на что укажет
            // заголовок, — в том числе за пределами каталога сегмента. Строка
            // разбирается строго, и негодная это отказ, а не «сегмент рассыпан»:
            // молчаливое «рассыпан» открыло бы сегмент **без половины кусков**.
            Some("container") => {
                let name = p.get(1).copied().unwrap_or("");
                let len = p.get(2).and_then(|x| x.parse::<u64>().ok());
                match (name == crate::container::FILE, len) {
                    (true, Some(len)) => head.container = Some(len),
                    _ => {
                        return Err(bad(&format!(
                            "{path}: строка container обязана быть \"{}\" с длиной, а не {:?}",
                            crate::container::FILE,
                            &p[1..]
                        )))
                    }
                }
            }
            Some("group") => head.groups.push(GroupHead {
                id: p.get(1).and_then(|x| x.parse().ok()).unwrap_or(0),
                path: p.get(2).copied().unwrap_or("").to_string(),
                kind: p
                    .get(3)
                    .and_then(|x| crate::slots::Kind::parse(x))
                    .unwrap_or(crate::slots::Kind::Identity),
                units: p.get(4).and_then(|x| x.parse().ok()).unwrap_or(0),
            }),
            Some("field") => head.fields.push(Field {
                norms_band: p
                    .get(8)
                    .and_then(|x| x.parse().ok())
                    .unwrap_or(head.fields.len() as u32),
                // Так же и с устойчивым номером: до реестра поле опознавалось
                // позицией, и умолчание её и воспроизводит.
                fid: p.get(9).and_then(|x| x.parse().ok()).unwrap_or(head.fields.len() as u32),
                // А основа имён файлов до реестра была именем поля.
                stem: p
                    .get(10)
                    .filter(|x| !x.is_empty())
                    .unwrap_or(p.get(1).unwrap_or(&""))
                    .to_string(),
                layout: p
                    .get(11)
                    .and_then(|x| crate::column::Layout::parse(x))
                    .unwrap_or(crate::column::Layout::Dense),
                presence: p
                    .get(12)
                    .and_then(|x| crate::column::Presence::parse(x))
                    .unwrap_or(crate::column::Presence::Bits),
                group: p.get(13).and_then(|x| x.parse().ok()).unwrap_or(0),
                values: p.get(14).and_then(|x| x.parse().ok()).unwrap_or(0),
                name: p.get(1).copied().unwrap_or("").to_string(),
                kind: p.get(4).and_then(|x| Kind::parse(x)).unwrap_or(Kind::Text),
                column: None,
                multi_column: None,
                multi_entries: p.get(20).and_then(|x| x.parse().ok()).unwrap_or(0),
                multi_values: p.get(21).and_then(|x| x.parse().ok()).unwrap_or(0),
                legacy_multivalue: false,
                legacy_keyword_values: false,
                store: None,
                vectors: None,
                stored: p.get(6).map(|x| *x != "0").unwrap_or(true),
                // Умолчание — «ищется»: сегменты, записанные до появления
                // столбца, искались по всем полям, и читать их иначе значило бы
                // молча выключить поиск по готовому индексу.
                searched: p.get(15).map(|x| *x != "0").unwrap_or(true),
                bounds: match (
                    p.get(16).and_then(|x| x.parse::<i64>().ok()),
                    p.get(17).and_then(|x| x.parse::<i64>().ok()),
                ) {
                    (Some(lo), Some(hi)) if lo <= hi => Some((lo, hi)),
                    _ => None,
                },
                positioned: p.get(7).map(|x| *x != "0").unwrap_or(true),
                spread: p.get(5).and_then(|x| x.parse().ok()).unwrap_or(1.0),
                boost: p.get(2).and_then(|x| x.parse().ok()).unwrap_or(1.0),
                avgdl: p.get(3).and_then(|x| x.parse().ok()).unwrap_or(1.0),
                // Сегмент старой сборки этих столбцов не несёт. Сумма
                // восстанавливается из средней и числа документов — она чуть
                // грубее записанной, но берётся из того же, из чего и
                // считалась бы. Наибольший уровень при этом объявляется
                // предельным: не зная его, занижать нельзя — заниженный
                // превратил бы потолок в не-потолок и начал бы терять выдачу.
                len_fixed: p.get(18).and_then(|x| x.parse().ok()).unwrap_or_else(|| {
                    let avgdl: f64 = p.get(3).and_then(|x| x.parse().ok()).unwrap_or(1.0);
                    (avgdl * head.docs as f64 * crate::norms::FIXED as f64) as u64
                }),
                lmax: p.get(19).and_then(|x| x.parse().ok()).unwrap_or(u8::MAX),
                scoring_docs: p
                    .get(22)
                    .filter(|x| !x.is_empty())
                    .map(|x| x.parse::<u64>())
                    .transpose()
                    .map_err(|_| bad(&format!("{path}: scoring_docs не является u64")))?,
                norms_at: 0,
                nu_by_level: std::sync::Arc::new([0f64; 256]),
                d_by_level: std::sync::Arc::new([0f64; 256]),
            }),
            _ => {}
        }
    }
    if head.fields.is_empty() || head.docs == 0 {
        return Err(bad(&format!("{path}: пустой заголовок индекса")));
    }
    if head.docs > u32::MAX as usize {
        return Err(bad(&format!("{path}: документов больше пространства u32")));
    }
    if head
        .fields
        .iter()
        .any(|field| field.scoring_docs.is_some_and(|count| count > head.docs as u64))
    {
        return Err(bad(&format!("{path}: scoring_docs больше числа документов")));
    }
    if head.layout >= 11
        && head.fields.iter().any(|field| {
            field.kind == Kind::Text && field.group == 0 && field.scoring_docs.is_none()
        })
    {
        return Err(bad(&format!("{path}: layout 11 требует scoring_docs для корневого text")));
    }
    if head.fields.len() > u16::MAX as usize || head.groups.len() > u16::MAX as usize {
        return Err(bad(&format!("{path}: слишком много полей или групп")));
    }
    if !head.groups.is_empty() {
        for (want, group) in head.groups.iter().enumerate() {
            if group.id as usize != want {
                return Err(bad(&format!(
                    "{path}: группы должны иметь плотные номера от нуля, ожидалась {want}, получена {}",
                    group.id
                )));
            }
            if group.units > u32::MAX as usize {
                return Err(bad(&format!("{path}: негодные метаданные группы {}", group.id)));
            }
            // Путь группы — это путь массива в документе, и он обязан быть
            // настоящим путём, а не любой строкой без управляющих символов.
            // Прежняя проверка пропускала что угодно длиной до 512 байт, и
            // запрос по такой группе адресовался бы к тому, чего нет.
            if group.id == 0 {
                if !group.path.is_empty() {
                    return Err(bad(&format!(
                        "{path}: у корневой группы путь {:?}, а корень — это сам документ",
                        group.path
                    )));
                }
            } else if let Err(e) = crate::schema::valid_field_path(&group.path) {
                return Err(bad(&format!("{path}: путь группы {}: {e}", group.id)));
            }
            if group.id == 0
                && (group.kind != crate::slots::Kind::Identity || group.units != head.docs)
            {
                return Err(bad(&format!(
                    "{path}: корневая группа обязана быть identity и содержать по слоту на документ"
                )));
            }
        }
    }
    let ngroups = head.groups.len().max(1);
    let mut stems = HashSet::with_capacity(head.fields.len());
    let mut fids = HashSet::with_capacity(head.fields.len());
    for field in &head.fields {
        valid_field_name(&field.stem).map_err(|e| bad(&format!("{path}: основа файла: {e}")))?;
        if field.name.is_empty()
            || field.name.len() > 512
            || field.name.chars().any(char::is_control)
        {
            return Err(bad(&format!("{path}: негодное имя поля {:?}", field.name)));
        }
        if !stems.insert(field.stem.clone()) || !fids.insert(field.fid) {
            return Err(bad(&format!(
                "{path}: основы файлов и номера полей должны быть уникальны"
            )));
        }
        if field.group as usize >= ngroups || field.norms_band as usize >= head.fields.len() {
            return Err(bad(&format!(
                "{path}: поле {:?} ссылается на несуществующую группу или полосу норм",
                field.name
            )));
        }
        if !field.boost.is_finite()
            || field.boost.abs() > 1_000_000.0
            || !field.avgdl.is_finite()
            || field.avgdl <= 0.0
            || field.avgdl > u32::MAX as f64
            || !field.spread.is_finite()
            || field.spread < 0.0
            || field.spread > 1.000_001
        {
            return Err(bad(&format!(
                "{path}: поле {:?} содержит NaN/Inf или негодную среднюю длину",
                field.name
            )));
        }
        // Сумма длин обязана быть достижимой: наибольшая длина на число
        // документов. Заголовок, обещающий больше, лжёт — и ложь эта опасна,
        // потому что из суммы выходит средняя, а из средней потолки отсечения.
        let reachable = (head.docs as u64)
            .saturating_mul(crate::norms::fixed_len(u8::MAX))
            .saturating_add(crate::norms::FIXED);
        if field.len_fixed > reachable {
            return Err(bad(&format!(
                "{path}: поле {:?} обещает сумму длин {} при достижимом потолке {reachable}",
                field.name, field.len_fixed
            )));
        }
    }
    Ok(head)
}

/// Загружает сегмент из каталога.
impl Index {
    /// Неизменяемая карта видимости на текущий миг.
    ///
    /// Состав сегмента уже immutable, но `live.bin` меняется на месте при
    /// update/delete. PIT обязан заморозить и эту часть, иначе следующая
    /// страница увидит другой корпус при том же наборе отображений.
    pub fn live_snapshot(&self) -> crate::live::Snapshot {
        self.live
            .as_ref()
            .map(crate::live::Live::snapshot)
            .unwrap_or_else(|| crate::live::Snapshot::all(self.docs))
    }

    /// Разделяемый, generation-aware снимок видимости.
    pub fn shared_live_snapshot(&self) -> std::sync::Arc<crate::live::Snapshot> {
        let Some(live) = self.live.as_ref() else {
            return std::sync::Arc::new(crate::live::Snapshot::all(self.docs));
        };
        loop {
            let before = live.version();
            if let Some(snapshot) = self
                .live_snapshot_cache
                .lock()
                .unwrap_or_else(std::sync::PoisonError::into_inner)
                .as_ref()
                .and_then(|(generation, snapshot)| {
                    (*generation == before).then(|| std::sync::Arc::clone(snapshot))
                })
            {
                return snapshot;
            }
            let snapshot = std::sync::Arc::new(live.snapshot());
            let after = live.version();
            if before != after {
                continue;
            }
            *self.live_snapshot_cache.lock().unwrap_or_else(std::sync::PoisonError::into_inner) =
                Some((after, std::sync::Arc::clone(&snapshot)));
            return snapshot;
        }
    }

    /// Содержимое поля документа. `None` — поле не хранится или номера нет.
    pub fn fetch(&self, doc: u32, field: usize) -> Option<Vec<u8>> {
        let f = self.fields.get(field)?;
        match f.store.as_ref() {
            Some(s) => s.get(doc),
            // Числовое поле хранит значение в колонке, и второй копии текстом
            // ему не нужно: она стоила 8.87 Б/док и десять секунд приёма на двух
            // миллионах — при том что колонка лежит рядом и точна.
            None if f.stored && f.kind.numeric() => Some(self.column_text(field, doc)),
            None => None,
        }
    }

    /// Значение числового поля текстом — из колонки.
    fn column_text(&self, field: usize, doc: u32) -> Vec<u8> {
        let f = &self.fields[field];
        let Some(v) = f.column.as_ref().and_then(|c| c.get(doc)) else {
            // Значения нет — пустая строка. Ровно её и хранила бы копия:
            // документ без поля приходит с пустым текстом.
            return Vec::new();
        };
        match f.kind {
            Kind::Bool => if v != 0 { "true" } else { "false" }.into(),
            Kind::Float | Kind::Double => float_of(v).to_string().into_bytes(),
            _ => v.to_string().into_bytes(),
        }
    }

    /// Номер поля по имени.
    pub fn field_of(&self, name: &str) -> Option<usize> {
        self.fields.iter().position(|f| f.name == name)
    }

    /// Местный номер поля по устойчивому. `None` — поля в сегменте нет.
    pub fn field_by_id(&self, fid: u32) -> Option<usize> {
        self.fields.iter().position(|f| f.fid == fid)
    }
}

/// Сверяет длину отображённого файла с тем, что обещает заголовок.
///
/// Чтение за границей отображения отдаёт нули — намеренно, и на горячем пути это
/// верно: хвостовой блок списка читается с запасом, и проверка на каждый
/// документ стоила бы дороже всего, что она ловит. Но у трёх файлов метаданных
/// длина известна заранее, из заголовка, и там молчаливый ноль не спасает от
/// падения, а **подменяет смысл**:
fn checked(
    src: &crate::container::SegmentSource,
    name: &str,
    want: usize,
) -> std::io::Result<Region> {
    let m = src.open(name)?;
    if m.len_bytes() < want {
        return Err(bad(&format!(
            "{}/{name}: {} байт вместо {want} — сегмент повреждён",
            src.dir(),
            m.len_bytes()
        )));
    }
    Ok(m)
}

pub fn load(dir: &str) -> std::io::Result<Index> {
    let head = read_head(dir)?;
    // Источник заводится сразу за заголовком и до первого куска: у упакованного
    // сегмента здесь ложится единственная область отображения, у рассыпанного не
    // происходит вовсе ничего — открытие каждого куска остаётся тем же, каким
    // было.
    let src = std::sync::Arc::new(crate::container::SegmentSource::of(dir, head.container)?);
    open_over(src, head)
}

/// Строго read-only открытие для миграции: shared mapping карты удалений запрещён.
pub fn load_read_only(dir: &str) -> std::io::Result<Index> {
    let head = read_head(dir)?;
    let src = std::sync::Arc::new(crate::container::SegmentSource::of(dir, head.container)?);
    let index = open_over_mode(src, head, false)?;
    if index.live.as_ref().is_some_and(|live| !live.intact()) {
        return Err(bad("карта удалений не прошла проверку контрольной суммы"));
    }
    Ok(index)
}

/// Открывает сегмент, собранный в память.
///
/// Заголовок берётся у самого источника: у такого сегмента он лежит куском
/// наравне с прочими. Дальше — тот же код, что и у легшего на диск, и это здесь
/// главное: разбор формата обязан быть один.
pub fn open_memory(src: std::sync::Arc<crate::container::SegmentSource>) -> std::io::Result<Index> {
    if !src.is_memory() {
        return Err(bad(&format!(
            "{}: открывается как сегмент в памяти, а под ним файл",
            src.dir()
        )));
    }
    let head = head_of(&src)?;
    open_over(src, head)
}

/// Открывает сегмент поверх готового источника — одним кодом на диск и память.
fn open_over(
    src: std::sync::Arc<crate::container::SegmentSource>,
    head: Head,
) -> std::io::Result<Index> {
    open_over_mode(src, head, true)
}

fn open_over_mode(
    src: std::sync::Arc<crate::container::SegmentSource>,
    head: Head,
    writable_live: bool,
) -> std::io::Result<Index> {
    let Head {
        docs,
        blocks,
        terms,
        layout,
        seq,
        posblock,
        posmin,
        mut fields,
        groups,
        container: _,
    } = head;
    // Каталог — или имя сегмента в памяти. Идёт только в сообщения об отказе и
    // в поле `dir`; открывать по нему файлы нельзя, и никто не открывает.
    let dir = src.dir().to_string();
    let dir = dir.as_str();
    // Читаются обе последние раскладки. Более старые прочесть нечем, и молчать
    // об этом нельзя: сегмент, собранный до шестой, отличается смыслом полей, а
    // не только их порядком.
    if !(LAYOUT_MIN..=LAYOUT).contains(&layout) {
        return Err(bad(&format!(
            "{dir}: раскладка {layout}, а читаются {LAYOUT_MIN}–{LAYOUT} — сегмент собран \
             прежней версией и требует пересборки"
        )));
    }

    let ngroups = fields.iter().map(|f| f.group as usize + 1).max().unwrap_or(1).max(groups.len());
    let mut slots: Vec<crate::slots::Slots> = Vec::with_capacity(ngroups);
    for g in 0..ngroups {
        let head = groups.iter().find(|x| x.id as usize == g);
        let kind = head.map(|h| h.kind).unwrap_or(crate::slots::Kind::Identity);
        let units = head.map(|h| h.units).unwrap_or(docs);
        match crate::slots::Slots::open(&src, g as u32, kind, docs, units) {
            Some(s) => slots.push(s),
            None => {
                return Err(bad(&format!(
                    "{dir}: у группы {g} обещана полоса арности {}, а файлов нет",
                    kind.name()
                )))
            }
        }
    }
    // Пути берутся из заголовка тем же обходом. У группы, которой в заголовке
    // нет вовсе (сегмент старше групп), путь пуст — и это законно: групп у него
    // и правда нет.
    let group_paths: Vec<String> = (0..ngroups)
        .map(|g| {
            groups.iter().find(|x| x.id as usize == g).map(|h| h.path.clone()).unwrap_or_default()
        })
        .collect();

    let nbands = fields.iter().map(|f| f.norms_band as usize + 1).max().unwrap_or(0);
    let norms_len = nbands
        .checked_mul(docs)
        .ok_or_else(|| bad(&format!("{dir}/head.tsv: переполнение длины norms.bin")))?;
    let norms = checked(&src, "norms.bin", norms_len)?;
    // Таблицы множителей заводятся по **различной** средней длине, а не по
    // полю: у всех числовых она единица, и одной таблицы им хватает на всех.
    // Пара таблиц на одну среднюю длину: множитель длины и знаменатель
    // насыщения. Поля с одинаковой `avgdl` делят их, не пересчитывая.
    type ByLevel = std::sync::Arc<[f64; 256]>;
    let mut tables: Vec<(f64, ByLevel, ByLevel)> = Vec::new();
    for f in fields.iter_mut() {
        f.norms_at = f.norms_band as usize * docs;
        // Одна средняя длина — одна пара таблиц на всех, кто её разделяет.
        let (nu, d) = match tables.iter().find(|(a, _, _)| *a == f.avgdl) {
            Some((_, nu, d)) => (nu.clone(), d.clone()),
            None => {
                let mut table = [0f64; 256];
                let mut dtable = [0f64; 256];
                for q in 0..256usize {
                    table[q] = norms::nu(q as u8, f.avgdl);
                    dtable[q] = norms::dl_part(q as u8, f.avgdl);
                }
                let pair = (std::sync::Arc::new(table), std::sync::Arc::new(dtable));
                tables.push((f.avgdl, pair.0.clone(), pair.1.clone()));
                pair
            }
        };
        f.nu_by_level = nu;
        f.d_by_level = d;
        // Колонка есть и у ключевого слова: в ней лежит номер списка в
        // словаре — тот самый ординал, на котором стоит верхушка значений.
        if f.kind.numeric() || f.kind.keyword() {
            if (f.multi_entries == 0) != (f.multi_values == 0)
                || (f.multi_entries > 0
                    && !(f.kind.numeric() && layout >= 10 || f.kind.keyword() && layout >= 12))
                || (f.multi_entries == 0 && src.has(&format!("{}.nmv", f.stem)))
            {
                return Err(bad(&format!(
                    "{dir}: несогласованная multivalue metadata поля {}",
                    f.name
                )));
            }
            if f.multi_entries > 0 {
                let raw = src.open(&format!("{}.nmv", f.stem))?;
                f.multi_column = Some(crate::multivalue::MultiColumn::open(
                    raw,
                    slots[f.group as usize].units(),
                    f.multi_entries,
                    f.multi_values,
                )?);
            }
            // Раскладка `none` означает, что значений в сегменте нет вовсе и
            // файлов быть не должно. Открывать нечего, и это не потеря.
            if f.layout != crate::column::Layout::None {
                let units = slots[f.group as usize].units();
                f.column = crate::column::Column::open_with(
                    &src,
                    &f.stem,
                    units,
                    f.presence,
                    f.layout,
                    if f.values == 0 { units } else { f.values },
                );
            }
        }
        if f.kind.dims().is_some() {
            f.vectors = crate::vector::Vectors::open(&src, &f.stem);
            if layout < 13 && f.vectors.as_ref().is_some_and(|v| v.uses_versioned_format()) {
                return Err(bad(&format!(
                    "{dir}: версия векторного кодека поля {} требует layout 13",
                    f.name
                )));
            }
            if f.vectors.is_none()
                && ["q8", "qm"].iter().any(|ext| src.has(&format!("{}.{ext}", f.stem)))
            {
                return Err(bad(&format!(
                    "{dir}: векторное поле {} содержит неполную или повреждённую пару q8/qm",
                    f.name
                )));
            }
            // Раскладка обязана сойтись со схемой. Разошлись — поле открывать
            // нельзя: считать расстояние по чужой размерности значит выдать
            // правдоподобный ответ на бессмыслицу.
            if f.vectors.as_ref().is_some_and(|v| v.dims() != f.kind.dims().unwrap_or(0)) {
                return Err(bad(&format!(
                    "{dir}: поле {:?} объявлено на {} измерений, а в раскладке {}",
                    f.name,
                    f.kind.dims().unwrap_or(0),
                    f.vectors.as_ref().map(|v| v.dims()).unwrap_or(0)
                )));
            }
            if f.vectors.as_ref().is_some_and(|v| v.docs() != docs) {
                return Err(bad(&format!(
                    "{dir}: число документов векторного поля {} не совпадает с сегментом",
                    f.name
                )));
            }
        }
        if f.stored {
            f.store = crate::store::Store::open(&src, &f.stem);
            // «Файлов нет» и «файлы есть, а хранилище не открылось» — разные
            // вещи, и вторая это порча, а не отсутствие.
            //
            // Молчание здесь худшего сорта: `fetch` вернул бы пустое на каждом
            // документе, и отличить это от «документ и правда пуст» нечем.
            // Правило уже написано дважды — `merge` и `check` его соблюдают, —
            // и открытие обязано соблюдать его тоже, иначе гнутый словарь
            // проходит в выдачу, а замечает его только тот, кто догадался
            // запустить проверку.
            if f.store.is_none()
                && ["sbin", "smrk", "sdic"].iter().all(|e| src.has(&format!("{}.{e}", f.stem)))
            {
                return Err(bad(&format!(
                    "{dir}: хранилище поля {} не открылось, а файлы на месте — не сошлись \
                     словарь, таблица словарей или суммы кусков; выдача вернула бы пустое \
                     на каждом документе и не отличила бы это от пустого документа",
                    f.name
                )));
            }
        }
    }

    // Карта живых открывается на правку и делится с читателями: гашение это
    // атомарный сброс бита в той же памяти, а не подмена файла. У сегмента в
    // памяти она лежит его же куском — и правится по тому же праву, см.
    // [`crate::live::Live::in_memory`].
    let live = if src.is_memory() {
        let piece = src.open(crate::live::FILE)?;
        crate::live::Live::in_memory(piece.slice(0, piece.len_bytes()), docs)
    } else if writable_live {
        crate::live::Live::open(dir, docs)
    } else {
        crate::live::Live::open_read_only(dir, docs)
    };
    // Карты нет или она короче нужного — это порча, а не «живы все».
    //
    // Разница существенная: обрезанная карта, прочитанная как «живы все»,
    // **воскрешает удалённые документы** и делает это молча.
    if live.is_none() {
        return Err(bad(&format!(
            "{dir}/{}: карты живых нет или она короче {docs} документов — сегмент повреждён",
            crate::live::FILE
        )));
    }

    let idstore = crate::ids::Ids::open(&src, docs);
    if let Err(e) = idstore.check(docs) {
        return Err(bad(&format!("{dir}: {e}")));
    }
    let idmap = crate::ids::IdMap::open(&src, docs, layout);
    if let Err(e) = idmap.check(docs) {
        return Err(bad(&format!("{dir}/{e} — сегмент повреждён")));
    }

    let post = src.open("postings.bin")?;
    // Сегмент без позиций — не ошибка: поле могло быть объявлено `nopos`.
    let pos = src.try_open("pos.bin").unwrap_or_else(Region::empty);
    let pos_idx = src.try_open("pos.idx").unwrap_or_else(Region::empty);
    // Здесь стоял `MADV_RANDOM` на постинги и позиции. Довод был такой: списки
    // читаются прыжками по блокам, упреждающее чтение при этом не помогает, а
    // вытесняет из кеша нужное.
    //
    // Довод не проверен, а цена у него есть и она названа. `MADV_RANDOM` —
    // **постоянное** изменение флагов области, и ядро расщепляет отображение на
    // части по границам совета. У упакованного сегмента постинги и позиции —
    // подобласти одного отображения `seg.dat`, то есть одна область
    // превращалась в три. А число областей у нас не свободный ресурс: под него
    // заведён отдельный предел (`vm.max_map_count`, см. `mmap::map_budget_with`),
    // и узел отказывается открывать состав, когда предел близко. Совет тратил
    // бы этот предел втрое быстрее, чем его считает сторож.
    //
    // Неизмеренная выгода против измеримой цены по объявленному пределу — не
    // размен. Возвращать это стоит только с числом QPS отбора в руках и
    // советом на **всё** отображение сразу, а не на его куски.

    let (terms_map, terms7) = if layout >= 7 {
        let t7 = crate::layout::Terms::open(&src, terms)?;
        walk_terms(dir, &t7, terms, blocks, post.len_bytes(), pos.len_bytes())?;
        (Region::empty(), Some(t7))
    } else {
        (checked(&src, "terms.bin", terms * TERM_META)?, None)
    };

    let mut index = Index {
        dir: dir.to_string(),
        // Опознание заголовка нужно тому, кто решает, перечитывать ли сегмент с
        // диска. У собранного в память перечитывать нечего и неоткуда: он не
        // меняется и живёт ровно столько, сколько его держат, — поэтому здесь
        // нули, а состав обязан переносить такой сегмент прежним объектом, а не
        // открывать заново. См. [`crate::segments::Segments::reopen`].
        head_id: if src.is_memory() { (0, 0) } else { head_ident(dir) },
        // Оба числа снимаются здесь и больше не пересчитываются: см. поля.
        // Место на диске сегмент в памяти не занимает — ни байта, и это не
        // «неизвестно», а ноль.
        bytes: if src.is_memory() {
            crate::sums::Bytes::default()
        } else {
            crate::sums::sizes(dir)
        },
        schema_sig: crate::merge::schema_sig(&fields.iter().map(|f| f.fid).collect::<Vec<u32>>()),
        post,
        fields,
        docs,
        slots,
        group_paths,
        live,
        live_snapshot_cache: std::sync::Mutex::new(None),
        blocks: checked(&src, "blocks.bin", blocks * BLOCK_META)?,
        pos,
        pos_idx,
        norms,
        terms: terms_map,
        terms7,
        layout,
        posblock,
        posmin,
        nterms: terms,
        dict: Dict::open(&src, terms, layout)?,
        term_filter: crate::bloom::Bloom::open(&src, "terms.bloom"),
        idmap,
        seq,
        src,
    };
    if layout < 10 {
        // Только полная scalar column доказывает отсутствие потерянных
        // массивов в старом формате. Пропуск может означать как missing,
        // так и многозначный JSON. По metadata отличить их нельзя; угадывать
        // по наличию presence postings у ещё более старого writer опасно.
        // Проверка не читает словари и не создаёт ленивой работы в запросе.
        let legacy: Vec<bool> = index
            .fields
            .iter()
            .map(|field| {
                field.kind.numeric()
                    && field.searched
                    && (field.column.is_none()
                        || field.values != index.slots[field.group as usize].units())
            })
            .collect();
        for (field, legacy) in index.fields.iter_mut().zip(legacy) {
            field.legacy_multivalue = legacy;
        }
    }
    if layout < 12 {
        for field in &mut index.fields {
            field.legacy_keyword_values = field.kind.keyword()
                && field.searched
                && (field.column.is_some() || field.multi_column.is_some());
        }
    }
    Ok(index)
}

/// Проходит **все** метаданные слов и сверяет их с длинами файлов.
///
/// Запись переменной длины меняет природу порчи. У шестой раскладки обрезанный
/// `terms.bin` давал `df = 0` — «такого слова здесь нет», — и это ловилось
/// сверкой длины с заголовком. У седьмой сдвиг на один байт разбирает **все
/// последующие** записи как попало: частота, номер документа и длина куска
/// поедут разом, и список окажется не пустым, а чужим. Проверять такое по длине
/// файла нечем.
///
/// Поэтому проход честный, по каждой записи. Он же попутно проверяет главный
/// договор раскладки: `postings.bin` и `pos.bin` — это **склейка кусков, чьи
/// длины лежат в записях слов**, а число блоков — сумма по длинным спискам. Если
/// хоть одна сумма разошлась с файлом, сегмент открывать нельзя.
fn walk_terms(
    dir: &str,
    t7: &crate::layout::Terms,
    terms: usize,
    blocks: usize,
    post_len: usize,
    pos_len: usize,
) -> std::io::Result<()> {
    let groups = crate::layout::Terms::groups(terms);
    let want_idx = groups * crate::layout::RESTART;
    if t7.idx_bytes() < want_idx {
        return Err(bad(&format!(
            "{dir}/terms.idx: {} байт вместо {want_idx} — сегмент повреждён",
            t7.idx_bytes()
        )));
    }
    let (mut at, mut post, mut pos, mut block) = (0usize, 0usize, 0usize, 0usize);
    for g in 0..groups {
        let mut w = t7.walk(g);
        // Опора обязана указывать ровно туда, где кончилась прошлая группа:
        // иначе между группами есть байты, которых никто не читает, — а значит
        // и сдвиг, которого никто не заметит.
        let (start, p0, s0, b0) = w.here();
        if (start, p0, s0, b0) != (at, post, pos, block) {
            return Err(bad(&format!(
                "{dir}/terms.idx: опора группы {g} обещает {start}/{p0}/{s0}/{b0}, \
                 а прошлая группа кончилась на {at}/{post}/{pos}/{block} — сегмент повреждён"
            )));
        }
        let mut seen = 0usize;
        while w.next().is_some() {
            seen += 1;
        }
        let want = (terms - g * crate::layout::ANCHOR).min(crate::layout::ANCHOR);
        if seen != want {
            return Err(bad(&format!(
                "{dir}/terms.bin: в группе {g} разобрано {seen} слов из {want} — \
                 сегмент повреждён"
            )));
        }
        (at, post, pos, block) = w.here();
    }
    for (name, got, want) in [
        ("terms.bin", t7.bytes(), at),
        ("postings.bin", post_len, post),
        ("pos.bin", pos_len, pos),
        ("blocks.bin", blocks, block),
    ] {
        if got != want {
            return Err(bad(&format!(
                "{dir}/{name}: {got} против {want} по метаданным слов — сегмент повреждён"
            )));
        }
    }
    Ok(())
}

/// Обратная частота документа. Робертсон-Спарк-Джонс со сглаживанием.
///
/// Свободной функцией, а не только методом сегмента: та же формула используется
/// и для общей статистики индекса.
///
/// Оба довода — `u64`, и это не запас на будущее.
///
/// Частота приходит суммой по сегментам и накапливалась в `u64`, а перед самой
/// формулой обрезалась до `u32`. Пока частот меньше четырёх миллиардов, обрезка
/// незаметна; выше — она бьёт по **самым частым словам корпуса**, то есть по
/// тем, ради которых отсечение и заводилось. Слово, встречающееся во всех
/// десяти в одиннадцатой документах, после обрезки получало вес, как у слова из
/// четырёх миллиардов, — почти максимальную важность вместо почти нулевой.
///
/// Число документов тоже `u64`: сравнивать его с частотой, приведя одно к
/// `usize`, а другое к `u32`, значит однажды сравнить разное.
pub fn idf_of(docs: u64, df: u64) -> f64 {
    let n = docs.max(1) as f64;
    let d = (df as f64).clamp(1.0, n);
    (1.0 + (n - d + 0.5) / (d + 0.5)).ln()
}

/// Как считать вклад документа, когда статистика берётся со всего состава.
///
/// Таблицы посчитаны по **общей** средней длине и потому одни на все сегменты:
/// они делятся ссылкой, а не копируются на каждый. Своё у сегмента только
/// `lift` — множитель, приводящий его сохранённые потолки к этой же общей
/// средней, см. [`crate::norms::lift_of`].
#[derive(Clone)]
pub struct FieldScore {
    /// Множитель длины по уровню при общей средней.
    pub nu: std::sync::Arc<[f64; 256]>,
    /// Длинная часть знаменателя по уровню при общей средней.
    pub d: std::sync::Arc<[f64; 256]>,
    /// Во сколько раз поднимать потолки **этого** сегмента.
    pub lift: f64,
}

impl FieldScore {
    /// Таблицы для заданной средней длины. Считаются один раз на запрос.
    pub fn tables(effective: f64) -> (std::sync::Arc<[f64; 256]>, std::sync::Arc<[f64; 256]>) {
        let mut nu = [0f64; 256];
        let mut d = [0f64; 256];
        for q in 0..256usize {
            nu[q] = crate::norms::nu(q as u8, effective);
            d[q] = crate::norms::dl_part(q as u8, effective);
        }
        (std::sync::Arc::new(nu), std::sync::Arc::new(d))
    }
}

#[cfg(test)]
