    /// Сколько байт в каждом куске крупного контейнера.
    ///
    /// Заметно больше [`CHUNK`]: будь кусок с буфер прохода, «проход кусками» и
    /// «чтение целиком» занимали бы одно и то же, и мерить было бы нечего.
    const BULK: usize = 6 * CHUNK;

    /// Каталог с крупным контейнером — ровно чтобы мерить занятое.
    ///
    /// Собран писателем контейнера, а не приёмом: приём на такой объём в
    /// отладочной сборке идёт секундами, а проверке нужен один-единственный
    /// признак — что файл много больше буфера прохода. Сводке при этом всё
    /// равно, чем каталог набит: она ходит по нему, а не по заголовку.
    fn bulky(name: &str) -> String {
        let d = std::env::temp_dir()
            .join(format!("svindb-sums-bulky-{name}-{}", std::process::id()))
            .to_string_lossy()
            .to_string();
        std::fs::remove_dir_all(&d).ok();
        std::fs::create_dir_all(&d).expect("каталог");
        let mut w = crate::container::Writer::create(&d, 9).expect("контейнер");
        for (i, piece) in ["dict.blob", "ids.bin", "postings.bin", "terms.bin"].iter().enumerate() {
            // Куски набиты по-разному: одинаковые дали бы одинаковые суммы, и
            // проход, спутавший отрезки, прошёл бы проверку насквозь.
            let body: Vec<u8> =
                (0..BULK).map(|x| x.wrapping_mul(31).wrapping_add(i) as u8).collect();
            w.put(piece, &body).expect("кусок");
        }
        w.finish().expect("закрытие");
        std::fs::write(format!("{d}/head.tsv"), "docs\t0\n").expect("заголовок");
        d
    }

    /// Сводка идёт по контейнеру проходом, а не держит его целиком.
    ///
    /// ## Что ломалось бы без него
    ///
    /// У упакованного сегмента файл один, и это весь сегмент — до четырёх
    /// гигабайт потолком этапа. Читай сводка его целиком, и пик занятого
    /// равнялся бы размеру сегмента: на приёме, на каждом слиянии и на каждой
    /// проверке. На пути слияния это смерть процесса — сборка идёт с
    /// `panic = "abort"`, и неудачное выделение там не ошибка. На пути приёма
    /// тише и хуже: сводка просто не запишется, а `check --full` объявит потом
    /// сегмент сломанным, не назвав причины.
    ///
    /// Меряется [`crate::alloc::peak`], а не `watch`: следа сводка не оставляет
    /// вовсе — она всё освобождает, — и стоит ровно тем, что держит в середине.
    ///
    /// Одного потолка занятого мало: проход обязан считать то же самое, что
    /// считало бы чтение целиком, иначе проверка доказывала бы лишь то, что
    /// сводка ничего не делает. Поэтому суммы сверяются с посчитанными по
    /// прочитанному в память файлу — и по контейнеру, и по каждому куску.
    #[test]
    fn a_summary_walks_the_container_instead_of_holding_it() {
        let d = bulky("peak");
        let cpath = format!("{d}/{}", crate::container::FILE);
        let bytes = std::fs::metadata(&cpath).expect("контейнер").len() as usize;
        assert!(bytes > 16 * CHUNK, "контейнер всего {bytes} байт — мерить нечего");
        // Потолок с запасом: проход держит буфер в CHUNK байт да мелочь на имена
        // и оглавление. Чтение целиком не уложилось бы и в вчетверо больший.
        let roof = bytes / 4;

        let peak = crate::alloc::peak(|| write(&d).expect("сводка"));
        assert!(peak < roof, "сводка заняла {peak} байт при контейнере {bytes}");
        let peak = crate::alloc::peak(|| verify(&d).expect("сводка"));
        assert!(peak < roof, "сверка заняла {peak} байт при контейнере {bytes}");

        assert!(verify(&d).expect("сводка").is_empty(), "сводка разошлась с контейнером");
        let whole = std::fs::read(&cpath).expect("контейнер");
        let named = compute(&d).expect("сводка");
        let seg = named
            .iter()
            .find(|s| s.name == crate::container::FILE)
            .expect("строки про seg.dat нет");
        assert_eq!(seg.len, whole.len() as u64, "длина прохода не та");
        assert_eq!(seg.crc, crate::wal::crc32(&whole), "сумма прохода не та");

        let t = crate::container::Table::read(&cpath).expect("оглавление");
        assert_eq!(t.members().len(), 4, "кусков не четыре");
        for m in t.members() {
            let row = named
                .iter()
                .find(|s| piece_of(&s.name) == Some(m.name.as_str()))
                .unwrap_or_else(|| panic!("строки про кусок {} нет", m.name));
            let body = whole
                .get(m.off as usize..(m.off + m.len) as usize)
                .unwrap_or_else(|| panic!("кусок {} не лёг в файл", m.name));
            assert_eq!(row.len, m.len, "длина куска {}", m.name);
            assert_eq!(row.crc, crate::wal::crc32(body), "сумма куска {}", m.name);
        }

        std::fs::remove_dir_all(&d).ok();
    }

    /// Нечитаемое оглавление не обнуляет меру — и не переспрашивается зря.
    ///
    /// ## Что ломалось бы без него
    ///
    /// Разбивка — вход политике укрупнения: по ней меряют, не упрётся ли слитый
    /// сегмент в потолок тридцатидвухбитного смещения. Проглоти [`sizes`] отказ
    /// оглавления молча — и она вернула бы нули, то есть объявила бы
    /// четырёхгигабайтный сегмент пустым. Политика набрала бы таких сколько
    /// угодно в одно слияние, а отказ пришёл бы от `merge::fits_offset` посреди
    /// работы, часами позже: цена молчания целиком переложена на дальний отказ.
    ///
    /// Вместо нулей берётся верхняя граница — длина самого контейнера: ни один
    /// кусок не длиннее файла, в котором лежит. Мера от этого осторожничает.
    ///
    /// Первая же половина проверки говорит о другом: пока разбивку называет
    /// сводка, оглавление не спрашивается вовсе. Видно это по тому, что
    /// нечитаемое оглавление на ответ не влияет никак.
    #[test]
    fn a_directory_that_will_not_parse_does_not_zero_the_measure() {
        let s = uneven("blindsize");
        let good = sizes(&s);
        assert!(good.postings > 0 && good.terms > 0 && good.stored_max > 0, "мерить нечего");

        let cpath = format!("{s}/{}", crate::container::FILE);
        let mut bent = std::fs::read(&cpath).expect("контейнер");
        let byte = bent.first_mut().expect("контейнер пуст");
        *byte ^= 0xFF;
        std::fs::write(&cpath, &bent).expect("порча");
        let cap = bent.len() as u64;
        assert!(cap > good.postings, "верхняя граница не отличима от измеренного");

        // Сводка называет куски поимённо — оглавление и не спрашивается, а
        // значит его порча ответа не меняет.
        assert_eq!(sizes(&s), good, "разбивка поехала от нечитаемого оглавления");

        // А без сводки мерить нечем — и вместо нулей идёт верхняя граница.
        std::fs::remove_file(format!("{s}/{FILE}")).expect("снос сводки");
        let blind = sizes(&s);
        for (what, got) in [
            ("postings", blind.postings),
            ("positions", blind.positions),
            ("terms", blind.terms),
            ("ids", blind.ids),
            ("dictionary", blind.dictionary),
            ("stored_max", blind.stored_max),
        ] {
            assert_eq!(got, cap, "{what}: неизмеренное выдано за измеренное");
        }

        std::fs::remove_dir_all(std::path::Path::new(&s).parent().unwrap()).ok();
    }

    /// Как сверка назвала строку сводки про это имя.
    fn tag(bad: &[(String, Verdict)], name: &str) -> &'static str {
        match bad.iter().find(|(n, _)| n == name) {
            None => "сошлось",
            Some((_, Verdict::Same)) => "сошлось",
            Some((_, Verdict::Length { .. })) => "длина",
            Some((_, Verdict::Content { .. })) => "содержимое",
            Some((_, Verdict::Gone)) => "нет",
            Some((_, Verdict::Extra)) => "лишний",
            Some((_, Verdict::Unreadable { .. })) => "не прочёлся",
        }
    }

    /// Имена строк сводки, называющих куски контейнера.
    fn piece_rows(dir: &str) -> Vec<String> {
        read(dir)
            .expect("сводка")
            .into_iter()
            .filter(|s| piece_of(&s.name).is_some())
            .map(|s| s.name)
            .collect()
    }

    /// Нечитаемое оглавление — не «все куски пропали».
    ///
    /// ## Что ломалось бы без него
    ///
    /// Сверка берёт куски из оглавления контейнера. Не разберись оглавление —
    /// сбитая сумма, нарушенный порядок имён, нахлёст, — и про каждый кусок
    /// сказать нечего. Ответить на это «названного в сводке нет» значит выдать
    /// оператору вердикт о данных, которых сверка не видела: опись `check`
    /// напечатает по строке «файла нет: он был при сборке сегмента и пропал
    /// после неё» на каждый из полусотни кусков, и человек пойдёт искать
    /// пропавший сегмент, целиком лежащий на диске.
    ///
    /// Заодно проверяется, что различение не куплено обратной ценой: у сегмента,
    /// у которого контейнер **и вправду** снесли, куски по-прежнему «пропали», а
    /// не «не прочлись». Иначе замена одного молчания другим прошла бы незаметно.
    ///
    /// Сумма по самому `seg.dat` при этом остаётся вердиктом о данных: байты
    /// файла читаются, и порчу они называют точнее, чем «прочесть не удалось».
    #[test]
    fn a_directory_that_will_not_parse_is_not_reported_as_lost_pieces() {
        let s = seg("blind");
        let cpath = format!("{s}/{}", crate::container::FILE);
        let good = std::fs::read(&cpath).expect("контейнер");
        let rows = piece_rows(&s);
        assert!(rows.len() > 8, "кусков в сводке всего {}", rows.len());
        assert!(verify(&s).expect("сводка").is_empty(), "целый сегмент уже расходится");

        // Опознание в начале файла: оглавление перестаёт разбираться целиком, а
        // байты файла читаются по-прежнему.
        let mut bent = good.clone();
        let byte = bent.first_mut().expect("контейнер пуст");
        *byte ^= 0xFF;
        std::fs::write(&cpath, &bent).expect("порча");
        let bad = verify(&s).expect("сводка");
        for name in rows.iter() {
            assert_eq!(tag(&bad, name), "не прочёлся", "кусок {name}");
        }
        assert_eq!(
            tag(&bad, crate::container::FILE),
            "содержимое",
            "порча самого контейнера названа не тем"
        );

        // Контейнера нет вовсе — и вот это уже находка о данных.
        std::fs::remove_file(&cpath).expect("снос");
        let bad = verify(&s).expect("сводка");
        for name in rows.iter() {
            assert_eq!(tag(&bad, name), "нет", "снесённый кусок {name}");
        }
        assert_eq!(tag(&bad, crate::container::FILE), "нет", "снесённый контейнер");

        std::fs::write(&cpath, &good).expect("возврат");
        assert!(verify(&s).expect("сводка").is_empty(), "возвращённое всё ещё расходится");
        std::fs::remove_dir_all(std::path::Path::new(&s).parent().unwrap()).ok();
    }

    /// То, что не прочлось, не объявляется пропавшим.
    ///
    /// ## Что ломалось бы без него
    ///
    /// `.ok()` на чтении файла превращал любой отказ ввода-вывода — нет прав,
    /// нехватка памяти под четыре гигабайта, сбой носителя — в находку «файла
    /// нет». Три исхода правила о молчании («нет», «пуст», «не прочёлся») тут
    /// сливались в один, и худший из них выдавался за первый.
    ///
    /// Отказ вносится петлёй символической ссылки: она даёт настоящий отказ
    /// ядра, не зависящий ни от прав запускающего, ни от свободной памяти, — и
    /// это заведомо **не** `NotFound`, то есть ровно тот случай, который прежде
    /// подменялся.
    #[cfg(unix)]
    #[test]
    fn what_could_not_be_read_is_not_called_missing() {
        let s = seg("loop");
        let rows = piece_rows(&s);
        assert!(rows.len() > 8, "кусков в сводке всего {}", rows.len());

        // Ссылка на саму себя: открытие упирается в петлю.
        let cpath = format!("{s}/{}", crate::container::FILE);
        let good = std::fs::read(&cpath).expect("контейнер");
        std::fs::remove_file(&cpath).expect("снос");
        std::os::unix::fs::symlink(crate::container::FILE, &cpath).expect("петля");
        let bad = verify(&s).expect("сводка");
        assert_eq!(tag(&bad, crate::container::FILE), "не прочёлся", "контейнер");
        for name in rows.iter() {
            assert_eq!(tag(&bad, name), "не прочёлся", "кусок {name}");
        }
        std::fs::remove_file(&cpath).expect("снос петли");
        std::fs::write(&cpath, &good).expect("возврат");
        assert!(verify(&s).expect("сводка").is_empty(), "возвращённое всё ещё расходится");

        // То же для файла каталога, который лежит рядом с контейнером.
        let hpath = format!("{s}/head.tsv");
        let head = std::fs::read(&hpath).expect("заголовок");
        std::fs::remove_file(&hpath).expect("снос");
        std::os::unix::fs::symlink("head.tsv", &hpath).expect("петля");
        let bad = verify(&s).expect("сводка");
        assert_eq!(tag(&bad, "head.tsv"), "не прочёлся", "заголовок");
        std::fs::remove_file(&hpath).expect("снос петли");
        std::fs::write(&hpath, &head).expect("возврат");
        assert!(verify(&s).expect("сводка").is_empty(), "возвращённое всё ещё расходится");

        std::fs::remove_dir_all(std::path::Path::new(&s).parent().unwrap()).ok();
    }
