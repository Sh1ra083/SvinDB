    /// Перевёрнутый бит ловится — а больше его ловить нечем.
    ///
    /// Проверяется на **каждом** куске сегмента, а не на одном: смысл суммы
    /// именно в том, что она не разбирается в содержимом и потому одинаково
    /// видит подмену везде. Длина при этом не меняется, поэтому ни одна проверка
    /// счёта такого не заметит — что тест и подтверждает отдельно.
    ///
    /// ## Почему обход идёт по кускам, а не по файлам
    ///
    /// У упакованного сегмента файлов остаётся два, и обход по файлам проверял
    /// бы два места вместо двух десятков. Порча же случается там, где лежат
    /// данные, — внутри контейнера, — и находка обязана называть **кусок**, а не
    /// весь `seg.dat`: находка на гигабайтном файле не указывает никуда. Поэтому
    /// бит переворачивается по смещению куска внутри контейнера, а спрашивается
    /// с сводки имя этого куска.
    #[test]
    fn a_single_flipped_bit_is_caught_in_every_file() {
        let s = seg("flip");
        let cpath = format!("{s}/{}", crate::container::FILE);
        let table = crate::container::Table::read(&cpath).ok();

        // Что портить: имя записи в сводке, файл, который правится, и смещение
        // внутри этого файла.
        let mut spots: Vec<(String, String, u64)> = Vec::new();
        for x in compute(&s).expect("сводка считается") {
            if x.len == 0 {
                continue;
            }
            match piece_of(&x.name) {
                Some(p) => {
                    let t = table.as_ref().expect("оглавление контейнера");
                    let m = t.find(p).unwrap_or_else(|| panic!("куска {p} нет в оглавлении"));
                    spots.push((x.name.clone(), cpath.clone(), m.off + m.len / 2));
                }
                None => spots.push((x.name.clone(), format!("{s}/{}", x.name), x.len / 2)),
            }
        }
        let inside = spots.iter().filter(|(n, ..)| piece_of(n).is_some()).count();
        assert!(spots.len() > 8, "проверяемых мест всего {}", spots.len());
        assert!(inside > 8, "кусков контейнера проверяется всего {inside}");

        for (name, path, at) in spots {
            let whole = std::fs::read(&path).expect("файл сегмента");
            let mut bent = whole.clone();
            let byte =
                bent.get_mut(at as usize).unwrap_or_else(|| panic!("нет байта {at} в {path}"));
            *byte ^= 1;
            std::fs::write(&path, &bent).expect("порча");
            let bad = verify(&s).expect("сводка");
            assert!(
                bad.iter().any(|(n, v)| *n == name && matches!(v, Verdict::Content { .. })),
                "перевёрнутый бит в {name} не пойман"
            );
            // Длина та же — значит структурная проверка тут бессильна по
            // построению, и это ровно тот случай, ради которого сумма и заведена.
            assert_eq!(std::fs::metadata(&path).expect("длина").len(), whole.len() as u64);
            std::fs::write(&path, &whole).expect("возврат");
        }
        assert!(verify(&s).expect("сводка").is_empty(), "возвращённое всё ещё бито");
        std::fs::remove_dir_all(std::path::Path::new(&s).parent().unwrap()).ok();
    }

    /// Пропавший и лишний файлы тоже находка — и с кусками контейнера так же.
    ///
    /// ## Почему кусок портится правкой сводки, а файл — переименованием
    ///
    /// Находка здесь одна и та же: сводка и сегмент говорят разное. У файла
    /// разойтись проще всего переименованием — так его и уводят. У куска
    /// переименование значило бы переписать оглавление контейнера с его суммой,
    /// то есть подделать заодно и то, чем сверяют; расхождение вносится с другой
    /// стороны — правкой самой сводки, которая никакой суммой не накрыта. Обе
    /// стороны сверки при этом проверены: строка сводки без куска в оглавлении и
    /// кусок в оглавлении без строки в сводке.
    #[test]
    fn a_missing_or_extra_file_shows_up() {
        let s = seg("shape");
        // Файлом у упакованного сегмента лежит заголовок — его и уводим.
        std::fs::rename(format!("{s}/head.tsv"), format!("{s}/head.away")).expect("переименование");
        let bad = verify(&s).expect("сводка");
        assert!(bad.iter().any(|(n, v)| n == "head.tsv" && matches!(v, Verdict::Gone)));
        assert!(bad.iter().any(|(n, v)| n == "head.away" && matches!(v, Verdict::Extra)));
        std::fs::rename(format!("{s}/head.away"), format!("{s}/head.tsv")).expect("возврат");
        assert!(verify(&s).expect("сводка").is_empty(), "возвращённый файл всё ещё находка");

        let cpath = format!("{s}/{}", crate::container::FILE);
        let table = crate::container::Table::read(&cpath).expect("оглавление контейнера");
        let some = table.members().first().expect("кусков нет").name.clone();
        let dropped = inside_name(&some);
        let phantom = inside_name("нетакого.bin");

        let text = std::fs::read_to_string(format!("{s}/{FILE}")).expect("сводка");
        let mut kept: String = text
            .lines()
            .filter(|l| !l.starts_with(&format!("{dropped}\t")))
            .map(|l| format!("{l}\n"))
            .collect();
        assert_ne!(kept, text, "строка про кусок {some} из сводки не убралась");
        kept.push_str(&format!("{phantom}\t16\t00000000\n"));
        std::fs::write(format!("{s}/{FILE}"), &kept).expect("правка сводки");

        let bad = verify(&s).expect("сводка");
        assert!(
            bad.iter().any(|(n, v)| *n == phantom && matches!(v, Verdict::Gone)),
            "кусок, названный сводкой и отсутствующий в оглавлении, не найден: {:?}",
            bad.iter().map(|(n, _)| n.as_str()).collect::<Vec<_>>()
        );
        assert!(
            bad.iter().any(|(n, v)| *n == dropped && matches!(v, Verdict::Extra)),
            "кусок оглавления, которого нет в сводке, не найден: {:?}",
            bad.iter().map(|(n, _)| n.as_str()).collect::<Vec<_>>()
        );

        write(&s).expect("сводка пишется заново");
        assert!(verify(&s).expect("сводка").is_empty(), "переписанная сводка всё ещё расходится");
        std::fs::remove_dir_all(std::path::Path::new(&s).parent().unwrap()).ok();
    }

    /// Нечитаемый контейнер — отказ сводки, а не сводка, в которой нет кусков.
    ///
    /// ## Что ломалось бы без него
    ///
    /// Сводка, не назвавшая ни одного куска, выглядит ровно так же, как сводка
    /// сегмента, у которого кусков и нет: сверять нечего, и опись скажет «всё
    /// цело». Пиши её молча поверх нечитаемого контейнера — и переписанная
    /// сводка **узаконила бы** порчу: до неё сегмент не сходился со своей
    /// записью, после неё сходится, потому что записи больше нет.
    ///
    /// Заодно проверяется, что отказавшая сводка не тронула прежнюю: старая
    /// запись на месте и продолжает называть порчу.
    #[test]
    fn a_container_that_will_not_open_refuses_the_summary() {
        let s = seg("noopen");
        let path = format!("{s}/{}", crate::container::FILE);
        let mut whole = std::fs::read(&path).expect("контейнер");
        let old = std::fs::read(format!("{s}/{FILE}")).expect("сводка");
        // Опознание в начале файла: контейнер перестаёт разбираться целиком.
        whole[0] ^= 0xFF;
        std::fs::write(&path, &whole).expect("порча");

        let e = write(&s).expect_err("сводка написана по нечитаемому контейнеру");
        assert_eq!(e.kind(), std::io::ErrorKind::InvalidData, "не тот отказ: {e}");
        assert!(e.to_string().contains(crate::container::FILE), "отказ не называет файл: {e}");

        assert_eq!(std::fs::read(format!("{s}/{FILE}")).expect("сводка"), old, "сводка переписана");
        let bad = verify(&s).expect("сводка");
        assert!(
            bad.iter()
                .any(|(n, v)| n == crate::container::FILE && matches!(v, Verdict::Content { .. })),
            "порча контейнера не названа: {:?}",
            bad.iter().map(|(n, _)| n.as_str()).collect::<Vec<_>>()
        );

        std::fs::remove_dir_all(std::path::Path::new(&s).parent().unwrap()).ok();
    }

