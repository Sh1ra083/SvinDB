    /// Сводка кладётся рядом и подставляется переименованием, а не наливается по
    /// имени.
    ///
    /// ## Что ломалось бы без него
    ///
    /// На эту запись опираются как на условие «свежий сегмент не объявят битым»,
    /// и без неё рвутся два разных обещания.
    ///
    /// Первое: `fs::write` открывает имя на запись, обрезая то, что там лежало.
    /// Отказ на любом байте — кончилось место, отвалился носитель, погас свет —
    /// оставлял бы вместо прежней сводки обрезок, а обрезанная сводка не
    /// «отсутствует», она врёт: недостающие строки читаются как «файла нет в
    /// сводке», то есть заметкой, и куски **молча** теряют покрытие сверкой, а
    /// недостающая строка про `seg.dat` объявляет поломкой здоровый сегмент.
    /// Всё остальное на этом пути доводится честно (`sync_all` у контейнера,
    /// `sync_dir` после переименования, атомарный заголовок) — сводка была
    /// единственным шагом без обеих гарантий.
    ///
    /// Второе: перекладка и пересборка фильтра ходят по каталогам, которых не
    /// создавали. `fs::write` идёт по символической ссылке и по имени `sums.tsv`
    /// перепишет чужой файл — при том что читает сводку [`read`] уже без
    /// следования по ссылке.
    ///
    /// Отказ записи устраивается тем, что каталог сегмента становится
    /// незаписываемым: положить рядом нечего, а прежней сводке ничего не
    /// делается. Голому `fs::write` каталог не нужен вовсе — файл уже
    /// существует, — поэтому этого отказа он не выдаст и проверку не пройдёт.
    #[cfg(unix)]
    #[test]
    fn writing_the_summary_never_pours_over_the_old_one() {
        use std::os::unix::fs::PermissionsExt;
        let s = seg("write");
        let up = std::path::Path::new(&s).parent().expect("каталог индекса").display().to_string();
        let path = format!("{s}/{FILE}");
        let before = std::fs::read(&path).expect("сводка есть");
        assert!(before.len() > 100, "проверять нечего: сводка пуста");

        // Отказ записи не уничтожает прежнюю сводку.
        let was = std::fs::metadata(&s).expect("каталог сегмента").permissions().mode();
        std::fs::set_permissions(&s, std::fs::Permissions::from_mode(0o500)).expect("права сняты");
        let denied = write(&s);
        std::fs::set_permissions(&s, std::fs::Permissions::from_mode(was))
            .expect("права возвращены");
        let e = denied.expect_err("запись в незаписываемый каталог обязана отказать");
        assert!(e.to_string().contains(FILE), "отказ обязан назвать файл: {e}");
        assert_eq!(
            std::fs::read(&path).expect("сводка на месте"),
            before,
            "отказ записи уничтожил прежнюю сводку"
        );

        // Ссылка по имени сводки заменяется, а не переписывается насквозь.
        let outside = format!("{up}/чужая.tsv");
        std::fs::write(&outside, "чужое содержимое\n").expect("чужой файл");
        std::fs::remove_file(&path).expect("сводка удаляется");
        std::os::unix::fs::symlink(&outside, &path).expect("ссылка");
        write(&s).expect("сводка пишется");
        assert_eq!(
            std::fs::read_to_string(&outside).expect("чужой файл"),
            "чужое содержимое\n",
            "запись ушла по ссылке и переписала чужой файл"
        );
        assert!(
            std::fs::symlink_metadata(&path).expect("сводка").file_type().is_file(),
            "на месте сводки осталась ссылка, а не сводка"
        );
        assert_eq!(std::fs::read(&path).expect("новая сводка"), before, "сводка сошлась не с той");

        // Временное имя не остаётся: сирота под ним — заметка `check`, и
        // оставлять её после успешной записи незачем.
        let left: Vec<String> = std::fs::read_dir(&s)
            .expect("каталог сегмента")
            .filter_map(|e| e.ok())
            .map(|e| e.file_name().to_string_lossy().to_string())
            .filter(|n| n.starts_with('.'))
            .collect();
        assert!(left.is_empty(), "после записи остались временные имена: {left:?}");

        std::fs::remove_dir_all(&up).ok();
    }

