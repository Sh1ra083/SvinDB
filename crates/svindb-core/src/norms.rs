//! Длина документа: квантование в байт и обратно, константы BM25.

pub const K1: f64 = 1.2;
/// Сила нормировки на длину.
pub const B: f64 = 0.75;

/// До этой длины уровень равен самой длине — там ошибка недопустима.
pub const LEVEL_EXACT_UPTO: f64 = 32.0;
/// Потолок шкалы. Всё, что длиннее, ранжируется как документ этой длины.
pub const LEVEL_MAX: f64 = 65_536.0;

/// Уровней на один e-кратный рост длины.
///
/// Выводится из требования «старший уровень соответствует ровно `LEVEL_MAX`»,
/// а не подбирается: `32 + ln(65536/32)·STEPS = 255`.
#[inline(always)]
pub fn level_steps() -> f64 {
    (255.0 - LEVEL_EXACT_UPTO) / (LEVEL_MAX / LEVEL_EXACT_UPTO).ln()
}

/// Уровень — в представительную длину.
///
/// Аргумент — байт, значений ровно 256. Таблица занимает два килобайта и лежит
/// в кеше целиком. Литералы сверяются с формулой с допуском в один ULP, который
/// учитывает различия реализации `exp` между поддерживаемыми платформами.
#[inline(always)]
pub fn decode_level(q: u8) -> f64 {
    LEVELS[q as usize]
}

/// Длина в токенах — в номер уровня.
///
/// Нулевая длина даёт нулевой уровень: пустое поле обязано отличаться от поля
/// в один токен, иначе документ без заголовка получит скор документа с
/// односложным заголовком.
pub fn level(len: usize) -> u8 {
    if len <= LEVEL_EXACT_UPTO as usize {
        return len as u8;
    }
    let steps = level_steps();
    (LEVEL_EXACT_UPTO + steps * (len as f64 / LEVEL_EXACT_UPTO).ln()).min(255.0).round() as u8
}

/// Множитель длины BM25 для документа с уровнем `q` при средней длине `avgdl`.
///
/// Одно место на весь проект: индексатор считает по нему потолок блока, а поиск
/// — вклад документа. Разъедься они — потолок перестал бы быть потолком, и
/// отсечение начало бы терять документы молча.
#[inline(always)]
pub fn nu(q: u8, avgdl: f64) -> f64 {
    1.0 / (K1 * (1.0 - B) + K1 * B * decode_level(q) / avgdl.max(1.0) + 1.0)
}
/// Длинная часть знаменателя BM25: `K1·((1−B) + B·|d|/avgdl)`.
#[inline(always)]
pub fn dl_part(q: u8, avgdl: f64) -> f64 {
    K1 * (1.0 - B) + K1 * B * decode_level(q) / avgdl.max(1.0)
}

/// Насыщение по частоте: `tf/(tf + d)`.
#[inline(always)]
pub fn sat(tf: u32, d: f64) -> f64 {
    let t = tf as f64;
    t / (t + d)
}

/// Множитель фиксированной точки для суммы длин поля.
///
/// ## Почему сумма целая, а не `f64`
///
/// Из суммы длин считается средняя, из средней — таблицы нормировки, из таблиц —
/// скор. Складывая длины в `f64`, мы получили бы сумму, **зависящую от порядка
/// слагаемых**: у семи сегментов и у двадцати трёх последние биты разойдутся, а
/// с ними разойдутся средняя, таблицы и выдача. То есть ранжирование опять
/// зависело бы от того, как приём нарезал корпус, — ровно от того, что этой
/// статистикой и чинится.
///
/// Целое складывается точно и в любом порядке. Поэтому глобальная средняя длина
/// становится функцией **мультимножества сегментов**, а не их истории, и
/// сравнивать скоры разных раскладок можно побитово, а не «в пределах допуска».
///
/// Двадцать бит дробной части: длина хранится с точностью до миллионной доли, а
/// потолок суммы — пятьдесят миллионов документов на предельный уровень 65536 на
/// `FIXED`, то есть около 3.4·10¹⁸ при пределе `u64` в 1.8·10¹⁹.
pub const FIXED: u64 = 1 << 20;

/// Длина уровня в фиксированной точке.
#[inline]
pub fn fixed_len(q: u8) -> u64 {
    (decode_level(q) * FIXED as f64).round() as u64
}

/// Средняя длина по сумме в фиксированной точке и числу документов.
///
/// Пол в единицу тот же, что и у посегментной средней: ноль в знаменателе
/// нормировки обратил бы вклад в бесконечность.
pub fn avgdl_of(fixed: u64, docs: u64) -> f64 {
    if docs == 0 {
        return 1.0;
    }
    (fixed as f64 / FIXED as f64 / docs as f64).max(1.0)
}

/// Во сколько раз может вырасти вклад документа при переходе от посегментной
/// средней длины `baked` к общей `effective`.
///
/// ## Зачем это вообще нужно
///
/// Потолки блоков и списков считаются **при сборке сегмента** и по его
/// собственной средней длине. Отсечение сравнивает их с порогом и выбрасывает
/// всё, что ниже. Если поиск начнёт считать вклад по общей средней, а потолки
/// останутся посегментными, то при `effective > baked` настоящий вклад окажется
/// **выше** сохранённого потолка — и отсечение начнёт молча терять выдачу.
/// Ровно от этого предостерегает [`nu`].
///
/// Пересчитать потолок из сохранённых `(qmax, tfmax)` нельзя: пара, дающая
/// максимум при одной средней, при другой максимума не даёт. Проверяется это
/// на числах — постинги (tf=1, L=1) и (tf=20, L=400) при K1=1.2, B=0.75: при
/// средней 10 больше первый (0.7194 против 0.3552), при средней 1000 — второй
/// (0.9681 против 0.7687). Пересчёт по сохранённой паре дал бы 0.7687, то есть
/// на четверть **ниже** настоящего максимума.
///
/// ## Почему множитель верен
///
/// Вклад — `sat(tf, d) = tf/(tf+d)`, где `d(q) = K1(1−B) + K1·B·L(q)/avgdl`.
/// Отношение вкладов при двух средних: `r = (tf + d_A)/(tf + d_E)`.
///
/// По `tf` оно убывает (производная `(d_E − d_A)/(tf + d_E)²` отрицательна при
/// `d_A > d_E`), значит наибольшее — при наименьшей возможной частоте, то есть
/// при `tf = 1`.
///
/// По длине оно растёт: подставив `d`, получаем `(A + k_A·L)/(A + k_E·L)` с
/// `A = 1 + K1(1−B)`, и при `effective > baked` коэффициент `k_A` больше `k_E`,
/// то есть функция возрастает. Значит наибольшее — при наибольшей длине,
/// реально встреченной в поле, а её и хранит `lmax`.
///
/// Перебор по всем 256 уровням — не приближение, а прямое вычисление этого
/// максимума; ограничение перебора уровнем `lmax` и делает запас умеренным.
/// Единица возвращается, когда общая средняя не больше посегментной: тогда
/// вклад только падает, и сохранённый потолок остаётся потолком сам по себе.
pub fn lift_of(baked: f64, effective: f64, lmax: u8) -> f64 {
    // Порядок проверок важен: сначала конечность, потом сравнение. NaN не
    // сравним ни с чем, и `effective > baked` на нём ложно — то есть подъёма
    // не будет, что и требуется, но полагаться на это молча нельзя.
    if !baked.is_finite() || !effective.is_finite() || effective <= baked {
        return 1.0;
    }
    let mut best = 1.0f64;
    for q in 0..=lmax {
        let r = (1.0 + dl_part(q, baked)) / (1.0 + dl_part(q, effective));
        if r > best {
            best = r;
        }
    }
    best
}

/// Потолок множителя длины: самый короткий возможный документ.
#[inline(always)]
pub fn nu_max(avgdl: f64) -> f64 {
    1.0 / (K1 * (1.0 - B) + K1 * B * 1.0 / avgdl.max(1.0) + 1.0)
}

/// Ближайшее `f32`, которое **не меньше** заданного значения.
///
/// Нужно всюду, где потолок кладётся на диск сокращённой разрядностью. Обычное
/// приведение округляет к ближайшему, то есть в половине случаев **вниз**, — и
/// тогда потолок перестаёт быть потолком. Ошибка в один младший бит, но природа
/// у неё та же, что у ошибки в целый порядок: отсечение вправе выбросить
/// документ, чей настоящий вклад выше сохранённой границы, и сделает это молча.
///
/// Округление вверх безопасно всегда: завышенная граница лишь ослабляет
/// отсечение, то есть стоит времени, а не выдачи.
#[inline]
pub fn up_f32(v: f64) -> f32 {
    let r = v as f32;
    if !r.is_finite() || (r as f64) >= v {
        return r;
    }
    // Положительные `f32` идут по возрастанию вместе со своими битами, поэтому
    // следующее представимое — это соседний код.
    f32::from_bits(r.to_bits() + 1)
}

