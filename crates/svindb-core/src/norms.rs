/// Раскладывает полосы длин так, чтобы одинаковое содержимое не повторялось.
///
/// ## Зачем
///
/// ## Почему общая полоса, а не признак «полосы нет»
///
/// Возвращает содержимое `norms.bin` и номер полосы для каждого поля. Полосы
/// лежат в порядке возрастания номера.
pub fn bands(per_field: &[Vec<u8>]) -> (Vec<u8>, Vec<u32>) {
    let mut out: Vec<u8> = Vec::new();
    let mut band = vec![0u32; per_field.len()];
    // Уровень → номер уже записанной полосы. Различных постоянных уровней
    // единицы, поэтому список, а не отображение.
    let mut shared: Vec<(u8, u32)> = Vec::new();
    let mut next = 0u32;
    for (f, levels) in per_field.iter().enumerate() {
        let flat = levels.first().copied().filter(|q| levels.iter().all(|x| x == q));
        band[f] = match flat.and_then(|q| shared.iter().find(|&&(v, _)| v == q).map(|&(_, b)| b)) {
            Some(b) => b,
            None => {
                let b = next;
                next += 1;
                if let Some(q) = flat {
                    shared.push((q, b));
                }
                out.extend_from_slice(levels);
                b
            }
        };
    }
    (out, band)
}

#[cfg(test)]
mod lift_tests {
    use super::*;

    /// Поднятый потолок обязан накрывать настоящий вклад при общей средней.
    ///
    /// Это главное свойство: потолок ниже вклада — молчаливая потеря выдачи.
    /// Перебираются обе средних, все уровни до `lmax` и частоты; сравнение идёт
    /// с потолком, уже прошедшим округление вверх до `f32`, — на диске он лежит
    /// именно так.
    #[test]
    fn a_lifted_ceiling_never_falls_below_the_real_contribution() {
        for &baked in &[1.0f64, 3.5, 10.0, 100.0, 1000.0] {
            for &effective in &[1.0f64, 3.5, 10.0, 100.0, 1000.0] {
                for &lmax in &[1u8, 32, 128, 200, 255] {
                    let lift = lift_of(baked, effective, lmax);
                    for q in 0..=lmax {
                        for tf in [1u32, 2, 3, 7, 20, 100, 1000] {
                            let local = up_f32(sat(tf, dl_part(q, baked))) as f64;
                            let global = sat(tf, dl_part(q, effective));
                            assert!(
                                lift * local >= global - 1e-12,
                                "A={baked} E={effective} lmax={lmax} q={q} tf={tf}: \
                                 потолок {} ниже вклада {global}",
                                lift * local
                            );
                        }
                    }
                }
            }
        }
    }

    /// Совпали средние — подъёма нет. Иначе одинаковый по составу индекс,
    /// лежащий в одном сегменте, отсекал бы слабее, чем должен.
    #[test]
    fn there_is_no_lift_when_the_averages_agree() {
        for &a in &[1.0f64, 7.25, 100.0, 65536.0] {
            assert_eq!(lift_of(a, a, 255), 1.0);
            // И когда общая средняя **меньше** посегментной: вклад тогда только
            // падает, и сохранённый потолок остаётся потолком сам по себе.
            assert_eq!(lift_of(a, a / 2.0, 255), 1.0);
        }
    }

    /// Запас растёт с расхождением средних и с наибольшей длиной поля.
    ///
    /// Проверка не про красоту: если бы подъём не зависел от `lmax`, поле из
    /// коротких документов платило бы за длину, которой в нём нет, и отсечение
    /// слабело бы на ровном месте.
    #[test]
    fn the_lift_grows_with_the_gap_and_with_the_longest_document() {
        assert!(lift_of(10.0, 20.0, 255) > lift_of(10.0, 11.0, 255));
        assert!(lift_of(10.0, 1000.0, 255) > lift_of(10.0, 1000.0, 32));

        // Запас ограничен тем, что в поле действительно встречалось. Поле, где
        // самый длинный документ короток, платит меньше поля с длинным хвостом
        // — при одном и том же расхождении средних. Ради этого `lmax` и лежит
        // в заголовке: без него перебор шёл бы до предельного уровня, и запас
        // выходил бы кратно больше нужного.
        let short_tail = lift_of(10.0, 1000.0, 32);
        let long_tail = lift_of(10.0, 1000.0, 255);
        assert!(
            short_tail < long_tail,
            "короткий хвост {short_tail} платит не меньше длинного {long_tail}"
        );
        // И предел перебора действительно ограничивает: с `lmax` до предельного
        // уровня запас вырастает на порядок.
        assert!(
            long_tail > short_tail * 5.0,
            "предел перебора ни на что не влияет: {short_tail} против {long_tail}"
        );
    }
}

