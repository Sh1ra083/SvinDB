//! Файл, отображённый в память, и чтение плоских массивов чисел.

use std::fs::File;
use std::io::Read;
use std::os::raw::c_void;
use std::os::unix::io::AsRawFd;

extern "C" {
    fn mmap(addr: *mut c_void, len: usize, prot: i32, flags: i32, fd: i32, off: i64)
        -> *mut c_void;
    fn munmap(addr: *mut c_void, len: usize) -> i32;
    fn msync(addr: *mut c_void, len: usize, flags: i32) -> i32;
    /// Нужен [`Region::sync`]: `msync` берёт только адрес, кратный странице, а
    /// зашитые 4096 неверны — на aarch64 у macOS страница 16 КБ, и опущенный до
    /// 4096 адрес остался бы невыровненным.
    fn getpagesize() -> i32;
    /// Совет ядру, как эту область будут читать. Ошибку возвращает, но она
    /// ничего не значит: совет — это совет, и невыполненный он всего лишь
    /// оставляет прежнее поведение.
    fn madvise(addr: *mut c_void, len: usize, advice: i32) -> i32;
}

/// «Понадобится скоро» — ядру велено читать наперёд, целыми окнами.
///
/// Единственный совет, который узел даёт ядру, и не случайно: он **разовое
/// действие**, а не изменение свойств области. Советы, меняющие флаги области
/// (`MADV_RANDOM`, `MADV_SEQUENTIAL`), заставляют ядро расщеплять отображение
/// по границам совета, а число областей у нас под отдельным пределом — см.
/// [`map_budget_with`]. Разбор, почему `MADV_RANDOM` на постинги был убран, — в
/// `index::open`.
const MADV_WILLNEED: i32 = 3;
/// Удалить private file-backed PTE и позволить page cache освободиться.
#[cfg(target_os = "linux")]
const MADV_DONTNEED: i32 = 4;

/// Размер страницы этой машины. Спрашивается один раз.
///
/// Зашитые 4096 неверны и по-разному: на aarch64 у macOS страница 16 КБ, у
/// ppc64 бывает 64 КБ. Прогрев с шагом 4096 на такой машине трогает одну и ту
/// же страницу по четыре и по шестнадцать раз — работа, которой не видно ни в
/// одном счётчике, потому что каждое обращение попадает в уже загруженную
/// страницу.
pub fn page_size() -> usize {
    use std::sync::atomic::{AtomicUsize, Ordering};
    static CACHED: AtomicUsize = AtomicUsize::new(0);
    let seen = CACHED.load(Ordering::Relaxed);
    if seen != 0 {
        return seen;
    }
    let n = unsafe { getpagesize() };
    // Ноль или отрицательное — ответ, которого не бывает; берём общий минимум,
    // потому что он верен всегда, только расточителен.
    let n = if n > 0 { n as usize } else { 4096 };
    CACHED.store(n, Ordering::Relaxed);
    n
}

/// Сколько байт и сколько времени позволено греть.
///
/// ## Зачем предел у прогрева
///
/// Прогрев затягивает страницы в кеш **ядра**, а не в кучу процесса, и потому
/// не виден ни одному счётчику памяти узла. Отсюда соблазн считать его
/// бесплатным. Он не бесплатен: кеш страниц конечен, и всё, что в него
/// затянуто, вытеснило что-то другое — в том числе страницы соседних служб на
/// той же машине. На индексе, который больше памяти, прогрев без предела
/// заведомо вытесняет собственное начало собственным концом.
///
/// ## Почему предел объявлен, а не подобран
///
/// Оба числа приходят снаружи и печатаются в журнал вместе с тем, чем кончилось.
/// Молчаливое усечение читается как «прогрето всё» — а это ровно то, по чему
/// оператор потом объясняет себе холодные первые запросы.
#[derive(Debug)]
pub struct WarmBudget {
    bytes: usize,
    until: Option<std::time::Instant>,
    /// Сработал ли предел хоть раз.
    stopped: bool,
}

impl WarmBudget {
    /// Предел в байтах и миллисекундах. Ноль в любом из них — «без предела».
    pub fn new(bytes: usize, ms: u64) -> WarmBudget {
        WarmBudget {
            bytes: if bytes == 0 { usize::MAX } else { bytes },
            until: (ms > 0)
                .then(|| std::time::Instant::now() + std::time::Duration::from_millis(ms)),
            stopped: false,
        }
    }

    pub fn unlimited() -> WarmBudget {
        WarmBudget::new(0, 0)
    }

    /// Можно ли греть кусок в `n` байт. `false` — предел исчерпан.
    pub fn take(&mut self, n: usize) -> bool {
        if self.stopped {
            return false;
        }
        if self.until.is_some_and(|t| std::time::Instant::now() >= t) {
            self.stopped = true;
            return false;
        }
        // Кусок больше остатка не греется вовсе, а не наполовину: греть его
        // частью значило бы резать отображение и трогать страницы поштучно.
        if n > self.bytes {
            self.stopped = true;
            return false;
        }
        self.bytes -= n;
        true
    }

    /// Оборвался ли прогрев по пределу.
    pub fn stopped(&self) -> bool {
        self.stopped
    }
}

/// Просит ядро прочесть область наперёд. Отказ — не ошибка.
fn advise_soon(ptr: *const u8, len: usize) {
    if ptr.is_null() || len == 0 {
        return;
    }
    let flag = MADV_WILLNEED;
    // Адрес обязан быть кратен странице — тот же довод, что у `msync`.
    let page = page_size();
    let base = ptr as usize;
    let down = base & !(page - 1);
    let len = len + (base - down);
    // Возврат намеренно выброшен: совет, который ядро не приняло, оставляет всё
    // как было. Отказывать запросу из-за неуслышанного совета было бы хуже, чем
    // не советовать вовсе.
    unsafe {
        madvise(down as *mut c_void, len, flag);
    }
}

const PROT_READ: i32 = 1;
const PROT_WRITE: i32 = 2;
const MAP_SHARED: i32 = 1;
const MAP_PRIVATE: i32 = 2;

/// Флаг «дождаться записи» у `msync`. У macOS и Linux он разный.
#[cfg(target_os = "macos")]
const MS_SYNC: i32 = 0x0010;
#[cfg(not(target_os = "macos"))]
const MS_SYNC: i32 = 4;

/// Файл, отображённый в память.
///
/// Держат его по значению теперь только двое, и оба по причине: карта живых —
/// единственная у нас область **на запись**, правящаяся атомарно через
/// [`word`](Self::word), и словарь хранимого поля, чьё отображение делится между
/// распаковщиками записей через `Arc`. Всё прочее держит [`Region`] — кусок
/// отображения со своими границами; заводя новый файл сегмента, берите его.
pub struct Mapped {
    ptr: *const u8,
    len: usize,
    /// Открыто ли отображение на запись и разделяемо ли оно с файлом.
    shared: bool,
    /// Память под куском, когда за ним стоит куча, а не файл.
    ///
    /// Поле не читается ничем — и не должно: вся его работа в том, чтобы
    /// **существовать**, пока жив кусок. Оно же отличает кучу от отображения
    /// там, где разница есть: `Drop` не зовёт `munmap` на память, которую не
    /// отображал, а [`is_mapped`](Self::is_mapped) не считает её областью у
    /// ядра — потолок процесса на число областей до кучи не относится.
    ///
    /// Слова, а не байты: правка куска идёт через [`word`](Self::word), то есть
    /// через `AtomicU64`, и восьмибайтное выравнивание обязано быть настоящим.
    /// `Vec<u8>` выровнен по одному байту, и атомарное обращение к нему —
    /// неопределённое поведение, а не медленное чтение.
    owned: Option<Box<[u64]>>,
}

// Отображение на чтение после создания не меняется, поэтому делить его между
// потоками безопасно. Ровно на этом стоит горячая подмена сегментов: поиск идёт
// по снимку, пока писатель готовит следующий.
//
// Разделяемое отображение на запись тоже делится между потоками, но с условием,
// которое обязано соблюдаться вызывающим: **править его можно только через
// [`Mapped::word`]**, то есть атомарными операциями. Единственный такой файл —
// карта живых, и там правится ровно один бит на удаление.
unsafe impl Sync for Mapped {}
unsafe impl Send for Mapped {}

/// Объясняет отказ `mmap`, если он про **число** отображений, а не про память.
///
/// ## Зачем переписывать чужое сообщение
///
/// `ENOMEM` от `mmap` почти никогда не означает «кончилась память». У ядра есть
/// потолок на число областей отображения у процесса — на Linux это
/// `vm.max_map_count`, по умолчанию 65530, — и упирается в него не память, а
/// **число сегментов**. Сколько именно областей уходит на сегмент, зависит от
/// того, упакован ли он: у упакованного их [`MIN_MAPS_PER_SEGMENT`] — контейнер
/// `seg.dat` и карта живых, — сколько бы кусков внутри ни лежало; у собранного
/// до контейнера область уходит на каждый непустой файл, замерено полтора-два
/// десятка при схеме по умолчанию (два текстовых поля с хранением) и до сорока
/// с колонками, векторами и широкой схемой. То есть при пределе 65530 россыпь
/// перестаёт открываться уже на нескольких тысячах сегментов, а контейнер — на
/// без малого тридцати тысячах.
///
/// Голое «cannot allocate memory» отправляет искать не туда: смотрят на
/// свободную память, видят её вдоволь и не находят причины. Отказ обязан назвать
/// и предел, и то, чем его поднять.
///
/// Размер отображаемого файла в сообщении не лишний: он отличает «упёрлись в
/// число» (файл мелкий, а памяти вдоволь) от настоящей нехватки адресного
/// пространства.
fn exhausted(e: std::io::Error, len: usize) -> std::io::Error {
    // Разбирается только нехватка. Прочие причины — путь, права, вид файла —
    // объясняют себя сами, и подменять их догадкой было бы хуже.
    if e.kind() != std::io::ErrorKind::OutOfMemory {
        return e;
    }
    let hint = if cfg!(target_os = "linux") {
        "предел числа областей отображения у процесса: \
         посмотрите `sysctl vm.max_map_count` и поднимите его"
    } else {
        "предел числа областей отображения у процесса"
    };
    std::io::Error::new(
        std::io::ErrorKind::OutOfMemory,
        format!(
            "{e}: отображение {len} байт не легло. Обычно это не память, а {hint}. \
             Областей на сегмент {MIN_MAPS_PER_SEGMENT}, если он упакованный — seg.dat и карта \
             живых; у собранного до контейнера область уходит на каждый непустой файл, \
             полтора-два десятка при схеме по умолчанию и больше при широкой. Поэтому предел \
             упирается в число сегментов — их уменьшает укрупнение (--target)"
        ),
    )
}

// ── Чтение чисел из области: одно правило на отображение и на его кусок ──
//
// Правило одно: **за границей — ноль**, а не падение. На нём стоит горячий путь
// — хвостовой блок списка читается с запасом, и проверка длины на каждый
// документ стоила бы дороже всего, что она ловит.
//
// Тела вынесены из [`Mapped`] в свободные функции ровно затем, чтобы у правила
// была одна редакция. Держи его двумя — своё у отображения и своё у куска, — и
// разойтись они могли бы на любой правке; а расхождение здесь означает чтение
// **соседнего** куска контейнера вместо нулей, то есть правдоподобный мусор
// вместо пустоты.
//
// `ptr` и `len` обязаны описывать живую область: указатель либо нулевой, либо
// начало `len` отображённых байт, которые переживут вызов. Вызывающих ровно двое
// и оба в этом файле — [`Mapped`] и [`Region`].

#[inline(always)]
fn read_u8(ptr: *const u8, len: usize, off: usize) -> u8 {
    if off >= len {
        return 0;
    }
    unsafe { *ptr.add(off) }
}

#[inline(always)]
fn read_u16(ptr: *const u8, len: usize, off: usize) -> u16 {
    if off + 2 > len {
        return 0;
    }
    unsafe { std::ptr::read_unaligned(ptr.add(off) as *const u16).to_le() }
}

#[inline(always)]
fn read_u32(ptr: *const u8, len: usize, off: usize) -> u32 {
    if off + 4 > len {
        return 0;
    }
    unsafe { std::ptr::read_unaligned(ptr.add(off) as *const u32).to_le() }
}

#[inline(always)]
fn read_u64(ptr: *const u8, len: usize, off: usize) -> u64 {
    if off + 8 > len {
        return 0;
    }
    unsafe { std::ptr::read_unaligned(ptr.add(off) as *const u64).to_le() }
}

/// Срез области. Выход за границу обрезается, а не роняет процесс: длина списка
/// известна из словаря, и хвостовой блок читается с запасом.
///
/// Время жизни здесь ничем не связано, и связать его обязан вызывающий: у обоих
/// оно приходит из `&self`, то есть срез живёт не дольше держателя отображения.
#[inline(always)]
fn read_slice<'a>(ptr: *const u8, len: usize, off: usize, n: usize) -> &'a [u8] {
    if ptr.is_null() || off >= len {
        return &[];
    }
    let end = off.saturating_add(n).min(len);
    unsafe { std::slice::from_raw_parts(ptr.add(off), end - off) }
}

/// Затягивает область в кеш страниц и отдаёт число тронутых байт.
///
/// ## Почему совет ядру, а не обход по байту
///
/// Прежде прогрев читал по байту из каждой страницы. Это работало, но платило
/// дважды: страничным отказом на **каждую** страницу — а это переход в ядро,
/// поиск в кеше, чтение с диска по одной странице — и шагом в зашитые 4096,
/// который на машине со страницей в 16 КБ трогает одну и ту же страницу
/// четырежды.
///
/// `MADV_WILLNEED` говорит ядру то же самое одним вызовом, и ядро читает
/// **окнами**, как ему удобно, а не по странице. Байтовый обход остаётся
/// запасным путём: совет — это совет, ядро вправе его не услышать, и тогда
/// прогрев обязан всё-таки случиться.
#[inline]
fn touch_pages(ptr: *const u8, len: usize) -> usize {
    if ptr.is_null() || len == 0 {
        return 0;
    }
    advise_soon(ptr, len);
    let mut sink = 0usize;
    let mut at = 0usize;
    let step = page_size();
    while at < len {
        sink += unsafe { *ptr.add(at) } as usize;
        at += step;
    }
    std::hint::black_box(sink);
    len
}

impl Mapped {
    /// Пустое отображение — для файлов, которых нет по построению.
    pub fn empty() -> Mapped {
        Mapped { ptr: std::ptr::null(), len: 0, shared: false, owned: None }
    }

    /// Кусок в памяти: те же байты, но без файла под ними.
    ///
    /// ## Зачем отображению вариант без отображения
    ///
    /// Сегмент, собранный в память, обязан читаться **тем же** кодом, что и
    /// лежащий на диске: разойдись они, у движка стало бы две реализации разбора
    /// одного формата, и вторая начала бы врать молча. Поэтому память
    /// притворяется отображением здесь, в самом низу, а не выше — там, где
    /// пришлось бы разводить по ветвям разбор словаря, постингов и колонок.
    ///
    /// Долговечности у такого куска нет и не подразумевается: за неё отвечает
    /// журнал, а [`sync`](Self::sync) на нём ничего не делает — синхронизировать
    /// с файлом нечего.
    pub fn of_bytes(bytes: &[u8]) -> Mapped {
        if bytes.is_empty() {
            return Mapped::empty();
        }
        // Хвост последнего слова остаётся нулевым: длина куска считается по
        // `len`, а не по числу слов, и за неё никто не заглядывает.
        let mut words = vec![0u64; bytes.len().div_ceil(8)].into_boxed_slice();
        // Приёмник длиннее источника и выровнен под слово — обе величины взяты
        // строкой выше, а не обещаны вызывающим.
        unsafe {
            std::ptr::copy_nonoverlapping(
                bytes.as_ptr(),
                words.as_mut_ptr() as *mut u8,
                bytes.len(),
            );
        }
        // Указатель снимается до перемещения `words` в структуру и остаётся
        // годным после: перемещается описатель, а не сама область на куче.
        let ptr = words.as_ptr() as *const u8;
        Mapped { ptr, len: bytes.len(), shared: false, owned: Some(words) }
    }

    pub fn open(path: &str) -> std::io::Result<Mapped> {
        let f = crate::fs::open_regular(std::path::Path::new(path), true, false)?;
        Self::open_file(f, false)
    }

    /// Отображает отдельный обычный файл: жёсткая ссылка на чужой inode не
    /// принимается. Это нужно при чтении недоверенного snapshot.
    pub fn open_private(path: &str) -> std::io::Result<Mapped> {
        let f = crate::fs::open_private_regular(std::path::Path::new(path))?;
        Self::open_file(f, false)
    }

    /// Открывает файл сегмента, называя настоящую причину отказа.
    fn open_file(f: File, shared: bool) -> std::io::Result<Mapped> {
        let len = usize::try_from(f.metadata()?.len()).map_err(|_| {
            std::io::Error::new(
                std::io::ErrorKind::InvalidData,
                "файл не помещается в адресное пространство",
            )
        })?;
        if len == 0 {
            return Ok(Mapped::empty());
        }
        let (prot, flags) =
            if shared { (PROT_READ | PROT_WRITE, MAP_SHARED) } else { (PROT_READ, MAP_PRIVATE) };
        let p = unsafe { mmap(std::ptr::null_mut(), len, prot, flags, f.as_raw_fd(), 0) };
        if p as isize == -1 {
            return Err(exhausted(std::io::Error::last_os_error(), len));
        }
        drop(f);
        LIVE_MAPS.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
        MAPS_MADE.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
        #[cfg(test)]
        thread_maps_add(1);
        Ok(Mapped { ptr: p as *const u8, len, shared, owned: None })
    }

    /// Отображает файл на запись, разделяя его с файлом и с другими читателями.
    ///
    /// Это не «то же самое, только с флагом». Обычное отображение —
    /// `MAP_PRIVATE`: правка в нём видна только правящему и в файл не попадает.
    /// Разделяемое отображение делает правку **сразу видимой всем**, кто
    /// отобразил тот же файл, и рано или поздно записывает её на диск.
    pub fn open_rw(path: &str) -> std::io::Result<Mapped> {
        // Writable mmap не принимает hardlink: иначе удаление документа в
        // одном индексе меняло бы inode другого индекса за его пределами.
        let f = crate::fs::open_private_regular_rw(std::path::Path::new(path), true, true)?;
        Self::open_file(f, true)
    }

    /// Слово как атомарное — единственный законный способ править отображение.
    ///
    /// `None`, если слова с таким номером нет. Выравнивание обеспечено самим
    /// `mmap`: он отдаёт адрес, кратный странице.
    ///
    /// Читать так можно любое отображение: атомарное чтение не хуже обычного.
    /// А вот **писать** — только разделяемое, см. [`is_shared`](Self::is_shared);
    /// запись в отображение на чтение это не ошибка компиляции, а падение.
    #[inline]
    pub fn word(&self, i: usize) -> Option<&std::sync::atomic::AtomicU64> {
        if self.ptr.is_null() || (i + 1) * 8 > self.len {
            return None;
        }
        Some(unsafe { &*(self.ptr.add(i * 8) as *const std::sync::atomic::AtomicU64) })
    }

    /// Открыто ли отображение на запись и делится ли оно с файлом.
    #[inline]
    pub fn is_shared(&self) -> bool {
        self.shared
    }

    /// Занимает ли это отображение область у ядра.
    ///
    /// Пустое — не занимает: `open_file` на нулевом файле не зовёт `mmap` вовсе.
    /// Нужно для подсчёта, много ли областей держит индекс: их число, а не
    /// память, упирается в потолок процесса.
    #[inline]
    pub fn is_mapped(&self) -> bool {
        !self.ptr.is_null() && self.owned.is_none()
    }

    /// Стоит ли за куском куча, а не файл.
    ///
    /// Спрашивает это карта живых: правка разделяемого отображения видна всем,
    /// кто отобразил тот же файл, а правка кучи — всем, кто держит этот самый
    /// кусок. Второе не слабее первого, пока держатель один на всех, и у
    /// сегмента в памяти он именно такой: `Arc<Index>`, а внутри него — эта
    /// область. Отображение же на чтение править нельзя вовсе, и отличать его
    /// от кучи обязательно.
    #[inline]
    pub fn is_memory(&self) -> bool {
        self.owned.is_some()
    }

    /// Сбрасывает правки на диск и ждёт завершения.
    ///
    /// Без этого правки живут в кеше страниц: смерть процесса им не страшна —
    /// кеш принадлежит ядру, — а вот потеря питания страшна. Зовётся не на
    /// каждое удаление, а на сброс и на заходе обслуживания.
    pub fn sync(&self) -> std::io::Result<()> {
        if !self.shared || self.ptr.is_null() {
            return Ok(());
        }
        let rc = unsafe { msync(self.ptr as *mut c_void, self.len, MS_SYNC) };
        if rc != 0 {
            return Err(std::io::Error::last_os_error());
        }
        Ok(())
    }

    pub fn len_bytes(&self) -> usize {
        self.len
    }

    pub fn is_empty(&self) -> bool {
        self.len == 0
    }

    /// Затягивает отображение в кеш страниц и отдаёт число тронутых байт.
    ///
    /// Ядру эта разница не видна: для него все страницы одинаковы, и первый же
    /// большой запрос вымоет словарь ради постингов, которые больше не
    /// понадобятся. Проход по странице закрепляет ценное в кеше — не отбирая
    /// память у процесса: страницы остаются общими и вытесняемыми, если нужда
    /// станет по-настоящему острой.
    pub fn warm(&self) -> usize {
        touch_pages(self.ptr, self.len)
    }

    /// Отдаёт ядру residency неизменяемого private file mapping.
    ///
    /// Writable/shared и owned-memory области намеренно исключены: первая
    /// содержит live bits, вторая вообще не имеет backing file. Адрес mapping
    /// остаётся законным; следующий читатель получит обычный page fault.
    #[cfg(target_os = "linux")]
    pub fn drop_immutable_cache(&self) -> usize {
        if !self.is_mapped() || self.shared || self.len == 0 {
            return 0;
        }
        let rc = unsafe { madvise(self.ptr as *mut c_void, self.len, MADV_DONTNEED) };
        if rc == 0 {
            self.len
        } else {
            0
        }
    }

    #[cfg(not(target_os = "linux"))]
    pub fn drop_immutable_cache(&self) -> usize {
        0
    }

    /// Байт по смещению. За границей — ноль.
    #[inline(always)]
    pub fn u8_at(&self, off: usize) -> u8 {
        read_u8(self.ptr, self.len, off)
    }

    /// Два байта по смещению, порядок от младшего. За границей — ноль.
    #[inline(always)]
    pub fn u16_at(&self, off: usize) -> u16 {
        read_u16(self.ptr, self.len, off)
    }

    /// Четыре байта по смещению, порядок от младшего. За границей — ноль.
    #[inline(always)]
    pub fn u32_at(&self, off: usize) -> u32 {
        read_u32(self.ptr, self.len, off)
    }

    /// Восемь байт по смещению. За границей — ноль.
    #[inline(always)]
    pub fn u64_at(&self, off: usize) -> u64 {
        read_u64(self.ptr, self.len, off)
    }

    /// Срез отображения. Выход за границу обрезается, а не роняет процесс:
    /// длина списка известна из словаря, и хвостовой блок читается с запасом.
    #[inline(always)]
    pub fn slice(&self, off: usize, n: usize) -> &[u8] {
        read_slice(self.ptr, self.len, off, n)
    }
}

impl Drop for Mapped {
    /// Отображение снимается, а не течёт.
    fn drop(&mut self) {
        // Память с кучи снимает сам `Box`; звать на неё `munmap` — падение.
        if self.owned.is_none() && !self.ptr.is_null() && self.len > 0 {
            unsafe { munmap(self.ptr as *mut c_void, self.len) };
            LIVE_MAPS.fetch_sub(1, std::sync::atomic::Ordering::Relaxed);
            #[cfg(test)]
            thread_maps_add(-1);
        }
    }
}

/// Кусок отображения со своими границами.
///
/// ## Зачем он рядом с [`Mapped`]
///
/// Область отображения — дефицит: у процесса есть потолок на их **число**, и
/// упирается в него не память, а число сегментов — по двадцать две области на
/// каждый, пока сегмент лежит россыпью. Убрать этот расход можно единственным
/// способом: сложить неизменяемые куски сегмента в один файл и отобразить его
/// **один раз**. Тогда читателю нужен уже не файл, а кусок отображения: свои
/// границы при общем на всех держателе.
///
/// Так теперь и лежит упакованный сегмент: держатель у всех его кусков один, и
/// областей на сегмент [`MIN_MAPS_PER_SEGMENT`]. [`of_file`](Self::of_file)
/// остался для того, что лежит **снаружи** контейнера намеренно, — карты живых
/// и старых, собранных до контейнера сегментов: неизменяемый сегмент не
/// переписывают, и россыпь остаётся россыпью навсегда.
///
/// ## Почему без времени жизни
///
/// Кусок, устроенный как `&'a [u8]`, протянул бы это время через `Index` в
/// `Arc<Index>`, оттуда в `Segments` и в каждую структуру поиска — то есть в
/// половину ядра, и ради того, что и так соблюдается. [`std::sync::Arc`] держит
/// отображение живым ровно столько, сколько жив любой его кусок, и никого об этом
/// не спрашивает.
/// Копия куска — второй держатель того же отображения, а не второе отображение:
/// [`std::sync::Arc`] считает держателей, границы копируются как есть. Ровно то
/// же делает [`Region::part`], заводя соседний кусок поверх общего держателя.
#[derive(Clone)]
pub struct Region {
    /// Кто держит отображение живым, пока жив кусок.
    ///
    /// `None` — за куском не стоит памяти вовсе: пустой файл или пустой кусок.
    /// Держать в таком случае нечего, и размещения на куче он не стоит — пустых
    /// файлов у сегмента много, разрежённая схема оставляет пустым едва ли не
    /// каждый второй.
    ///
    /// Поле не читается ничем — и не должно: вся его работа в том, чтобы
    /// **существовать**, пока жив кусок, и снять отображение, когда умрёт
    /// последний. Делает это `Drop` у `Arc`, а `dead_code` вызовов `Drop` не
    /// видит и объявляет поле лишним. Убрать его по этому совету значит вернуть
    /// чтение снятой области.
    #[allow(dead_code)]
    owner: Option<std::sync::Arc<Mapped>>,
    ptr: *const u8,
    len: usize,
    /// Разделяемо ли отображение владельца с файлом — см. [`Mapped::open_rw`].
    shared: bool,
}

// Кусок после создания не меняется, поэтому делить его между потоками безопасно
// — на тех же основаниях, что и само отображение, и с тем же условием: править
// разделяемую область можно только атомарно, через [`Mapped::word`]. Куском
// такая область не бывает: единственная у нас — карта живых, и она лежит
// отдельным файлом на [`Mapped`], намеренно вне контейнера.
//
// `Arc` в поле `Send + Sync` и сам; ручным здесь остаётся только указатель.
unsafe impl Sync for Region {}
unsafe impl Send for Region {}

impl Region {
    /// Пустой кусок — для файлов, которых нет по построению.
    ///
    /// «Куска нет» и «кусок есть, но пустой» — **разные** вещи, и обе в ходу:
    /// `Option<Region>` отвечает на первый вопрос, `Region::empty` на второй. На
    /// этой разнице стоит опись `check`: несуществующего файла у сегмента быть не
    /// обязано, а существующий пустой обязан быть перечислен.
    pub fn empty() -> Region {
        Region { owner: None, ptr: std::ptr::null(), len: 0, shared: false }
    }

    /// Отдельный файл целиком: отображение заводится своё, и кусок — весь он.
    pub fn of_file(path: &str) -> std::io::Result<Region> {
        Ok(Self::whole(Mapped::open(path)?))
    }

    /// То же для недоверенного архива: жёсткая ссылка на чужой inode не
    /// принимается — см. [`Mapped::open_private`].
    pub fn of_private_file(path: &str) -> std::io::Result<Region> {
        Ok(Self::whole(Mapped::open_private(path)?))
    }

    /// Кусок в памяти. Байты копируются: см. [`Mapped::of_bytes`].
    pub fn of_bytes(bytes: &[u8]) -> Region {
        Self::whole(Mapped::of_bytes(bytes))
    }

    /// Всё отображение одним куском.
    fn whole(m: Mapped) -> Region {
        // Пустое отображение области у ядра не занимает (`Mapped::open` на
        // нулевом файле не зовёт `mmap` вовсе), и держать его незачем.
        if m.ptr.is_null() || m.len == 0 {
            return Region::empty();
        }
        let (ptr, len, shared) = (m.ptr, m.len, m.shared);
        Region { owner: Some(std::sync::Arc::new(m)), ptr, len, shared }
    }

    /// Кусок общего отображения: свои границы, держатель на всех один.
    ///
    /// ## Что здесь обрезается и что этим не проверено
    ///
    /// Кусок обрезается по концу **отображения**, и это не проверка оглавления,
    /// а последняя защита: за концом отображения лежит неотображённая память, и
    /// чтение там не даёт нулей, а роняет процесс сигналом. Смещение же приходит
    /// из оглавления, то есть с диска, и сверять его с обещанной длиной обязан
    /// читатель оглавления — там, где расхождение ещё можно назвать порчей
    /// (`index::checked` так и делает). Обрезанный до пустоты кусок читается
    /// нулями и молчит, а молчание хуже отказа.
    ///
    /// Границы владельца кончаются здесь: **чтение** внутри готового куска
    /// обрезается уже по самому куску, и это разные обрезки — см.
    /// [`slice`](Self::slice).
    pub fn part(base: &std::sync::Arc<Mapped>, off: usize, len: usize) -> Region {
        let end = off.saturating_add(len).min(base.len);
        if base.ptr.is_null() || off >= base.len || end <= off {
            return Region::empty();
        }
        Region {
            owner: Some(base.clone()),
            ptr: unsafe { base.ptr.add(off) },
            len: end - off,
            shared: base.shared,
        }
    }

    /// Сколько кусков делят это отображение — считая текущий.
    ///
    /// Ноль — за куском нет памяти вовсе. Единица — отображение держит он один.
    ///
    /// Наблюдение это несущее, а не любопытство: весь смысл контейнера в том,
    /// что отображение **одно на все куски**, и проверить это иначе нечем.
    /// Счётчик [`live_maps`] общий на процесс и в многопоточном прогоне шумит;
    /// здесь же ответ точен и локален.
    pub fn owners(&self) -> usize {
        self.owner.as_ref().map_or(0, std::sync::Arc::strong_count)
    }

    /// Кусок куска: свои границы внутри уже готового куска, держатель тот же.
    ///
    /// Нужен там, где кусок сам делится дальше и подкускам надо пережить
    /// родителя: записи словарей внутри `<поле>.sdic` живут именно так — каждая
    /// уезжает в свой распаковщик, а отображение у них одно на всех.
    ///
    /// Обрезается по концу **родителя**, а не отображения: за концом куска в
    /// контейнере лежит соседний кусок, и отдать его вместо пустоты значило бы
    /// вернуть правдоподобный мусор нужной длины.
    pub fn sub(&self, off: usize, len: usize) -> Region {
        let end = off.saturating_add(len).min(self.len);
        if self.ptr.is_null() || off >= self.len || end <= off {
            return Region::empty();
        }
        Region {
            owner: self.owner.clone(),
            ptr: unsafe { self.ptr.add(off) },
            len: end - off,
            shared: self.shared,
        }
    }

    /// Лежит ли за куском настоящая память.
    ///
    /// Не «занимает ли он область у ядра»: область принадлежит **владельцу**, и у
    /// контейнера она одна на все куски. Считает области счётчик самого
    /// [`Mapped`] — см. [`live_maps`].
    #[inline]
    pub fn is_mapped(&self) -> bool {
        !self.ptr.is_null()
    }

    #[inline]
    pub fn len_bytes(&self) -> usize {
        self.len
    }

    #[inline]
    pub fn is_empty(&self) -> bool {
        self.len == 0
    }

    /// Затягивает кусок в кеш страниц и отдаёт число тронутых байт.
    ///
    /// Именно кусок, а не весь файл владельца: греют словарь и опоры затем, чтобы
    /// их не вымыл первый же большой запрос, и прогрев вместе с ними списков —
    /// это ровно то вымывание, от которого прогрев и заведён.
    pub fn warm(&self) -> usize {
        // За живым сегментом стоит куча, а не файл: страницы уже резидентны, и
        // советовать по ним ядру нечего. Совет безвреден, но обход по странице
        // — чистая работа впустую, а на живом сегменте она идёт в потоке, где
        // её меньше всего ждут.
        if self.owner.as_ref().is_some_and(|m| m.is_memory()) {
            return self.len;
        }
        touch_pages(self.ptr, self.len)
    }

    /// Сбрасывает правки куска на диск и ждёт завершения.
    ///
    /// ## Почему адрес выравнивается, а не берётся как есть
    ///
    /// `msync` принимает только адрес, кратный странице, и на невыровненном
    /// отвечает `EINVAL`. У отображения такой адрес всегда — его отдаёт `mmap`, —
    /// а у куска нет: кусок начинается там, где кончился предыдущий. Поэтому
    /// начало опускается до границы страницы, а конец поднимается: сброшено
    /// будет чуть больше просимого, и это безобидно — лишние страницы
    /// принадлежат тому же отображению и тому же файлу.
    ///
    /// Сбросить вместо куска весь файл владельца было бы короче и неверно: у
    /// контейнера это `msync` по гигабайтам вместо килобайтов на каждом сбросе.
    ///
    /// Разделяемых кусков сегодня нет ни одного — единственная область на запись
    /// это карта живых, а она лежит отдельным файлом на [`Mapped`]. Тому, кто
    /// заведёт первый, лучше не искать причину `EINVAL`.
    pub fn sync(&self) -> std::io::Result<()> {
        if !self.shared || self.ptr.is_null() {
            return Ok(());
        }
        // Размер страницы у ядра, а не зашитый: на aarch64 у macOS он 16 КБ.
        let page = match usize::try_from(unsafe { getpagesize() }) {
            Ok(p) if p > 0 => p,
            _ => {
                return Err(std::io::Error::new(
                    std::io::ErrorKind::Unsupported,
                    "ядро не сообщило размер страницы — выровнять адрес для msync нечем",
                ))
            }
        };
        let slack = self.ptr as usize % page;
        // Конец поднимается до границы страницы: последняя страница отображения
        // отображена целиком, сколько бы байт файла в неё ни попало, — значит
        // `msync` по ней законен.
        let span = self.len.saturating_add(slack).div_ceil(page).saturating_mul(page);
        let rc = unsafe { msync((self.ptr as usize - slack) as *mut c_void, span, MS_SYNC) };
        if rc != 0 {
            return Err(std::io::Error::last_os_error());
        }
        Ok(())
    }

    /// Байт по смещению. За границей куска — ноль.
    #[inline(always)]
    pub fn u8_at(&self, off: usize) -> u8 {
        read_u8(self.ptr, self.len, off)
    }

    /// Два байта по смещению, порядок от младшего. За границей куска — ноль.
    #[inline(always)]
    pub fn u16_at(&self, off: usize) -> u16 {
        read_u16(self.ptr, self.len, off)
    }

    /// Четыре байта по смещению, порядок от младшего. За границей куска — ноль.
    #[inline(always)]
    pub fn u32_at(&self, off: usize) -> u32 {
        read_u32(self.ptr, self.len, off)
    }

    /// Восемь байт по смещению. За границей куска — ноль.
    #[inline(always)]
    pub fn u64_at(&self, off: usize) -> u64 {
        read_u64(self.ptr, self.len, off)
    }

    /// Срез куска. Выход за границу обрезается, а не роняет процесс.
    ///
    /// Обрезается по концу **куска**, а не по концу отображения, и это несущее
    /// различие. Читатель списков берёт хвостовой блок с запасом и рассчитывает
    /// получить за концом нули — на этом же стоит и `bits`, уходящий на медленный
    /// путь у границы окна `u64`. Обрежь здесь по владельцу — и ошибка в длине
    /// куска отдала бы вместо нулей начало **соседнего** куска контейнера, то
    /// есть правдоподобный мусор вместо пустоты.
    #[inline(always)]
    pub fn slice(&self, off: usize, n: usize) -> &[u8] {
        read_slice(self.ptr, self.len, off, n)
    }
}

/// Сколько областей отображения держит процесс прямо сейчас.
///
/// ## Зачем счётчик, а не обход структур
///
/// У процесса есть потолок на **число** областей — на Linux это
/// `vm.max_map_count`, по умолчанию 65530, — и упирается в него не память, а
/// число сегментов: у упакованного сегмента областей [`MIN_MAPS_PER_SEGMENT`],
/// у собранного до контейнера — полтора-два десятка при схеме по умолчанию и до
/// сорока с колонками, векторами и широкой схемой. При пределе 65530 россыпь
/// перестаёт открываться на нескольких тысячах сегментов, и это потолок, а не
/// замедление.
///
/// Считать обходом структур пришлось бы в восьми типах, и каждый новый файл
/// сегмента про этот обход забыли бы. Счётчик стоит там, где области и правда
/// заводятся и снимаются, поэтому не врёт по построению и не требует правки при
/// добавлении файлов.
///
/// Нужен он затем, чтобы предел был виден **заранее**: отказ `mmap` понятен, но
/// приходит поздно — индекс уже не открывается.
static LIVE_MAPS: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(0);

/// Сколько областей отображения держит процесс.
pub fn live_maps() -> usize {
    LIVE_MAPS.load(std::sync::atomic::Ordering::Relaxed)
}

/// Сколько областей заведено за всю жизнь процесса — не убывает никогда.
///
/// Живой счётчик отвечает на вопрос «упрёмся ли в потолок», а этот — на вопрос
/// «сколько раз мы отобразили то, что уже было отображено». Разница
/// принципиальная: путь, который открывает неизменяемый файл сегмента заново на
/// каждый вызов, для [`live_maps`] невидим — область снимается тут же, по выходу
/// из вызова, и до и после цикла счётчик показывает одно и то же. Видна такая
/// растрата только по накопленному числу.
pub fn maps_made() -> usize {
    MAPS_MADE.load(std::sync::atomic::Ordering::Relaxed)
}

static MAPS_MADE: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(0);

#[cfg(test)]
thread_local! {
    /// Сколько областей завёл и ещё не снял **этот поток**. Только для замеров.
    ///
    /// [`live_maps`] мерилом быть не может, и это выяснено делом: прогон
    /// многопоточный, соседний тест успевает завести и снять свою область между
    /// двумя чтениями общего счётчика — см. довод у
    /// `the_counter_counts_mappings_and_empty_files_take_none`. Поэтому там, где
    /// нужно **точное** число областей на сегмент, счёт ведётся по потоку:
    /// разность верна, пока замеряемое само не заводит потоков, а `index::load`
    /// их не заводит.
    ///
    /// Учёт только в отладочной сборке: в выпуске у него не было бы ни одного
    /// читателя, а платить за него пришлось бы на каждом отображении.
    static THREAD_MAPS: std::cell::Cell<isize> = const { std::cell::Cell::new(0) };
}

/// Правит счёт этого потока: `+1` на заведённую область, `-1` на снятую.
#[cfg(test)]
fn thread_maps_add(d: isize) {
    // `try_with`, а не `with`: последнее отображение потока снимается уже при
    // разборе его локальных значений, и `with` там не находит ячейки. Пропущенное
    // приращение в этот миг никому не важно — замеряют внутри теста, а не на
    // выходе из потока.
    THREAD_MAPS.try_with(|c| c.set(c.get() + d)).ok();
}

/// Сколько областей держит этот поток.
#[cfg(test)]
fn thread_maps() -> isize {
    THREAD_MAPS.try_with(std::cell::Cell::get).unwrap_or(0)
}

/// Потолок числа областей у процесса, если ядро его сообщает.
///
/// Linux отдаёт его в `/proc/sys/vm/max_map_count`. У macOS сопоставимой ручки
/// нет — там предел задаётся иначе и наружу не выставлен, поэтому `None`, а не
/// выдуманное число.
pub fn max_maps() -> Option<usize> {
    std::fs::read_to_string("/proc/sys/vm/max_map_count").ok()?.trim().parse().ok()
}

/// Сколько областей отображения держит **весь процесс**, а не только мы.
///
/// ## Почему не [`live_maps`]
///
/// Тот считает наши отображения — те, что завёл [`Mapped`]. У процесса же есть
/// области, которых мы не заводили и снять не можем: исполняемый файл и все его
/// куски, разделяемые библиотеки, куча, и по две-три области на **каждый** поток
/// (стек и защитная страница под ним). У узла с несколькими десятками работников
/// таких областей 200-400 ещё до того, как открыт первый сегмент, и в предел
/// ядра они входят наравне с нашими.
///
/// Считать по [`live_maps`] значило бы занизить потребность ровно на эту величину
/// и объявить пригодным предел, на котором узел не откроется.
///
/// Linux печатает по строке на область в `/proc/self/maps`. У macOS такого файла
/// нет — там базовый расход неизвестен, и `None` честнее выдуманного числа:
/// сообщение тогда прямо говорит, что ядро расхода не сообщает, а не выдаёт
/// неполную сумму за полную. Практически это сочетание не встречается: предел
/// (`max_maps`) и расход берутся из одного `/proc`, и нет его сразу у обоих.
///
/// Голым это число базой не берут: в нём есть и **наши** области, а их в
/// потребности считает уже слагаемое «сегментов × на сегмент». Вычитание — у
/// [`maps_outside_index`].
pub fn process_maps() -> Option<usize> {
    Some(std::fs::read_to_string("/proc/self/maps").ok()?.lines().count())
}

/// Расход процесса **вне** индекса: из всех его областей вычтены наши.
///
/// `process` — показание [`process_maps`], `ours` — [`live_maps`].
///
/// ## Почему вычитание, а не голое показание `/proc`
///
/// Потребность считается как «база + сегментов × на сегмент». Второе слагаемое —
/// это области, которые открытие **заведёт**, а `/proc/self/maps` показывает те,
/// что уже стоят. На первом открытии в процессе своих ещё нет, вычитать нечего, и
/// обе арифметики дают одно число. Расходятся они дальше, и вот на чём.
///
/// `Segments::load` зовётся и после старта — посреди переигрывания журнала, когда
/// сброс завёл сегмент. Прежний набор в этот миг ещё жив: его сменят на новый,
/// когда тот соберётся. Голая база складывает два поколения **одного и того же**
/// индекса и объявляет, что ему нужно вдвое, — узлу, который минуту назад
/// поднялся на этом же пределе. Отказ выходит такой, с каким оператору нечего
/// делать: числа в нём не сходятся ни с составом (сегментов две тысячи, а расход
/// назван как на четыре), ни с советом («укрупнить втрое» там, где до потолка
/// оставалась треть). Отказ, ломающий работающий узел, хуже отсутствия проверки.
///
/// ## Чем за это платят — и почему обмен принят
///
/// Уходит из базы и то своё, что держит в этом же процессе **другой** индекс:
/// соседний шард в `Shards::open`. Этот расход настоящий, и проверка на нём
/// становится мягче должного. Уходит и пик самогó переоткрытия: два поколения
/// разом — это правда, запас в десятую долю её не покрывает, и здесь она больше
/// не считается.
///
/// Полагаться на то, что отказ `mmap` объяснится сам, **нельзя**, и это
/// проверено счётом: из сорока открытий в ядре девятнадцать
/// глотают ошибку через `.ok()?` — колонка, фильтр, хранилище поля просто
/// становятся «этого поля нет». То есть отказ по пределу областей у половины
/// мест не громкий, а **молчаливый**, и выдача после него неотличима от честной.
/// Поэтому мягкости одной проверки недостаточно, и рядом стоит вторая — по
/// пику, против **жёсткого** предела: см. [`MapBudget::peak`] и
/// [`MapBudget::peaks_over`].
pub fn maps_outside_index(process: Option<usize>, ours: usize) -> Option<usize> {
    // Насыщение, а не вычитание в лоб: замеры берутся не одним мгновением, и
    // между ними соседний поток успевает завести область — тогда наших окажется
    // больше, чем прочтено у процесса. Отрицательной базы не бывает, бывает ноль;
    // в выпуске с `panic = "abort"` переполнение вычитания убило бы узел на
    // открытии, то есть ровно там, где проверка обязана объяснять, а не падать.
    process.map(|p| p.saturating_sub(ours))
}

/// Пол числа областей на сегмент: контейнер и карта живых.
///
/// Ниже него не опускает никакая настройка: карта живых нужна, чтобы отвечать
/// «этот документ погашен», а контейнер — чтобы вообще что-то прочитать. Всё
/// прочее (словарь, списки, значения полей, коды векторов) сверх этого.
///
/// Пол нужен затем, чтобы отказать **до** открытия первого сегмента: если уже
/// `сегментов × 2` не лезет в предел, ни одна настройка положения не спасёт, и
/// открывать тысячи каталогов, чтобы убедиться в этом, незачем.
pub const MIN_MAPS_PER_SEGMENT: usize = 2;

/// Ниже этого предел советовать незачем.
///
/// Столько же требует Elasticsearch на том же месте, и это не совпадение: у нас
/// та же арифметика — область на файл сегмента, сегментов много. Совет поднять
/// предел до чего-то меньшего оператор выполнит один раз и вернётся с тем же
/// отказом через неделю.
pub const MIN_ADVISED_MAPS: usize = 262_144;

/// Рабочая доля предела: девять десятых, а не весь.
///
/// Области заводятся не только на открытии. Каждый сброс добавляет сегмент —
/// это ещё столько же областей, сколько держит любой другой; каждое слияние
/// держит источники и выход **одновременно**, то есть на время слияния индекс
/// занимает больше, чем занимает готовым. Узел, стартовавший ровно на ста
/// процентах предела, умрёт на первом же сбросе — и умрёт отказом `mmap` посреди
/// приёма, а не отказом на старте, когда чинить дёшево.
const HEADROOM_NUM: usize = 9;
const HEADROOM_DEN: usize = 10;

/// Хватит ли процессу областей отображения на весь индекс.
///
/// Считается без единого обращения к диску сверх уже прочитанного: число
/// сегментов известно из списка состава, предел — из `/proc`, базовый расход —
/// оттуда же.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct MapBudget {
    /// Сегментов в индексе.
    pub segments: usize,
    /// Областей на сегмент.
    pub per_seg: usize,
    /// Расход процесса **вне** индекса; `None` — ядро его не сообщает.
    ///
    /// Именно вне: свои области входят в [`per_seg`](Self::per_seg) × число
    /// сегментов, и повтори их база — потребность выросла бы вдвое на ровном
    /// месте. Считает эту величину [`maps_outside_index`].
    pub base: Option<usize>,
    /// Сколько областей потребуется всего.
    pub need: usize,
    /// Предел ядра.
    pub limit: usize,
    /// Рабочий потолок: доля предела, оставляющая запас на сбросы и слияния.
    pub budget: usize,
    /// Точная ли оценка. `false` — [`per_seg`](Self::per_seg) взят по полу, и
    /// настоящая потребность **больше** посчитанной.
    pub exact: bool,
    /// Свои области, уже стоящие в этом процессе, — [`live_maps`].
    ///
    /// Нужны второму порогу: [`need`](Self::need) считает, сколько понадобится
    /// **новому** составу, а старый в этот миг ещё жив, и ядру предъявляются оба
    /// разом.
    pub ours: usize,
}

/// Потребность при известном числе областей на сегмент.
pub fn map_budget(segments: usize, per_seg: usize, base: Option<usize>, limit: usize) -> MapBudget {
    budget_of(segments, per_seg.max(MIN_MAPS_PER_SEGMENT), base, limit, true, 0)
}

/// То же, но с числом уже стоящих своих областей — для второго порога.
pub fn map_budget_with(
    segments: usize,
    per_seg: usize,
    base: Option<usize>,
    limit: usize,
    ours: usize,
) -> MapBudget {
    budget_of(segments, per_seg.max(MIN_MAPS_PER_SEGMENT), base, limit, true, ours)
}

/// Потребность по полу: столько нужно, чего бы ни оказалось в сегменте.
pub fn map_budget_floor(segments: usize, base: Option<usize>, limit: usize) -> MapBudget {
    budget_of(segments, MIN_MAPS_PER_SEGMENT, base, limit, false, 0)
}

fn budget_of(
    segments: usize,
    per_seg: usize,
    base: Option<usize>,
    limit: usize,
    exact: bool,
    ours: usize,
) -> MapBudget {
    // Насыщение, а не перенос: при переполнении потребность обязана остаться
    // огромной, а не завернуться в ноль и объявить, что всё помещается.
    let need = base.unwrap_or(0).saturating_add(segments.saturating_mul(per_seg));
    let budget = limit.saturating_mul(HEADROOM_NUM) / HEADROOM_DEN;
    MapBudget { segments, per_seg, base, need, limit, budget, exact, ours }
}

impl MapBudget {
    /// Помещается ли индекс в рабочий потолок.
    pub fn fits(&self) -> bool {
        self.need <= self.budget
    }

    /// Сколько областей будет стоять в самый тесный миг открытия.
    ///
    /// Новому составу нужно [`need`](Self::need), а старый в этот миг ещё жив —
    /// его сменят, когда новый соберётся. Ядру предъявляются оба.
    pub fn peak(&self) -> usize {
        self.need.saturating_add(self.ours)
    }

    /// Переваливает ли пик за **жёсткий** предел ядра.
    ///
    /// Именно за жёсткий, а не за рабочий потолок, и это разделение несущее.
    /// Рабочий потолок — забота о будущем: он оставляет запас на сбросы и
    /// слияния, которые заведут области потом, и потому сверяется с
    /// [`need`](Self::need), где своих нет. Жёсткий предел — про сейчас: за ним
    /// `mmap` откажет **на этом самом открытии**.
    ///
    /// Разделять пришлось потому, что мягкости первой проверки недостаточно:
    /// девятнадцать открытий из сорока глотают ошибку через `.ok()?`, и отказ
    /// по пределу областей у них выглядит как «поля нет».
    /// Молчаливая неполная выдача хуже отказа, поэтому пик проверяется отдельно
    /// и отказывает всегда, петля там или не петля.
    pub fn peaks_over(&self) -> bool {
        self.limit > 0 && self.peak() > self.limit
    }

    /// Какой предел просить у ядра.
    ///
    /// Не «поставьте 262144»: тому, кому нужно 2.8 млн, такой совет хуже
    /// молчания — он его выполнит, перезапустит узел и получит тот же отказ.
    /// Считается от настоящей потребности, с тем же запасом в десятую долю
    /// (иначе поднятый ровно под потребность предел умер бы на первом сбросе),
    /// и округляется вверх до степени двойки — чтобы совет не менялся от каждого
    /// нового сегмента и выглядел как настройка, а не как замер.
    pub fn advised_limit(&self) -> usize {
        let want = self.need.saturating_mul(HEADROOM_DEN).div_ceil(HEADROOM_NUM);
        let mut p = MIN_ADVISED_MAPS;
        while p < want {
            // Умножение проверяется: `next_power_of_two` при переполнении
            // отдаёт ноль в выпуске, а ноль здесь означал бы «предел не нужен».
            match p.checked_mul(2) {
                Some(x) => p = x,
                None => return want,
            }
        }
        p
    }

    /// Сколько сегментов помещается в нынешний предел.
    pub fn segments_that_fit(&self) -> usize {
        self.budget.saturating_sub(self.base.unwrap_or(0)) / self.per_seg.max(1)
    }

    /// Отказ, который говорит, что делать, — все числа посчитанные.
    ///
    /// Числа здесь любые, поэтому существительное всюду стоит **перед** числом
    /// («сегментов 2929»): согласовывать окончание с посчитанной величиной
    /// пришлось бы отдельным правилом на каждое слово, а промах в нём читается
    /// как небрежность ровно там, где нужно доверие.
    pub fn explain(&self) -> String {
        let need = if self.exact {
            format!("{}", self.need)
        } else {
            format!("не меньше {}", self.need)
        };
        let measured = if self.exact {
            "замерено на первом"
        } else {
            "пол; настоящее число больше"
        };
        let base = match self.base {
            Some(b) => format!(", у самого процесса ещё {b}"),
            None => ", базовый расход процесса ядро не сообщает".to_string(),
        };
        let fits = self.segments_that_fit();
        let lever = if fits == 0 {
            "в нынешний предел не помещается ни один сегмент — укрупнением это не лечится"
                .to_string()
        } else {
            format!(
                "в нынешний предел их помещается {fits} из {}, то есть --target= надо поднять \
                 примерно в {} раз",
                self.segments,
                self.segments.div_ceil(fits)
            )
        };
        let n = self.advised_limit();
        // Совет, посчитанный по полу, — тоже оценка снизу, и выдать его за
        // точный значило бы отправить оператора поднимать предел дважды: он
        // поставит названное, перезапустит узел и упрётся снова, теперь уже на
        // точном замере. Пусть лучше сразу знает, что настоящее число больше.
        let lower = if self.exact {
            String::new()
        } else {
            // Пол в две области — это ровно упакованный сегмент, и врать про
            // него больше нечем: столько он и занимает, сколько бы кусков ни
            // лежало в контейнере. Занижен совет по полу только там, где
            // сегменты остались рассыпанными, — вот про них и сказано. Прежняя
            // приписка «областей не две, а полтора-два десятка» была верна до
            // контейнера и теперь отправила бы поднимать предел вдесятеро
            // против нужного.
            format!(
                "\nи это нижняя граница совета: областей на сегмент {MIN_MAPS_PER_SEGMENT} — \
                 столько занимает упакованный, seg.dat и карта живых. У сегмента, собранного до \
                 контейнера, область уходит на каждый непустой файл: полтора-два десятка, и \
                 тогда предел нужен во столько же раз выше — такие сегменты переупаковывает \
                 слияние"
            )
        };
        format!(
            "областей отображения памяти не хватит: индексу нужно {need}, а рабочий потолок {} — \
             девять десятых от vm.max_map_count = {}. Десятая доля не осторожность: сброс \
             добавляет ещё один сегмент, слияние держит источники и выход разом, и узел, \
             стартовавший ровно на пределе, умер бы на первом сбросе.\n\
             считано: сегментов {}, областей на сегмент {} ({measured}){base}\n\
             поднять предел сейчас:      sysctl -w vm.max_map_count={n}\n\
             чтобы пережил перезагрузку: echo 'vm.max_map_count={n}' > /etc/sysctl.d/99-svindb.conf\
             {lower}\n\
             либо укрупнить сегменты: {lever}\n\
             проверку снимает --allow-low-map-count: узел стартует и упрётся в предел на открытии",
            self.budget, self.limit, self.segments, self.per_seg
        )
    }
}

/// Что делать, когда областей отображения на весь индекс заведомо не хватит.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum MapShortfall {
    /// Отказать в открытии.
    Refuse,
    /// Предупредить и открывать.
    Warn,
}

const SHORTFALL_WARN: u8 = 0;
const SHORTFALL_REFUSE: u8 = 1;

/// Умолчание — предупреждение, и это не мягкость.
///
/// Ядро открывают не только узлы: `svindb merge` и `svindb check` открывают
/// индекс на минуту, новых сегментов не заводят и после себя ничего не держат.
/// А `merge` — это ровно тот рычаг, которым число сегментов уменьшают. Отказать
/// ему значило бы отнять единственный способ починить индекс, который в предел
/// уже упёрся. Решение отказывать принимает узел, и принимает его по тому, кого
/// он обслуживает, — см. [`set_map_shortfall`].
static SHORTFALL: std::sync::atomic::AtomicU8 = std::sync::atomic::AtomicU8::new(SHORTFALL_WARN);

/// Объявляет, отказом или предупреждением отвечать на нехватку областей.
pub fn set_map_shortfall(p: MapShortfall) {
    let v = match p {
        MapShortfall::Refuse => SHORTFALL_REFUSE,
        MapShortfall::Warn => SHORTFALL_WARN,
    };
    SHORTFALL.store(v, std::sync::atomic::Ordering::Relaxed);
}

/// Как отвечать на нехватку областей.
pub fn map_shortfall() -> MapShortfall {
    if SHORTFALL.load(std::sync::atomic::Ordering::Relaxed) == SHORTFALL_REFUSE {
        MapShortfall::Refuse
    } else {
        MapShortfall::Warn
    }
}

/// Читает `count` чисел `u32` начиная со смещения `skip_bytes`.
///
/// Именно читает, а не отображает: `blocks.bin` и `terms.bin` нужны целиком и
/// на всём протяжении запроса — выбор опорного списка трогает `t_df` каждого
/// списка, а прыжок через блоки трогает `b_last` подряд. Отображать то, что
/// всё равно будет прочитано полностью, смысла нет.
pub fn read_u32s(path: &str, count: usize, skip_bytes: usize) -> std::io::Result<Vec<u32>> {
    let buf = read_all(path)?;
    let need = skip_bytes + count * 4;
    if buf.len() < need {
        return Err(short(path, need, buf.len()));
    }
    let mut out = Vec::with_capacity(count);
    for i in 0..count {
        let o = skip_bytes + i * 4;
        out.push(u32::from_le_bytes([buf[o], buf[o + 1], buf[o + 2], buf[o + 3]]));
    }
    Ok(out)
}

/// Читает `count` чисел `u64` начиная со смещения `skip_bytes`.
///
/// Смещения блоков — **шестьдесят четыре бита**, и это не запас. На двухстах
/// миллионах документов файл списков занимает 9.3 GB, а тридцатидвухбитное
/// смещение заворачивается после четырёх: читатель принимал байт данных за
/// заголовок блока и получал ширину 86 бит при потолке 32.
pub fn read_u64s(path: &str, count: usize, skip_bytes: usize) -> std::io::Result<Vec<u64>> {
    let buf = read_all(path)?;
    let need = skip_bytes + count * 8;
    if buf.len() < need {
        return Err(short(path, need, buf.len()));
    }
    let mut out = Vec::with_capacity(count);
    for i in 0..count {
        let o = skip_bytes + i * 8;
        let mut b = [0u8; 8];
        b.copy_from_slice(&buf[o..o + 8]);
        out.push(u64::from_le_bytes(b));
    }
    Ok(out)
}

pub fn read_all(path: &str) -> std::io::Result<Vec<u8>> {
    let mut buf = Vec::new();
    File::open(path)?.read_to_end(&mut buf)?;
    Ok(buf)
}

/// Обрезанный файл — это ошибка загрузки, а не повод читать мусор.
fn short(path: &str, need: usize, have: usize) -> std::io::Error {
    std::io::Error::new(
        std::io::ErrorKind::InvalidData,
        format!("{path}: нужно {need} байт, в файле {have}"),
    )
}

#[cfg(test)]
