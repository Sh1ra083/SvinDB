        assert!(Region::part(&base, 100, 8).is_empty(), "кусок начался за отображением");
        assert!(Region::part(&base, 1000, 8).is_empty());
        assert!(Region::part(&base, 0, 0).is_empty(), "кусок нулевой длины занял держателя");
        // Длина с запасом обрезается по концу отображения.
        assert_eq!(Region::part(&base, 90, 1000).len_bytes(), 10);
        // Переполнение суммы не заворачивается в «кусок в один байт».
