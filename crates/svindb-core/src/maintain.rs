/// Очередь работ: укрупнение не голодает под потоком удалений.
#[cfg(test)]
mod queue_tests {
    use super::*;

    /// Доросший грязный сегмент вычищается, даже когда укрупнению всегда есть
    /// чем заняться.
    ///
    /// ## Что ломалось бы без этого
    ///
    /// Сегмент, доросший до целевого размера, в окно укрупнения не попадает
    /// **никогда**: он один уже не влезает в потолок. Значит вычистить из него
    /// мёртвое может только уборка. А у живого узла окно укрупнения находится
    /// почти всегда — выход прошлого слияния ещё долго ниже цели, и любые два
    /// свободных сегмента дают окно. Пока уборка стоит за укрупнением
    /// безусловно, до неё просто не доходит очередь, и мёртвое в доросшем
    /// сегменте остаётся там навсегда, сколько бы его ни накопилось.
    ///
    /// Соседний тест этого не ловит: там мелкие сегменты кончаются, окно
    /// пропадает само, и уборка получает заход. Здесь мелкие **подсыпаются**
    /// каждый круг — ровно как на узле, который принимает.
    #[test]
    fn a_grown_dirty_segment_is_cleaned_even_while_consolidation_always_has_work() {
        let dir = std::env::temp_dir()
            .join(format!("svindb-queue-grown-{}", std::process::id()))
            .to_string_lossy()
            .to_string();
        std::fs::remove_dir_all(&dir).ok();

        // Доросший сегмент: 2000 документов при цели в 1000. В окно не влезает.
        let mut ix = crate::indexer::Indexer::new(&dir, vec!["body".into()], vec![1.0], 5000);
        for i in 0..2000 {
            ix.add(&format!("big{i:05}"), &[&format!("общее слово{}", i % 7)]);
        }
        ix.flush_now();

        let cfg = Config {
            target_docs: 1000,
            at_once: 8,
            dead_fraction: 0.2,
            grace_ms: 0,
            ..Config::default()
        };

        // Гасим половину доросшего — он грязен выше порога и остаётся таким.
        let ids: Vec<String> = (0..1000).map(|i| format!("big{i:05}")).collect();
        assert_eq!(delete(&dir, &ids).expect("гашение").killed, 1000);

        let dirty_share = || {
            let segs = crate::segments::Segments::load(&dir).expect("индекс");
            segs.list
                .iter()
                .filter(|s| s.docs > cfg.target_docs)
                .map(|s| s.dead() as f64 / s.docs as f64)
                .fold(0.0f64, f64::max)
        };
        assert!(dirty_share() >= 0.49, "доросший обязан быть грязным: {}", dirty_share());

        // Двенадцать кругов, и каждый круг подсыпаем мелочь — то есть окно
        // укрупнения есть всегда, как на принимающем узле.
        let mut reclaimed = 0usize;
        for round in 0..12 {
            let mut ix = crate::indexer::Indexer::new(&dir, vec!["body".into()], vec![1.0], 20);
            for i in 0..40 {
                ix.add(&format!("s{round}_{i:03}"), &[&format!("общее слово{}", i % 7)]);
            }
            ix.flush_now();
            if let Some(Action::Reclaimed { .. }) = once(&dir, cfg).expect("заход") {
                reclaimed += 1;
            }
        }

        assert!(
            reclaimed > 0,
            "уборка не случилась ни разу: доросший грязный сегмент недостижим для укрупнения, \
             и мёртвое осталось бы в нём навсегда"
        );
        assert!(
            dirty_share() < cfg.dead_fraction,
            "доросший сегмент так и остался грязным: {}",
            dirty_share()
        );
        std::fs::remove_dir_all(&dir).ok();
    }

    /// Умолчание ширины — доля ядер, а не все ядра и не одно.
    ///
    /// Ноль здесь значит «четверть, но не меньше одного», и обе половины
    /// существенны: все ядра — это фоновая работа поверх приёма, одно —
    /// слияние, которое не поспевает за нарезкой.
    #[test]
    fn the_default_width_is_a_share_of_the_cores() {
        let all = std::thread::available_parallelism().map_or(1, |n| n.get());
        let cfg = Config::default();
        assert_eq!(cfg.merge_threads, 0, "умолчание перестало быть долей");
        assert_eq!(cfg.threads(), (all / 4).max(1));
        assert!(cfg.threads() >= 1, "ноль потоков — это не слияние");
        assert!(cfg.threads() <= all.max(1), "долей вышло больше, чем ядер");
        assert_eq!(Config { merge_threads: 3, ..Config::default() }.threads(), 3);
    }

    /// Вечно грязный сегмент не должен отменять укрупнение.
    ///
    /// ## Что здесь воспроизводится
    ///
    /// Прежде заход брал самый грязный сегмент, переписывал его и **возвращался**,
    /// не дойдя до укрупнения. Индекс с постоянным потоком удалений всегда имеет
    /// что убирать — значит укрупнение не случалось никогда, сколько бы мелких
    /// сегментов ни накопилось. Это не рассуждение: на прежнем коде эта проверка
    /// падает, потому что `Consolidated` не выходит ни разу за двенадцать заходов.
    #[test]
    fn consolidation_happens_even_under_a_steady_stream_of_deletes() {
        let dir = std::env::temp_dir()
            .join(format!("svindb-queue-{}", std::process::id()))
            .to_string_lossy()
            .to_string();
        std::fs::remove_dir_all(&dir).ok();

        // Один крупный сегмент — вечный источник грязи — и двадцать мелких.
        let mut ix = crate::indexer::Indexer::new(&dir, vec!["body".into()], vec![1.0], 5000);
        for i in 0..2000 {
            ix.add(&format!("big{i:05}"), &[&format!("общее слово{}", i % 7)]);
        }
        ix.flush_now();
        let mut ix = crate::indexer::Indexer::new(&dir, vec!["body".into()], vec![1.0], 10);
        for i in 0..200 {
            ix.add(&format!("small{i:05}"), &[&format!("общее слово{}", i % 7)]);
        }
        ix.flush_now();
        assert_eq!(manifest::segments(&dir).len(), 21, "нужны двадцать мелких и один крупный");

        let cfg = Config {
            target_docs: 1000,
            at_once: 8,
            dead_fraction: 0.2,
            grace_ms: 0,
            ..Config::default()
        };
        let mut alive: Vec<String> = (0..2000).map(|i| format!("big{i:05}")).collect();
        let (mut consolidated, mut reclaimed) = (0usize, 0usize);
        for round in 0..12 {
            // Четверть живых крупного уходит каждый заход: доля мёртвого в нём
            // не опускается ниже порога, сколько его ни переписывай.
            let take = alive.len() / 4;
            let ids: Vec<String> = alive.drain(..take).collect();
            assert_eq!(delete(&dir, &ids).expect("гашение").killed, take, "заход {round}");
            match once(&dir, cfg).expect("заход") {
                Some(Action::Consolidated { .. }) => consolidated += 1,
                Some(Action::Reclaimed { .. }) => reclaimed += 1,
                None => {}
            }
        }
        assert!(consolidated > 0, "укрупнение не случилось ни разу за двенадцать заходов");
        assert!(reclaimed > 0, "уборка, наоборот, не случилась ни разу — голодает она");

        let segs = crate::segments::Segments::load(&dir).expect("индекс");
        let live: usize = segs.list.iter().map(|s| s.docs - s.dead()).sum();
        assert_eq!(live, alive.len() + 200, "живых документов не столько, сколько осталось");
        std::fs::remove_dir_all(&dir).ok();
    }
}

#[cfg(test)]
mod delete_manifest_tests {
    /// Удаление отказывается, когда состав прочитать нельзя.
    ///
    /// Прежде `manifest::segments` при неудаче отдавал пустой список, а пустой
    /// список для удаления значит «гасить не в чем». Удаление возвращало
    /// `Ok(0)` — то есть вызывающий получал успех, не тронув ни одного
    /// документа. Именно так теряются данные молча: администратор уверен, что
    /// убрал их, а они на месте и продолжают находиться поиском.
    ///
    /// Порча делается настоящей: список сегментов подменяется именем, которого
    /// на диске нет. Ровно так это и выглядит после недописанного `segments.tsv`.
    #[test]
    fn deleting_refuses_when_the_manifest_cannot_be_read() {
        let dir = std::env::temp_dir()
            .join(format!("svindb-del-manifest-{}", std::process::id()))
            .to_string_lossy()
            .to_string();
        std::fs::remove_dir_all(&dir).ok();
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(format!("{dir}/segments.tsv"), "seg-которого-нет\n").unwrap();

        let ids = vec!["хоть-что-нибудь".to_string()];
        let out = super::delete(&dir, &ids);
        assert!(
            out.is_err(),
            "удаление отчиталось об успехе на нечитаемом составе — \
             вызывающий уверен, что данные убраны, а они на месте"
        );
        std::fs::remove_dir_all(&dir).ok();
    }
}

/// Каталог обязан быть неразличим по ответу от своего отсутствия.
#[cfg(test)]
mod catalog_tests {
    use super::*;

    fn corpus(name: &str, docs: u32, per_seg: u32) -> String {
        let dir = std::env::temp_dir()
            .join(format!("svindb-cat-{name}-{}", std::process::id()))
            .to_string_lossy()
            .to_string();
        std::fs::remove_dir_all(&dir).ok();
        let mut ix = crate::indexer::Indexer::new(&dir, vec!["body".into()], vec![1.0], per_seg);
        for i in 0..docs {
            ix.add(&format!("d{i}"), &[&format!("общее слово{}", i % 7)]);
        }
        ix.flush_now();
        dir
    }

    fn load(dir: &str) -> Vec<Index> {
        manifest::segments(dir).iter().filter_map(|n| index::load(n).ok()).collect()
    }

    fn write_catalog(dir: &str, sources: &[&Index]) {
        std::fs::write(format!("{dir}/{}", crate::catalog::FILE), crate::catalog::build(sources))
            .unwrap();
    }

    #[test]
    fn catalog_refresh_is_deferred_until_the_tail_is_material() {
        let dir = corpus("refresh-tail", 70, 1);
        let segs = load(&dir);
        let refs: Vec<&Index> = segs.iter().collect();
        assert!(refs.len() > CATALOG_MAX_TAIL);

        write_catalog(&dir, &refs[..1]);
        assert!(catalog_refresh_needed(&dir, &refs), "большой хвост не потребовал свёртки");

        assert!(refresh_catalog(&dir), "каталог с safety tail не собрался");
        let covered =
            crate::catalog::coverage(&dir, &refs.iter().map(|ix| ix.head_id).collect::<Vec<_>>())
                .expect("покрытие не прочиталось");
        assert_eq!(refs.len() - covered, CATALOG_RETAIN_TAIL);
        assert!(!catalog_refresh_needed(&dir, &refs), "каталог пересобрался бы сразу снова");
        std::fs::remove_dir_all(&dir).ok();
    }

    #[test]
    fn merge_does_not_rebuild_the_global_catalog_until_the_series_settles() {
        let dir = corpus("refresh-after-series", 400, 50);
        let before = load(&dir);
        let before_refs: Vec<&Index> = before.iter().collect();
        write_catalog(&dir, &before_refs);
        let catalog_before = std::fs::read(format!("{dir}/{}", crate::catalog::FILE)).unwrap();

        let cfg = Config {
            target_docs: 1_000,
            at_once: 8,
            dead_fraction: 0.9,
            grace_ms: 0,
            merge_policy: merge::MergeKind::Flat,
            ..Config::default()
        };
        assert!(once(&dir, cfg).expect("merge").is_some());
        assert_eq!(
            std::fs::read(format!("{dir}/{}", crate::catalog::FILE)).unwrap(),
            catalog_before,
            "маленький merge переписал весь глобальный каталог"
        );

        let after = load(&dir);
        let after_refs: Vec<&Index> = after.iter().collect();
        assert!(catalog_refresh_needed(&dir, &after_refs));
        assert!(refresh_catalog(&dir), "финальная свёртка каталога не собралась");
        assert!(!catalog_refresh_needed(&dir, &after_refs));
        std::fs::remove_dir_all(&dir).ok();
    }

    #[test]
    fn immutable_segments_open_the_id_directory_only_once() {
        let dir = corpus("cached-directory", 400, 50);
        let indexes = load(&dir);
        let refs: Vec<&Index> = indexes.iter().collect();
        write_catalog(&dir, &refs);
        drop(indexes);

        let segments = crate::segments::Segments::load(&dir).expect("ReadView");
        let ids = vec!["d17".to_string(), "d399".to_string(), "missing".to_string()];
        let _ = crate::stats::take();
        for _ in 0..3 {
            let places = segments.locate_ids(&ids).expect("каталог поколения");
            assert!(!places[0].is_empty());
            assert!(!places[1].is_empty());
            assert!(places[2].is_empty());
        }
        if crate::stats::ENABLED {
            let counters = crate::stats::take();
            assert_eq!(counters.catalog_opened, 1, "каталог mmap-ился на каждый GET");
            assert_eq!(counters.catalog_used, 3);
        }
        std::fs::remove_dir_all(&dir).ok();
    }

    /// Удаление с каталогом гасит ровно то же, что и без него.
    ///
    /// ## Почему сверка, а не проверка «работает ли каталог»
    ///
    /// У каталога одно обязательство — не менять ответ. Проверять надо именно
    /// его, и проверять на **одном и том же** корпусе двумя проходами: с
    /// файлом и без. Всё прочее — сколько он сэкономил, попал ли — это про
    /// скорость, а про скорость он вправе быть каким угодно.
    #[test]
    fn deletion_answers_the_same_with_and_without_a_catalog() {
        let want: Vec<String> = (0..400u32).step_by(3).map(|i| format!("d{i}")).collect();

        // Без каталога.
        let bare = corpus("bare", 400, 50);
        let bare_segs = load(&bare);
        let _ = crate::stats::take();
        let a = delete_in(&bare_segs.iter().collect::<Vec<_>>(), &want).expect("удаление");
        let without = crate::stats::take().catalog_used;

        // С каталогом — тот же корпус, собранный заново.
        let with = corpus("with", 400, 50);
        let with_segs = load(&with);
        let refs: Vec<&Index> = with_segs.iter().collect();
        write_catalog(&with, &refs);
        assert!(
            crate::catalog::Catalog::open(
                &with,
                crate::catalog::stamp(&refs.iter().map(|x| x.head_id).collect::<Vec<_>>())
            )
            .is_some(),
            "каталог не открылся — проверка вхолостую"
        );
        let b = delete_in(&refs, &want).expect("удаление");
        let used = crate::stats::take().catalog_used;

        assert_eq!(a.killed, b.killed, "с каталогом погашено другое число документов");
        assert_eq!(a.missing, b.missing, "с каталогом разошёлся список ненайденных");
        assert!(a.killed > 100, "погашено всего {} — проверка вхолостую", a.killed);
        // И оба пути правда пройдены: иначе это сверка двух одинаковых заходов.
        if crate::stats::ENABLED {
            assert_eq!(without, 0, "на корпусе без каталога он всё-таки нашёлся");
            assert_eq!(used, 1, "каталог не ответил — сверять было нечего");
        }
        std::fs::remove_dir_all(&bare).ok();
        std::fs::remove_dir_all(&with).ok();
    }

    /// Каталог, убранный на ходу, ничего не ломает.
    ///
    /// Он производный: у него нет ни порядка `fsync`, ни участия в
    /// восстановлении, и потерять его нельзя. Проверяется это буквально —
    /// файл удаляется между двумя заходами, и второй обязан отработать так же.
    #[test]
    fn a_catalog_removed_mid_flight_changes_nothing() {
        let dir = corpus("gone", 300, 40);
        let segs = load(&dir);
        let refs: Vec<&Index> = segs.iter().collect();
        write_catalog(&dir, &refs);

        let first: Vec<String> = (0..150u32).step_by(2).map(|i| format!("d{i}")).collect();
        let _ = crate::stats::take();
        let a = delete_in(&refs, &first).expect("удаление с каталогом");
        assert!(a.killed > 50, "первый заход погасил {} — вхолостую", a.killed);
        if crate::stats::ENABLED {
            assert_eq!(crate::stats::take().catalog_used, 1, "каталог не отвечал до удаления");
        }

        // Каталог убран прямо посреди работы.
        std::fs::remove_file(format!("{dir}/{}", crate::catalog::FILE)).unwrap();

        let second: Vec<String> = (150..300u32).step_by(2).map(|i| format!("d{i}")).collect();
        let b = delete_in(&refs, &second).expect("удаление без каталога");
        if crate::stats::ENABLED {
            assert_eq!(crate::stats::take().catalog_used, 0, "убранный каталог всё ещё отвечает");
        }
        assert_eq!(b.killed, second.len(), "без каталога погашено не всё: {}", b.killed);
        assert!(b.missing.is_empty(), "без каталога кто-то не нашёлся: {:?}", b.missing);
        std::fs::remove_dir_all(&dir).ok();
    }

    /// Испорченный и устаревший каталог тоже не меняют ответа.
    ///
    /// Три порчи разом: подпись состава от другого набора, обрезанный хвост и
    /// перевранный номер сегмента. Первые две отвергаются на открытии, третья
    /// доживает до сверки — и там отсекается чтением настоящего
    /// идентификатора.
    #[test]
    fn a_broken_catalog_does_not_change_the_answer() {
        let want: Vec<String> = (0..200u32).step_by(2).map(|i| format!("d{i}")).collect();
        let bare = corpus("bare2", 200, 30);
        let bare_segs = load(&bare);
        let truth = delete_in(&bare_segs.iter().collect::<Vec<_>>(), &want).expect("удаление");
        assert!(truth.killed > 50, "погашено {} — вхолостую", truth.killed);

        for spoil in ["stamp", "cut", "wrong-segment"] {
            let dir = corpus(&format!("spoil-{spoil}"), 200, 30);
            let segs = load(&dir);
            let refs: Vec<&Index> = segs.iter().collect();
            let mut bytes = crate::catalog::build(&refs);
            match spoil {
                // Подпись от другого состава: каталог верен, но не для нас.
                "stamp" => bytes[16..24].copy_from_slice(&0xdead_beefu64.to_le_bytes()),
                // Обрыв на середине записи.
                "cut" => bytes.truncate(bytes.len() - 5),
                // Номер сегмента, которого в составе нет.
                _ => {
                    let at = 24 + 8;
                    bytes[at..at + 4].copy_from_slice(&9999u32.to_le_bytes());
                }
            }
            std::fs::write(format!("{dir}/{}", crate::catalog::FILE), &bytes).unwrap();
            let got = delete_in(&refs, &want).expect("удаление");
            assert_eq!(
                (got.killed, got.missing.len()),
                (truth.killed, truth.missing.len()),
                "порча {spoil} изменила ответ"
            );
            std::fs::remove_dir_all(&dir).ok();
        }
        std::fs::remove_dir_all(&bare).ok();
    }
}
