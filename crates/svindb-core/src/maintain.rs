//! Обслуживание индекса: укрупнение и уборка.
//!
//! ## Три части вместо одной
//!
//! Заход разделён на [`choose`], [`run`] и [`publish`], и разделение это не
//! ради стройности. Первая и третья идут под замком состава — тем же, который
//! берут приём (`Writer::push`), сброс и удаление, — и потому обязаны быть
//! быстрыми: просмотр открытых сегментов и правка одного файла. Вторая —
//! слияние, и она длится столько, сколько длится: секунды на миллионе, минуты
//! на пяти гигабайтах. Держи её замок, как было раньше, — и на эти минуты
//! встали бы приём и удаления всего узла.
//!
//! Платой за это стало окно, в котором состав меняется под работающим слиянием.
//! Что в него попадает и что с этим делается — у [`publish`].

use std::collections::HashSet;

use crate::index::{self, Index};
use crate::manifest;
use crate::merge;

/// Настройки обслуживания.
#[derive(Clone, Copy, Debug)]
pub struct Config {
    /// Потолок укрупнения **в документах**.
    ///
    /// Прежде это был единственный потолок, и он же решал, что трогать, а что
    /// нет: мельче цели — укрупняем, крупнее — не трогаем. Ярусной политике
    /// ([`merge::plan_tiered`]) он достался вторым потолком рядом с байтовым, а
    /// решение «трогать или нет» перешло к байтам целиком — см.
    /// [`merge::Seg::frozen`]. Причина не в стройности: одинаковые по документам
    /// сегменты отличаются по байтам на порядок, потому что хвост корпуса
    /// тяжелее середины, и мерить ими размер значит не мерить его вовсе.
    ///
    /// Оставлен он потому, что перенумерация внутри сегмента
    /// тридцатидвухбитная, и запас по документам честнее держать явным, чем
    /// выводить из плотности корпуса, которая у каждого своя.
    pub target_docs: usize,
    /// Сколько сегментов брать за одно укрупнение.
    pub at_once: usize,
    /// С какой доли мёртвого сегмент стоит переписать.
    ///
    /// Порог для **незамороженных**. У замороженных он свой и выше — см.
    /// [`grown_dead_fraction`].
    pub dead_fraction: f64,
    /// Сколько ждать перед удалением исходных каталогов.
    pub grace_ms: u64,
    /// Сколько потоков отдавать слиянию. `0` — четверть ядер, но не меньше
    /// одного.
    ///
    /// Умолчание — доля, а не число: узел на четырёх ядрах и узел на
    /// шестидесяти четырёх нуждаются в разном, и зашитое число неверно на
    /// обоих. Четверть — потому что слияние фоновое: приём сжимает своё
    /// содержимое ровно теми же ядрами, и отобрать их у него значило бы
    /// разменять видимую скорость узла на невидимую работу. Разбор — у
    /// [`crate::merge::Limits::threads`].
    pub merge_threads: usize,
    /// Потолок слитого сегмента в мегабайтах. `0` — умолчание [`merge::Tier`].
    ///
    /// Достижимый размер — около **половины** этого числа: сегмент замораживается
    /// на половине потолка, чтобы всегда оставалось место слить его с равным.
    pub max_merged_mb: u64,
    /// Пол яруса в мегабайтах: ниже него размеры не различаются. `0` — умолчание.
    pub floor_mb: u64,
    /// Сколько сегментов позволено одному ярусу. `0` — умолчание.
    pub per_tier: usize,
    /// Какой политикой укрупнять.
    ///
    /// Здесь, а не только в переменной среды: переменная заводилась как рычаг
    /// оператора **до** появления настройки, и с её появлением место политики
    /// тут. Переменная осталась перекрытием на один запуск — тем, чем и была.
    ///
    /// Пределы `Tiered` из этого поля не берутся: их собирает [`Config::tier`]
    /// из соседних настроек, иначе одно и то же число жило бы в двух местах.
    pub merge_policy: merge::MergeKind,
    /// Сколько свободно на диске, байт. `0` — не знаем, не проверяем.
    ///
    /// ## Зачем планировщику знать про диск
    ///
    /// Слияние пишет выход рядом с источниками и только потом их снимает.
    /// Значит на время работы место нужно **и под то, и под другое**. Кончится
    /// оно посреди — работа бросается целиком: часы счёта в мусор, каталог
    /// недописанного на диске, а место, которое слияние собиралось вернуть, так
    /// и не вернулось. Хуже того, это повторяется каждые две секунды.
    ///
    /// Проверка до начала стоит одного системного вызова и превращает это в
    /// названный отказ с двумя числами.
    ///
    /// Число приходит снаружи, а не измеряется здесь: свободное место узнаёт
    /// узел, у него для этого есть системная часть, а ядро индекса про
    /// файловые системы не знает и знать не обязано.
    pub disk_free_bytes: u64,
    /// Сколько памяти отдать слиянию, байт. `0` — вывести из машины.
    ///
    /// Здесь, а не только внутри [`merge_budget`], потому что от этого числа
    /// зависит **выбор работы**, а не только её исполнение: заход, у которого
    /// уборка не влезла, ведёт себя иначе того, у которого она влезла. Проверять
    /// такое поведение переменной среды значило бы проверять его вперемешку со
    /// всеми соседними тестами процесса.
    pub merge_budget_bytes: u64,
}

impl Default for Config {
    fn default() -> Self {
        Config {
            target_docs: 1_000_000,
            at_once: 8,
            dead_fraction: 0.20,
            grace_ms: 2000,
            merge_threads: 0,
            max_merged_mb: 0,
            floor_mb: 0,
            per_tier: 0,
            merge_policy: merge::MergeKind::default(),
            merge_budget_bytes: 0,
            disk_free_bytes: 0,
        }
    }
}

impl Config {
    /// Сколько памяти отдать слиянию на самом деле.
    fn budget(&self) -> u64 {
        if self.merge_budget_bytes > 0 {
            self.merge_budget_bytes.max(merge::PEAK_FLOOR)
        } else {
            merge_budget()
        }
    }

    /// Сколько потоков отдать слиянию на самом деле.
    fn threads(&self) -> usize {
        if self.merge_threads > 0 {
            return self.merge_threads;
        }
        std::thread::available_parallelism().map_or(1, |n| (n.get() / 4).max(1))
    }

    /// Ярусные пределы, собранные из настроек обслуживания.
    ///
    /// Из настроек приходят двое: ширина слияния и потолок в документах.
    /// Байтовые пределы берутся умолчаниями [`merge::Tier`] — их у настроек
    /// пока нет, и заводить их обязан тот, кто владеет файлом настроек.
    /// Те же пределы наружу — для диагностики, которая обязана считать
    /// «заморожен» по тому же правилу, по какому его считает политика.
    pub fn tier_of(&self) -> merge::Tier {
        self.tier()
    }

    fn tier(&self) -> merge::Tier {
        let d = merge::Tier::default();
        // Ноль значит «как решит движок», а не «нуль байт»: настройка, у которой
        // ноль означал бы нулевой потолок, выключала бы укрупнение при попытке
        // его не настраивать.
        let mb = |v: u64, def: u64| if v > 0 { v << 20 } else { def };
        merge::Tier {
            at_once: self.at_once,
            max_docs: self.target_docs,
            max_merged: mb(self.max_merged_mb, d.max_merged),
            floor_bytes: mb(self.floor_mb, d.floor_bytes),
            per_tier: if self.per_tier > 0 { self.per_tier } else { d.per_tier },
            // Память узла — не настройка, а обстоятельство, и потому берётся
            // здесь, а не из файла. Окно набирается, пока влезает; не влезло —
            // окно короче, сегментов больше. Это дешевле любого отказа.
            max_peak: self.budget(),
            ..d
        }
    }

    /// Какой политикой укрупнять. Умолчание — ярусная.
    fn merge_policy(&self) -> merge::MergePolicy {
        // Переменная среды перекрывает настройку, а не наоборот: ею чинят узел,
        // который настроил себя во вред, и требовать для этого правки файла в
        // каталоге, который, может, и не открывается, значило бы не дать рычага
        // вовсе. Тот же порядок старшинства, что у аргументов запуска.
        let chosen = match std::env::var_os(MERGE_POLICY_ENV) {
            Some(w) => policy_word(Some(w.as_ref())),
            None => self.merge_policy,
        };
        // Пределы приходят от соседних настроек, а не от выбора: одно число не
        // должно жить в двух местах.
        match chosen {
            merge::MergeKind::Flat => merge::MergePolicy::Flat(merge::Policy {
                at_once: self.at_once,
                max_docs: self.target_docs,
            }),
            merge::MergeKind::Tiered => merge::MergePolicy::Tiered(self.tier()),
            merge::MergeKind::UpdateHeavy => {
                let mut t = self.tier();
                // Широкое окно гасит россыпь heartbeat-сегментов десятками за
                // один проход. Пользовательские значения могут сделать профиль
                // ещё агрессивнее, но не тише его нижней границы.
                t.at_once = t.at_once.max(32);
                t.per_tier = t.per_tier.max(t.at_once);
                t.floor_bytes = t.floor_bytes.max(16 * 1024 * 1024);
                // Погашенные версии у update-heavy корпуса — нормальный фон,
                // поэтому окно, возвращающее место, важнее такого же чистого.
                t.reclaim_weight = t.reclaim_weight.max(3.0);
                merge::MergePolicy::UpdateHeavy(t)
            }
        }
    }
}

/// Чем оператор просит плоскую политику, пока настройка не заведена.
///
/// ## Почему переменная среды, а не `merge_policy` в настройках
///
/// Настройке там и место, и слово у неё то же самое —
/// [`merge::MergePolicy::parse`] разбирает его для обоих читателей. Но файл
/// настроек правится отдельной работой, а рычаг оператору нужен вместе с самой
/// политикой: без него сказать ярусному укрупнению «не сейчас» можно только
/// через `--no-maintain`, а он гасит заодно и уборку — то есть мёртвое
/// перестаёт возвращаться на диск. Переменная среды даёт тот же ответ до
/// перезапуска узла и уходит, как только настройка появится.
pub const MERGE_POLICY_ENV: &str = "SVINDB_MERGE_POLICY";

/// Разбирает значение настройки или переменной среды.
///
/// Непонятное слово — не отказ, а ярусная политика и жалоба в поток ошибок:
/// узел, не поднявшийся из-за опечатки в необязательной переменной, хуже узла,
/// который сказал, что её не понял. Жалоба одна на запуск: заход идёт каждые две
/// секунды, и повторять её сорок три тысячи раз в сутки — это не сообщение, а
/// шум, в котором тонет всё остальное.
fn policy_word(word: Option<&std::ffi::OsStr>) -> merge::MergeKind {
    let Some(word) = word else { return merge::MergeKind::default() };
    let text = word.to_string_lossy().to_string();
    if text.trim().is_empty() {
        return merge::MergeKind::default();
    }
    match merge::MergeKind::parse(&text) {
        Some(p) => p,
        None => {
            static ONCE: std::sync::Once = std::sync::Once::new();
            ONCE.call_once(|| {
                eprintln!(
                    "{MERGE_POLICY_ENV}={text}: не понимаю такой политики укрупнения, \
                     знаю tiered, update_heavy и flat — беру tiered"
                );
            });
            merge::MergeKind::default()
        }
    }
}

/// С какой доли мёртвого стоит переписывать **замороженный** сегмент.
///
/// ## Почему порог у него свой и выше
///
/// Уборка переписывает сегмент целиком, и прибыль с неё — `d/(1-d)`
/// возвращённых байт на каждый записанный, где `d` — доля мёртвого. При 0.20 это
/// 0.25 байта на байт, при 0.35 — уже 0.54. Незамороженному сегменту такой
/// размен прощается: он всё равно будет переписан укрупнением, и лишний заход
/// уборки просто опережает слияние. Замороженный же не сливается ни с кем
/// никогда ([`merge::Seg::frozen`]) — каждый его заход это отдельная полная
/// перезапись, и окупаться она обязана сама.
///
/// Не ниже общего порога: оператор, поднявший `dead_fraction`, просит меньше
/// перезаписей, а не больше, и молча сбрасывать его выбор до нашего числа
/// значило бы решать за него.
pub fn grown_dead_fraction(cfg: Config) -> f64 {
    cfg.dead_fraction.max(GROWN_DEAD_FRACTION)
}

/// Порог для замороженных. Разбор — у [`grown_dead_fraction`].
const GROWN_DEAD_FRACTION: f64 = 0.35;

/// Что сделало обслуживание за один заход.
#[derive(Debug)]
pub enum Action {
    /// Укрупнение: сколько сегментов слито и сколько в них документов.
    ///
    /// `carried` — сколько удалений, случившихся **во время** слияния,
    /// публикация перенесла в выход. Величина эта обычно ноль, и молчать о ней
    /// нельзя: ненулевая означает, что окно без замка и правда наблюдается, а
    /// перестань она гаситься — удалённое воскресало бы, и заметить это было бы
    /// не по чему.
    Consolidated {
        segments: usize,
        docs: usize,
        carried: usize,
        took_ms: f64,
    },
    Reclaimed {
        was: usize,
        now: usize,
        carried: usize,
        took_ms: f64,
    },
}

/// Гасит документы по идентификаторам. Отдаёт число погашенных.
///
/// Удаления применяются **пачкой по сегментам**: карта живых подменяется
/// целиком, и делать это на каждый идентификатор значило бы переписывать
/// четверть мегабайта ради одного бита.
pub fn delete(dir: &str, ids: &[String]) -> std::io::Result<Removed> {
    // Состав читается с проверкой, а не «как получится».
    //
    // `manifest::segments` при неудаче чтения отдаёт **пустой** список, и для
    // обхода это терпимо — обходить нечего. Но здесь пустой список означает
    // «сегментов нет», то есть гасить не в чем, — и удаление отчитывается об
    // успехе, не тронув ни одного документа. Для удаления это худший из
    // возможных отказов: вызывающий уверен, что данные убраны, а они на месте.
    let names = manifest::segments_checked(dir)
        .map_err(|e| std::io::Error::new(std::io::ErrorKind::InvalidData, e))?;
    let loaded: Vec<Index> = names.iter().filter_map(|n| index::load(n).ok()).collect();
    delete_in(&loaded.iter().collect::<Vec<_>>(), ids)
}

/// Пересобирает каталог идентификаторов под нынешний состав.
///
/// Молча: у каталога нет ни одного обязательства, кроме «не врать», и
/// невозможность собраться — не событие. Не собрался — его нет, а без него
/// поиск по идентификатору идёт обходом, как шёл всегда.
///
/// Пишется через временное имя с переименованием: наполовину записанный файл
/// отвергся бы и на открытии (заголовок обещает больше, чем лежит), но платить
/// за это отвержение на каждом запросе до следующей уборки не за что.
pub fn refresh_catalog(dir: &str) -> bool {
    let names = manifest::segments(dir);
    let loaded: Vec<Index> = names.iter().filter_map(|n| index::load(n).ok()).collect();
    if loaded.len() != names.len() {
        // Часть состава не открылась: каталог по неполному составу указывал бы
        // не туда, и подпись это не поймала бы — она считается по тому, что
        // открылось.
        return false;
    }
    // Не включаем в каталог самый новый L0-хвост. Именно его постоянно
    // переписывает compaction; каталог по всему составу устаревал после
    // каждого маленького merge и снова сортировал сотни миллионов ID.
    // Половина предела оставляет гистерезис: хвост может вырасти ещё на 32
    // сегмента, прежде чем понадобится следующая последовательная свёртка.
    let covered = loaded.len().saturating_sub(CATALOG_RETAIN_TAIL).max(1);
    let refs: Vec<&Index> = loaded.iter().collect();
    let bytes = crate::catalog::build(&refs[..covered]);
    let tmp = format!("{dir}/{}.tmp", crate::catalog::FILE);
    if std::fs::write(&tmp, &bytes).is_err() {
        std::fs::remove_file(&tmp).ok();
        return false;
    }
    if std::fs::rename(&tmp, format!("{dir}/{}", crate::catalog::FILE)).is_err() {
        std::fs::remove_file(&tmp).ok();
        return false;
    }
    true
}

/// Создаёт первый каталог на первом же disk-сегменте.
///
/// Дальнейшие append-публикации используют его как generation-aware префикс,
/// а merge сворачивает хвост вызовом [`refresh_catalog`]. На большом уже
/// существующем составе функция намеренно ничего не строит синхронно: внезапно
/// сортировать сотни миллионов ID на пути ACK хуже отсутствующего кеша.
pub fn ensure_initial_catalog(dir: &str) {
    if std::path::Path::new(&format!("{dir}/{}", crate::catalog::FILE)).exists() {
        return;
    }
    if manifest::segments(dir).len() == 1 {
        let _ = refresh_catalog(dir);
    }
}

/// Сколько append-сегментов допустимо проверять точным хвостом до свёртки
/// глобального ID directory.
///
/// Пересобирать каталог на каждый flush нельзя: на сотнях миллионов ID сам
/// каталог занимает гигабайты. Шестьдесят четыре сегмента сохраняют point read
/// ограниченным и амортизируют одну большую последовательную пересборку.
pub const CATALOG_MAX_TAIL: usize = 64;

/// Сколько самых новых сегментов новая свёртка намеренно оставляет точному
/// хвостовому пути. Значение меньше [`CATALOG_MAX_TAIL`] создаёт гистерезис и
/// не даёт plateau/append чередованию перестраивать каталог в tight loop.
pub const CATALOG_RETAIN_TAIL: usize = 32;

/// Нужна ли свёртка ID directory для нынешнего устойчивого состава.
///
/// После merge старый каталог обычно перестаёт описывать какой-либо префикс и
/// функция отвечает `true`. Во время серии merge вызывать её можно, но саму
/// пересборку следует делать только когда планировщик больше не видит работы:
/// иначе следующий маленький merge немедленно обесценит гигабайтный результат.
pub fn catalog_refresh_needed(dir: &str, sources: &[&Index]) -> bool {
    if sources.is_empty() {
        return false;
    }
    let idents: Vec<(u64, i64)> = sources.iter().map(|index| index.head_id).collect();
    crate::catalog::coverage(dir, &idents)
        .is_none_or(|covered| sources.len().saturating_sub(covered) >= CATALOG_MAX_TAIL)
}

/// Где лежат эти идентификаторы: по каталогу, если он есть и сошёлся.
///
/// ## Почему это отдельный шаг, а не ветка внутри обхода
///
/// Каталог обязан быть **неразличим** по ответу от своего отсутствия. Самый
/// надёжный способ это обеспечить — не смешивать пути: либо каталог отвечает на
/// **все** спрошенные идентификаторы со сверкой, либо его нет вовсе и работает
/// прежний обход. Половинчатый ответ («на эти ответил, на те не смог») пришлось
/// бы склеивать, и склейка стала бы третьим путём, который никто не проверяет.
///
/// `None` — каталога нет, он не сошёлся или не смог ответить на какой-то из
/// спрошенных. Вызывающий идёт обычным обходом.
/// Открытый generation-aware ID directory одного immutable состава.
///
/// Отдельный объект нужен не ради API: построение resident grid гигабайтного
/// `catalog.bin` занимало сотни миллисекунд, когда point GET повторял его на
/// каждый запрос. `Segments` держит этот объект один раз на всё поколение.
pub struct IdDirectory {
    catalog: crate::catalog::Catalog,
    covered: usize,
    prefix: Vec<(u64, i64)>,
}

impl IdDirectory {
    pub fn open(sources: &[&Index]) -> Option<IdDirectory> {
        Self::open_guarded(sources, None)
    }

    pub fn open_guarded(
        sources: &[&Index],
        guard: Option<&crate::work::Guard>,
    ) -> Option<IdDirectory> {
        if guard.is_some_and(|g| !g.check()) {
            return None;
        }
        let first = sources.first()?;
        // Каталог лежит рядом с сегментами, то есть на уровень выше любого из
        // них.
        let dir = std::path::Path::new(&first.dir).parent()?.to_string_lossy().to_string();
        let idents: Vec<(u64, i64)> = sources.iter().map(|ix| ix.head_id).collect();
        // Не строим resident grid заведомо старого/скопированного каталога
        // каждые 500 мс фоновой проверки. После открытия stamp проверяется
        // повторно: атомарная замена файла между шагами не обходит проверку.
        crate::catalog::coverage(&dir, &idents)?;
        let (catalog, covered) =
            crate::catalog::Catalog::open_prefix_guarded(&dir, &idents, guard)?;
        let prefix = idents[..covered].to_vec();
        Some(IdDirectory { catalog, covered, prefix })
    }

    /// Можно ли разделить уже открытый directory со следующим ReadView.
    ///
    /// Частые searchable-live публикации меняют объект [`Segments`], но не
    /// дисковый префикс, который адресует каталог. Поэтому cache обязан жить
    /// дольше одного объекта ReadView. При merge префикс меняется и разделение
    /// прекращается; при большом append-хвосте новый каталог подхватывается
    /// только после того, как фоновая свёртка действительно опубликовала более
    /// длинное покрытие.
    pub(crate) fn reusable(&self, sources: &[&Index]) -> bool {
        if !self.compatible(sources) {
            return false;
        }
        if sources.len().saturating_sub(self.covered) < CATALOG_MAX_TAIL {
            return true;
        }
        let Some(first) = sources.first() else { return false };
        let Some(parent) = std::path::Path::new(&first.dir).parent() else { return false };
        let idents: Vec<(u64, i64)> = sources.iter().map(|index| index.head_id).collect();
        // Пока на диске прежнее покрытие, старое mmap остаётся лучшим вариантом:
        // переоткрывать те же гигабайты на каждой live-публикации нельзя.
        crate::catalog::coverage(&parent.to_string_lossy(), &idents)
            .is_none_or(|covered| covered <= self.covered)
    }

    pub(crate) fn compatible(&self, sources: &[&Index]) -> bool {
        sources.len() >= self.prefix.len()
            && sources
                .iter()
                .zip(self.prefix.iter())
                .all(|(index, identity)| index.head_id == *identity)
    }

    pub fn locate(
        &self,
        sources: &[&Index],
        ids: &[String],
        hashes: &[u64],
    ) -> Option<Vec<Vec<(usize, u32)>>> {
        self.locate_guarded(sources, ids, hashes, None)
    }

    /// То же построение мест, но с кооперативным сторожем запроса.
    ///
    /// ID-directory обычно резко сокращает point-read, однако на большом
    /// MGET у него остаются два потенциально длинных участка: lookup каждой
    /// цели в каталоге и проверка append/L0-хвоста. Нельзя считать каталог
    /// «маленьким» только потому, что он mmap: холодная страница может ждать
    /// диск. `None` означает отмену/истечение deadline, а не повреждение
    /// каталога; вызывающий обязан отличить этот случай до fallback-обхода.
    pub fn locate_guarded(
        &self,
        sources: &[&Index],
        ids: &[String],
        hashes: &[u64],
        guard: Option<&crate::work::Guard>,
    ) -> Option<Vec<Vec<(usize, u32)>>> {
        let mut scratch: Vec<(u32, u32)> = Vec::new();
        let mut out: Vec<Vec<(usize, u32)>> = Vec::with_capacity(ids.len());
        for (id, &hash) in ids.iter().zip(hashes.iter()) {
            if guard.is_some_and(|g| !g.check()) {
                return None;
            }
            let mut places =
                crate::catalog::locate(&self.catalog, sources, id, hash, &mut scratch)?;
            // Сегменты после покрытого префикса — небольшой L0-хвост,
            // появившийся append-публикациями. Каталог по-прежнему избавляет
            // от обхода всего старого состава; хвост сворачивается обслуживанием.
            let mut docs = Vec::new();
            for (at, ix) in sources.iter().enumerate().skip(self.covered) {
                if guard.is_some_and(|g| !g.check()) {
                    return None;
                }
                docs.clear();
                ix.idmap.find_all(id, hash, &mut docs);
                places.extend(docs.iter().map(|&doc| (at, doc)));
            }
            out.push(places);
        }
        crate::stats::catalog_used(1);
        Some(out)
    }
}

fn by_catalog(
    sources: &[&Index],
    ids: &[String],
    hashes: &[u64],
) -> Option<Vec<Vec<(usize, u32)>>> {
    IdDirectory::open(sources)?.locate(sources, ids, hashes)
}

/// Generation-aware места идентификаторов для point GET/MGET.
///
/// `None` означает только «каталог не помог»; вызывающий обязан выполнить
/// прежний точный обход. `Some` содержит полный ответ: глобальный префикс плюс
/// append-хвост, со сверкой настоящих ID против совпадений хеша.
pub fn locate_ids(sources: &[&Index], ids: &[String]) -> Option<Vec<Vec<(usize, u32)>>> {
    let hashes: Vec<u64> = ids.iter().map(|id| crate::bloom::hash(id)).collect();
    by_catalog(sources, ids, &hashes)
}

/// То же по уже загруженным сегментам.
pub fn delete_in(sources: &[&Index], ids: &[String]) -> std::io::Result<Removed> {
    if sources.is_empty() || ids.is_empty() {
        return Ok(Removed {
            killed: 0,
            logical: Vec::new(),
            missing: ids.to_vec(),
            touched: Vec::new(),
        });
    }
    let mut killed = 0usize;
    let mut touched = Vec::new();
    // Один логический id может иметь несколько физических копий в разных
    // frozen/legacy сегментах. Этот флаг строится в том же проходе, что и
    // гашение, поэтому вызывающему не нужен второй полный обход только ради
    // ответа `deleted`.
    let mut killed_id: Vec<bool> = vec![false; ids.len()];
    // Документ, которого нет ни в одном сегменте, — не обязательно
    // несуществующий: он может лежать в буфере приёма и стать видимым через
    // секунду. Возвращаем такие вызывающему, а не молча теряем.
    let mut found_any: Vec<bool> = vec![false; ids.len()];
    // Хеши считаются один раз на все сегменты: от сегмента они не зависят, а
    // сегментов десятки.
    let hashes: Vec<u64> = ids.iter().map(|id| crate::bloom::hash(id)).collect();
    // Каталог говорит, где искать; не сошёлся — ищем как искали всегда.
    let known = by_catalog(sources, ids, &hashes);
    for (s, ix) in sources.iter().enumerate() {
        let name = ix.dir.as_str();
        if ix.idmap.is_empty() {
            continue;
        }
        // Сначала ищем всё, что есть в этом сегменте, и только потом трогаем
        // карту: если ничего не нашлось, файл не переписывается вовсе.
        let mut found: Vec<(usize, u32)> = Vec::with_capacity(ids.len());
        match known.as_ref() {
            Some(all) => {
                for (i, places) in all.iter().enumerate() {
                    found.extend(places.iter().filter(|(at, _)| *at == s).map(|&(_, d)| (i, d)));
                }
            }
            None => {
                let mut docs: Vec<u32> = Vec::new();
                for (i, (id, &h)) in ids.iter().zip(hashes.iter()).enumerate() {
                    docs.clear();
                    ix.idmap.find_all(id, h, &mut docs);
                    found.extend(docs.iter().map(|&d| (i, d)));
                }
            }
        }
        if found.is_empty() {
            continue;
        }
        // Карта уже отображена сегментом и правится на месте. Ни чтения, ни
        // записи файла, ни переоткрытия читателями — один атомарный сброс бита
        // на документ.
        let mut changed = false;
        for (i, doc) in found {
            found_any[i] = true;
            if ix.kill(doc) {
                killed += 1;
                killed_id[i] = true;
                changed = true;
            }
        }
        if changed {
            touched.push(name.to_string());
        }
    }
    let missing = ids
        .iter()
        .zip(found_any.iter())
        .filter(|(_, seen)| !**seen)
        .map(|(id, _)| id.clone())
        .collect();
    let mut logical = Vec::new();
    let mut logical_seen = HashSet::new();
    for (id, killed) in ids.iter().zip(killed_id) {
        if killed && logical_seen.insert(id.as_str()) {
            logical.push(id.clone());
        }
    }
    Ok(Removed { killed, logical, missing, touched })
}

/// Гасит **старые** версии перечисленных идентификаторов, оставляя новейшую.
///
/// ## Зачем это отдельно от [`delete_in`]
///
/// Удаление гасит все версии: документа больше нет. Замена — не удаление: у неё
/// есть преемник, и он обязан пережить гашение. Разница видна только тому, кто
/// смотрит на весь состав разом, потому что «новейшая» — это свойство не
/// сегмента, а их порядка.
///
/// ## Почему это применяется после публикации, а не до
///
/// Замена состоит из двух событий с разной задержкой: старая версия перестаёт
/// быть нужной сразу, новая становится видимой только с публикацией. Гаси
/// старую раньше — и между этими событиями у документа не остаётся ни одной
/// живой версии: поиск отвечает пустотой на документ, который никуда не девался.
/// Ровно это и наблюдалось как «база иногда теряет singleton».
///
/// Поэтому порядок обратный: сперва новая версия входит в состав, затем гасятся
/// старые. Промежуток между ними — доли микросекунды под одним замком, и в нём
/// видны **обе** версии, а не ни одной. Это не равноценный обмен, а
/// осознанный: лишний кандидат стоит проверки, отсутствие документа — неверного
/// решения. Читатель по идентификатору не страдает и в этом промежутке: он
/// обходит состав с конца и берёт первую живую версию, то есть новейшую.
///
/// ## Почему новейшую называют, а не вычисляют
///
/// Казалось бы, её видно и так: состав упорядочен от старых сегментов к новым,
/// значит новейшая версия — в последнем сегменте, где она есть. Это неправда, и
/// неправда опасная. Слияние кладёт результат на место **первого** из
/// источников: слей оно самый свежий сегмент с давним, и документы свежего
/// окажутся в начале списка, впереди чужих прежних версий. Гашение «по порядку»
/// приняло бы прежнюю версию за новейшую, погасило бы настоящую — и документ
/// либо откатился бы на версию назад, либо исчез совсем, если прежняя к тому
/// времени уже была погашена. Воспроизведено стендом под нагрузкой с
/// работающим обслуживанием; без обслуживания не воспроизводится.
///
/// Поэтому хранитель называется явно: это сегмент, в который **только что** лёг
/// преемник, и знает его тот, кто публикует.
///
/// ## Почему это можно звать сколько угодно раз
///
/// Гасится всё, кроме содержимого хранителя, и только у тех идентификаторов,
/// чью живую версию хранитель правда держит. Нет живой версии — не гасится
/// ничего: такой идентификатор возвращается в `missing`, и вызывающий повторит
/// попытку, когда хранитель появится в составе. Повторный заход на прибранном
/// составе не делает ничего.
pub fn supersede_in(sources: &[&Index], keeper: &str, ids: &[String]) -> std::io::Result<Removed> {
    if sources.is_empty() || ids.is_empty() {
        return Ok(Removed {
            killed: 0,
            logical: Vec::new(),
            missing: ids.to_vec(),
            touched: Vec::new(),
        });
    }
    let hashes: Vec<u64> = ids.iter().map(|id| crate::bloom::hash(id)).collect();
    // Хранитель обязан быть в составе и обязан держать живую версию — иначе
    // гасить нечего в пользу чего.
    let Some(keep) = sources.iter().find(|ix| ix.dir == keeper) else {
        return Ok(Removed {
            killed: 0,
            logical: Vec::new(),
            missing: ids.to_vec(),
            touched: Vec::new(),
        });
    };
    // Каталог говорит, где искать; не сошёлся — ищем как искали всегда.
    let known = by_catalog(sources, ids, &hashes);
    let at_keeper = sources.iter().position(|ix| ix.dir == keeper);
    let mut docs: Vec<u32> = Vec::new();
    // Есть ли у хранителя живая версия каждого идентификатора.
    let mut kept: Vec<bool> = vec![false; ids.len()];
    for (i, (id, &h)) in ids.iter().zip(hashes.iter()).enumerate() {
        kept[i] = match (known.as_ref(), at_keeper) {
            (Some(all), Some(k)) => all[i].iter().any(|&(at, d)| at == k && keep.is_live(d)),
            _ => {
                docs.clear();
                keep.idmap.find_all(id, h, &mut docs);
                docs.iter().any(|&d| keep.is_live(d))
            }
        };
    }

    let mut killed = 0usize;
    let mut touched = Vec::new();
    let mut killed_id: Vec<bool> = vec![false; ids.len()];
    for (s, ix) in sources.iter().enumerate() {
        if ix.dir == keeper || ix.idmap.is_empty() {
            continue;
        }
        let mut changed = false;
        for (i, (id, &h)) in ids.iter().zip(hashes.iter()).enumerate() {
            if !kept[i] {
                continue;
            }
            let here: Vec<u32> = match known.as_ref() {
                Some(all) => all[i].iter().filter(|(at, _)| *at == s).map(|&(_, d)| d).collect(),
                None => {
                    docs.clear();
                    ix.idmap.find_all(id, h, &mut docs);
                    docs.clone()
                }
            };
            for doc in here {
                if ix.kill(doc) {
                    killed += 1;
                    killed_id[i] = true;
                    changed = true;
                }
            }
        }
        if changed {
            touched.push(ix.dir.clone());
        }
    }
    // Не «не встречался нигде», а «преемника не нашлось»: вызывающему это нужно,
    // чтобы попробовать ещё раз, когда хранитель появится в составе.
    let missing =
        ids.iter().zip(kept.iter()).filter(|(_, ok)| !**ok).map(|(id, _)| id.clone()).collect();
    let mut logical = Vec::new();
    let mut logical_seen = HashSet::new();
    for (id, killed) in ids.iter().zip(killed_id) {
        if killed && logical_seen.insert(id.as_str()) {
            logical.push(id.clone());
        }
    }
    Ok(Removed { killed, logical, missing, touched })
}

/// Итог удаления.
pub struct Removed {
    /// Сколько документов действительно погашено.
    pub killed: usize,
    /// Идентификаторы, для которых в этом проходе погашена хотя бы одна
    /// физическая версия. Порядок совпадает с входным `ids`; повторяющиеся
    /// значения выдаются один раз. Это поле отделяет логический ответ API от
    /// физического числа битов, изменённых в live maps.
    pub logical: Vec<String>,
    /// Сегменты, чья карта живых изменилась.
    pub touched: Vec<String>,
    /// Идентификаторы, не найденные ни в одном сегменте.
    ///
    /// Обычно это документы, ещё лежащие в буфере приёма: они станут видимыми
    /// после сброса, и удаление к ним надо применить тогда. Отсюда же следует,
    /// что молча их отбрасывать нельзя — иначе удаление свежепринятого документа
    /// пропадает без следа.
    pub missing: Vec<String>,
}

/// Один заход обслуживания, открывая сегменты самому.
///
/// Годится для стендов и однократных запусков. Узлу под нагрузкой нужен
/// [`once_in`]: у него сегменты уже открыты, а открытие — это полный разбор
/// словаря каждого.
pub fn once(dir: &str, cfg: Config) -> std::io::Result<Option<Action>> {
    // Нечитаемый список — отказ, а не «нечего делать». Прежде обслуживание в
    // этом случае молча ничего не делало **навсегда**: долг рос, причина не
    // называлась, а виновата была одна испорченная строка в файле.
    let names: Vec<String> = manifest::segments_checked(dir)
        .map_err(std::io::Error::other)?
        .iter()
        .map(|p| manifest::name_of(p))
        .collect();
    if names.is_empty() {
        return Ok(None);
    }
    let loaded: Vec<Index> = names
        .iter()
        .map(|n| index::load(&format!("{dir}/{n}")))
        .collect::<std::io::Result<Vec<_>>>()?;
    let refs: Vec<&Index> = loaded.iter().collect();
    once_in(dir, &refs, cfg)
}

/// Один заход обслуживания по **уже открытым** сегментам. `None` — делать нечего.
///
/// ## Зачем не открывать свои
///
/// Прежде заход начинался с `index::load` по каждому сегменту, а это не пара
/// отображений: у раскладки 7 и выше открытие гонит `walk_terms`, полный разбор
/// всех записей словаря. Повторялось это **каждые две секунды** и целиком под
/// замком состава — то есть узел, которому нечего укрупнять, всё равно
/// перечитывал весь индекс сорок три тысячи раз в сутки, каждый раз перекрывая
/// приём и удаления.
///
/// У писателя те же сегменты уже открыты, и они годятся как есть: сегмент
/// неизменяем, а карта живых правится на месте в разделяемом отображении — доля
/// мёртвого по уже открытому сегменту видна верно.
///
/// ## Заход целиком — не для узла под нагрузкой
///
/// Здесь три части идут подряд, то есть слияние оказывается там же, где выбор и
/// публикация: у вызывающего под замком состава. Узлу это не годится — слияние
/// пятигигабайтного сегмента длится минутами, и всё это время стояли бы приём и
/// удаления. Ему нужны [`choose`], [`run`] и [`publish`] порознь: первая и
/// третья под замком и быстро, вторая — без замка и сколько понадобится.
pub fn once_in(dir: &str, open: &[&Index], cfg: Config) -> std::io::Result<Option<Action>> {
    let Some(job) = choose(dir, open, cfg)? else {
        return Ok(None);
    };
    let out = run_all(&job, dir)?;
    publish_all(dir, &job, &out, cfg).map(Some)
}

/// Сегменты, по которым слияние идёт **прямо сейчас**, полными путями.
///
/// Слияние больше не идёт под замком состава, значит два захода могут
/// пересечься во времени. Возьми они одни и те же источники — оба сложили бы их
/// каждый в свой выход, и второй `publish` не нашёл бы источников в списке: пара
/// минут работы и место на диске уходят в мусор, а результата нет. Дешевле не
/// выбирать занятое.
///
/// Путь, а не имя: индексов в одном процессе бывает несколько, и `seg0000` у
/// них у всех.
static BUSY: std::sync::Mutex<Vec<String>> = std::sync::Mutex::new(Vec::new());

/// Пометка «эти сегменты заняты слиянием», снимающая себя сама.
///
/// Снимается на `Drop`, а не в [`publish`]: слияние может отказать — кончилось
/// место, поехало смещение, — и тогда источники обязаны снова стать
/// выбираемыми. Снимай пометку только успешная публикация, один отказ выводил бы
/// сегменты из обслуживания до перезапуска узла.
struct Lease {
    paths: Vec<String>,
}

impl Lease {
    /// Занимает пути разом. `None` — хотя бы один уже занят.
    fn take(paths: Vec<String>) -> Option<Lease> {
        let mut busy = BUSY.lock().unwrap_or_else(|e| e.into_inner());
        if paths.iter().any(|p| busy.contains(p)) {
            return None;
        }
        busy.extend(paths.iter().cloned());
        Some(Lease { paths })
    }

    fn busy(path: &str) -> bool {
        BUSY.lock().unwrap_or_else(|e| e.into_inner()).iter().any(|p| p == path)
    }
}

impl Drop for Lease {
    fn drop(&mut self) {
        let mut busy = BUSY.lock().unwrap_or_else(|e| e.into_inner());
        busy.retain(|p| !self.paths.contains(p));
    }
}

/// Что именно делает заход. Наружу видно только в имени итога.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Kind {
    /// Укрупнение окна мелких сегментов.
    Consolidate,
    /// Уборка одного грязного.
    Reclaim,
    /// Уборка одного грязного **по частям**.
    ///
    /// ## Зачем она нужна отдельно от обычной
    ///
    /// Расход уборки растёт вместе с источником, а источник тем крупнее, чем
    /// дольше живёт индекс. На узле с малой памятью наступает мгновение, после
    /// которого крупный грязный сегмент не убирается уже никогда: сливаться ему
    /// не с кем (он заморожен), а переписать его целиком не хватает памяти.
    /// Мёртвое остаётся в нём навсегда — сколько бы его ни накопилось, — и
    /// каждый запрос за это платит.
    ///
    /// Разделив выход, узел платит за каждую часть отдельно и платит столько,
    /// сколько сам назначил: пик становится `O(размер части)` и перестаёт
    /// зависеть от размера источника.
    ReclaimSplit,
}

impl Kind {
    /// Приставка имени выходного каталога.
    fn prefix(self) -> &'static str {
        match self {
            Kind::Consolidate => "mrg",
            Kind::Reclaim | Kind::ReclaimSplit => "cln",
        }
    }
}

/// Выбранная работа: что слить, по каким картам живых и куда.
///
/// Живёт от [`choose`] до [`publish`] и всё это время держит источники занятыми,
/// а копии их карт живых — при себе.
pub struct Job<'a> {
    kind: Kind,
    sources: Vec<&'a Index>,
    /// Имена источников: по ним публикация правит список, а не по номерам.
    /// Номера за время слияния успевают разъехаться — приём дописывает свои
    /// сегменты, соседнее слияние вырезает свои.
    names: Vec<String>,
    /// Копии карт живых на миг выбора. Разбор — у [`crate::live::Snapshot`].
    alive: Vec<crate::live::Snapshot>,
    /// Имена каталогов выходов без пути.
    ///
    /// Обычно один. Уборка по частям заводит по имени на часть: они встают в
    /// список подряд, на место источника, и порядок между ними — порядок
    /// документов источника.
    outs: Vec<String>,
    /// Сколько документов в источниках было на миг выбора.
    docs_in: usize,
    threads: usize,
    started: std::time::Instant,
    _lease: Lease,
}

impl Job<'_> {
    /// Имена источников — их и вырежет публикация.
    pub fn sources(&self) -> &[String] {
        &self.names
    }

    /// Имя каталога, куда ляжет слитое. У уборки по частям — первой части.
    pub fn out(&self) -> &str {
        self.outs.first().map_or("", |s| s.as_str())
    }

    /// Имена всех выходов: у обычной работы один, у уборки по частям несколько.
    pub fn outs(&self) -> &[String] {
        &self.outs
    }

    /// Логические байты источников работы. Нужны для job-level read
    /// amplification рядом с физическим `/proc/self/io`.
    pub fn input_bytes(&self) -> u64 {
        self.sources.iter().map(|source| source.bytes.total).sum()
    }

    pub fn input_docs(&self) -> usize {
        self.docs_in
    }

    pub fn kind_name(&self) -> &'static str {
        match self.kind {
            Kind::Consolidate => "consolidate",
            Kind::Reclaim => "reclaim",
            Kind::ReclaimSplit => "reclaim_split",
        }
    }
}

/// Выбирает работу. Быстро: ни одного слияния, только просмотр открытых.
///
/// Зовётся **под замком состава** и потому не делает ничего, что длится: список
/// сегментов здесь не читается вовсе — его перечитает [`publish`], которому он
/// и нужен.
///
/// ## Очередь работ: сперва укрупнение
///
/// Прежде уборка шла первой и безусловно: заход брал самый грязный сегмент,
/// переписывал его и **возвращался**, не дойдя до укрупнения. На индексе с
/// постоянным потоком удалений всегда находилось что убирать, и укрупнение не
/// случалось никогда — то есть сегменты копились, а поиск платил за каждый.
///
/// Теперь наоборот: есть что укрупнять — укрупняем, и мёртвое в этих сегментах
/// уходит попутно, потому что слияние погашенных не переносит. Нечего — убираем
/// самый грязный.
///
/// «Есть что укрупнять» пока значит «планировщик нашёл окно хотя бы из двух
/// сегментов, не доросших до цели». Правило **временное**: оно меряет окно
/// числом документов, а надо мерять байтами по ярусам, как это делает Lucene
/// (`TieredMergePolicy`). Ярусная политика заменит его целиком; до тех пор здесь
/// стоит простое и честное правило, а не заглушка, которая тихо ничего не
/// делает.
/// Почему обслуживанию нечего делать.
///
/// ## Зачем это вообще есть
///
/// Прежде отказ был молчаливым `Ok(None)`, и снаружи он выглядел так же, как
/// «работы нет». Разница между «нечего укрупнять» и «работа есть, но не влезает
/// в память» — это разница между здоровым узлом и узлом, который вечно
/// показывает долг и никогда его не разбирает. Кампания видела второе и не
/// могла отличить: `/_health` сообщал `pending_segments=3, running=0` и больше
/// ничего.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub enum Blocked {
    /// Работы нет: состав в пределах допустимого.
    #[default]
    Nothing,
    /// Все свободные сегменты заняты соседним слиянием.
    Leased,
    /// Работа есть, но не влезает в отведённую слиянию память.
    OverPeak {
        /// Чем именно не влезает: самое крупное слагаемое оценки.
        ///
        /// Одним числом отказ говорит «не влезает», и разговор кончается.
        /// Именем слагаемого он говорит, **чем**: широкой схемой, массивом,
        /// содержимым или просто числом документов. Первые три лечатся
        /// настройкой, последнее — только памятью.
        worst: &'static str,
        /// Сколько нужно, байт.
        need: u64,
        /// Сколько отведено, байт.
        have: u64,
        /// Сколько сегментов пыталось войти в работу.
        sources: usize,
        /// Какая именно работа не влезла.
        ///
        /// Различие несущее: уборка одного источника и слияние окна лечатся
        /// по-разному. Первую спасает разделение выхода, вторую — сужение окна.
        kind: Kind,
        /// Во сколько обошлась бы **самая дешёвая** пара сегментов, байт.
        ///
        /// Ноль — пары нет вовсе. Это и есть число, которым оператор чинит
        /// узел: пока `smallest_pair_need` выше отведённого, поднимать нужно
        /// память, а не ждать. Без него `need` крупного окна говорит лишь о том,
        /// что окно велико, — а велико оно, может, и по своей воле.
        smallest_pair_need: u64,
    },
    /// Все свободные сегменты выведены из укрупнения насовсем.
    ///
    /// Долг, если он есть, не разберётся уже ничем, кроме уборки: замороженный
    /// сегмент не сливается ни с кем никогда.
    AllFrozen,
    /// Ни одна пара не сводится к общему порядку полей.
    ///
    /// Пройдёт само, как только соседи сольются между собой, — но пока держится,
    /// состав не укрупняется, и знать об этом надо.
    SchemaSplit,
    /// Окно упирается в потолок смещений внутри сегмента.
    OverOffset,
    /// Окно упирается в потолок размера или числа документов.
    OverSize,
    /// Список сегментов уже у предела: новому выходу в нём не будет места.
    ///
    /// Слияние **уменьшает** число сегментов, поэтому упереться сюда можно
    /// только уборкой одного источника по частям: она одна отдаёт выходов
    /// больше, чем съела источников. Отказ здесь честнее, чем работа, чей итог
    /// не удастся опубликовать: часы счёта и полный диск в обмен на ничто.
    ManifestFull {
        /// Сколько сегментов сейчас.
        now: usize,
        /// Сколько их станет после публикации.
        after: usize,
        /// Предел.
        limit: usize,
    },
    /// Свободного места на диске меньше, чем запросила бы работа.
    DiskShort {
        /// Сколько свободно, байт.
        free: u64,
        /// Сколько понадобится, байт.
        need: u64,
    },
    /// Кто-то занял источники между просмотром и захватом. Пройдёт само.
    Race,
}

impl Blocked {
    /// Короткое имя для `/_health` и метрик.
    pub fn name(&self) -> &'static str {
        match self {
            Blocked::Nothing => "",
            Blocked::Leased => "leased",
            Blocked::OverPeak { .. } => "over_peak",
            Blocked::AllFrozen => "all_frozen",
            Blocked::SchemaSplit => "schema_split",
            Blocked::OverOffset => "over_offset",
            Blocked::OverSize => "over_size",
            Blocked::DiskShort { .. } => "disk_short",
            Blocked::ManifestFull { .. } => "manifest_full",
            Blocked::Race => "lease_race",
        }
    }
}

pub fn choose<'a>(dir: &str, open: &[&'a Index], cfg: Config) -> std::io::Result<Option<Job<'a>>> {
    choose_why(dir, open, cfg, &mut Blocked::Nothing)
}

/// То же, но называет причину, по которой работы не нашлось.
pub fn choose_why<'a>(
    dir: &str,
    open: &[&'a Index],
    cfg: Config,
    why: &mut Blocked,
) -> std::io::Result<Option<Job<'a>>> {
    let Some((free, picked)) = survey(open, cfg, why) else { return Ok(None) };
    let chosen: Vec<(String, &'a Index)> = picked.at.iter().map(|&i| free[i].clone()).collect();
    take(dir, cfg, picked.kind, &chosen, picked.parts, why)
}

/// Влезут ли части в список сегментов. Не влезут — причина названа.
///
/// Единственная работа, от которой состав **растёт**, — уборка по частям: она
/// отдаёт выходов больше, чем съела источников. Значит она одна и способна
/// упереться в предел списка, и узнать об этом надо до, а не после часов счёта.
fn room_for(now: usize, parts: usize, why: &mut Blocked) -> bool {
    let after = now.saturating_sub(1).saturating_add(parts);
    if after > manifest::MAX_SEGMENTS {
        *why = Blocked::ManifestFull { now, after, limit: manifest::MAX_SEGMENTS };
        return false;
    }
    true
}

/// На сколько частей делить уборку, чтобы она влезла. `None` — не поможет.
///
/// ## Как считается
///
/// Пик части складывается из двух видов слагаемых. Одни делятся вместе с
/// выходом — живые документы, корневые единицы, содержимое. Переменные
/// nested/multivalue units без per-document bound не делятся по среднему.
/// Другие слагаемые не делятся
/// вовсе: карта перенумерации заводится на **все** документы источника при
/// каждом проходе, потому что проход обязан знать про каждый исходный
/// документ, попал он в эту часть или нет.
///
/// Отсюда и предел: если неделимая часть сама не влезает, делить бесполезно, и
/// честный ответ — отказ с числом, а не бесконечное дробление.
fn split_parts(src: &Index, cfg: Config, have: u64) -> Option<usize> {
    let live = src.docs.saturating_sub(src.dead());
    if live == 0 {
        return None;
    }
    // Больше этого дробить незачем: части мельче целевого размера сегмента
    // тут же пойдут обратно в укрупнение, и уборка обменяла бы одну работу на
    // десяток.
    let floor_docs = (cfg.target_docs / 8).max(1024);
    let most = live.div_ceil(floor_docs).max(1);
    for parts in 2..=most {
        let per = live.div_ceil(parts);
        if merge::reclaim_part_peak(src, per as u64) <= have {
            return Some(parts);
        }
    }
    None
}

/// Два самых дешёвых сегмента, годных к слиянию друг с другом.
///
/// Последняя ступень лестницы деградации: когда окно, набранное по выгоде, не
/// влезает в память, пара всё равно уменьшает состав на один сегмент. Схемы
/// сверяются — пара, у которой нет общего порядка полей, не слилась бы и
/// стоила бы захода впустую.
fn cheapest_pair_at(segs: &[merge::Seg]) -> Option<Vec<usize>> {
    if segs.len() < 2 {
        return None;
    }
    let mut order: Vec<usize> = (0..segs.len()).collect();
    order.sort_by_key(|&i| segs[i].bytes);
    for (a, &i) in order.iter().enumerate() {
        for &j in order[a + 1..].iter() {
            if merge::pair_fits_schema(segs, i, j) {
                let mut pair = vec![i, j];
                // По возрасту: слияние склеивает документы в порядке
                // переданного среза, и порядок обязан быть тем же, в каком
                // сегменты лежат в списке.
                pair.sort_unstable();
                return Some(pair);
            }
        }
    }
    None
}

/// Что обслуживание взяло бы прямо сейчас — **без** захвата и без каталогов.
///
/// ## Зачем отдельно от [`choose_why`]
///
/// Датчик достижимости (`schedulable`) и сам планировщик обязаны отвечать одно
/// и то же. Пока датчик считал по своей формуле, он возвращал положительное
/// число в состояниях, где планировщик гарантированно отдавал «работы нет»: он
/// не знал ни про проверку памяти, ни про повышенный порог грязи у выросшего
/// сегмента, ни про порядок ветвей. А на этом датчике стоит предикат покоя
/// кампании — то есть «узел успокоился» могло не наступить никогда, притом что
/// планировщику делать было нечего.
///
/// Поэтому выбор работы живёт здесь и зовётся обоими. Побочных действий тут нет
/// ни одного: ни аренды, ни каталога, ни записи на диск.
struct Picked {
    kind: Kind,
    /// Номера в списке свободных сегментов.
    at: Vec<usize>,
    /// На сколько частей делить выход. Единица — как было.
    parts: usize,
}

fn survey<'a>(
    open: &[&'a Index],
    cfg: Config,
    why: &mut Blocked,
) -> Option<(Vec<(String, &'a Index)>, Picked)> {
    if open.is_empty() {
        return None;
    }
    // Занятые соседним слиянием пропускаются, как и живые: у живого сегмента
    // нет каталога, а слияние читает источники по нему и правит список
    // сегментов по именам. Попади он в работу — она отказала бы на первом же
    // открытии файла, и отказ повторялся бы каждые две секунды, пока буфер не
    // уедет на диск. Укрупнять его и незачем: он исчезнет сам вместе со
    // сбросом, и место на диске занимает ровно ноль.
    //
    // Порядок остальных сохраняется: публикация правит список по именам,
    // поэтому дыра в нём ничего не ломает.
    let free: Vec<(String, &'a Index)> = open
        .iter()
        .filter(|ix| !ix.src.is_memory())
        .filter(|ix| !Lease::busy(&ix.dir))
        .map(|ix| (manifest::name_of(&ix.dir), *ix))
        .collect();
    if free.is_empty() {
        *why = Blocked::Leased;
        return None;
    }

    // Самый грязный — считается до всего остального: от него зависит и порядок.
    let dirtiest = free
        .iter()
        .enumerate()
        .filter(|(_, (_, s))| s.docs > 0)
        .map(|(i, (_, s))| (i, s.dead() as f64 / s.docs as f64))
        .max_by(|a, b| a.1.total_cmp(&b.1));

    let segs: Vec<merge::Seg> = free.iter().map(|(_, s)| merge::Seg::of(s)).collect();
    let policy = cfg.merge_policy();
    let have = cfg.budget();
    // Во сколько обошлась бы самая дешёвая пара. Считается один раз и уходит
    // наружу вместе с отказом: пока это число выше отведённого, чинить надо
    // память, а не ждать. Без него `need` крупного окна говорит лишь о том, что
    // окно велико, — а велико оно, может, и по своей воле.
    let cheapest_pair = || -> u64 {
        match cheapest_pair_at(&segs) {
            Some(at) => {
                let pair: Vec<&Index> = at.iter().map(|&i| free[i].1).collect();
                merge::peak_estimate(&pair)
            }
            None => 0,
        }
    };
    let fits = |at: &[usize], kind: Kind| -> Result<(), Blocked> {
        let sources: Vec<&Index> = at.iter().map(|&i| free[i].1).collect();
        // Место на диске — до памяти: работа, которой некуда лечь, не начнётся
        // ни при каком бюджете, а бросить её посреди дороже всего.
        //
        // Выход не больше суммы живого у источников, и запас вдвое здесь не от
        // осторожности: словарь и записи слов переживают гашение всех
        // документов, кроме одного, и из выхода не уходят.
        if cfg.disk_free_bytes > 0 {
            let want: u64 = sources.iter().map(|s| merge::Seg::of(s).live()).sum();
            if want > cfg.disk_free_bytes {
                return Err(Blocked::DiskShort { free: cfg.disk_free_bytes, need: want });
            }
        }
        let need = merge::peak_estimate(&sources);
        if need > have {
            Err(Blocked::OverPeak {
                worst: merge::worst_part(&sources),
                need,
                have,
                sources: sources.len(),
                kind,
                smallest_pair_need: cheapest_pair(),
            })
        } else {
            Ok(())
        }
    };

    // Уборка выросшего грязного идёт первой, но **не забирает заход себе
    // безусловно**.
    //
    // Сегмент, доросший до целевого размера, в окно укрупнения не попадает
    // никогда: он один уже не влезает в потолок. Значит вычистить из него
    // мёртвое может только уборка, и если она не запускается, мёртвое остаётся
    // там навсегда — сколько бы его ни накопилось.
    //
    // Здесь была ошибка во все три стороны, и все три найдены замером.
    // Сначала уборка стояла первой и безусловно, и на потоке удалений
    // укрупнение не случалось ни разу: заход возвращался, не дойдя до него.
    // Потом её переставили в конец — и голодать стала она: у живого узла окно
    // укрупнения находится почти всегда. Третья — тот самый безусловный
    // возврат: уборка выросшего сегмента единственная может не влезть в память
    // навсегда, и её отказ отменял заход целиком, вместе с укрупнением,
    // диагностикой и хвостовой уборкой. Один недостижимый сегмент останавливал
    // обслуживание насовсем.
    //
    // Порог у выросшего свой и выше общего: каждый его заход это полная
    // перезапись, и окупаться она обязана сама. Разбор — у
    // [`grown_dead_fraction`].
    if let Some((at, share)) = dirtiest {
        let grown = match &policy {
            merge::MergePolicy::Tiered(t) | merge::MergePolicy::UpdateHeavy(t) => {
                segs[at].frozen(t)
            }
            // У плоской политики понятия «заморожен» нет; ближайшее — «не влезает
            // в потолок по документам», и оно решает то же самое.
            merge::MergePolicy::Flat(_) => free[at].1.docs > cfg.target_docs,
        };
        let need = if grown { grown_dead_fraction(cfg) } else { cfg.dead_fraction };
        if grown && share >= need {
            match fits(&[at], Kind::Reclaim) {
                Ok(()) => {
                    return Some((free, Picked { kind: Kind::Reclaim, at: vec![at], parts: 1 }));
                }
                Err(e) => match split_parts(free[at].1, cfg, have)
                    .filter(|&parts| room_for(segs.len(), parts, why))
                {
                    // Целиком не влезла — влезет по частям. Пик части назначаем
                    // мы, а не размер сегмента, поэтому уборка перестаёт быть
                    // недостижимой навсегда.
                    Some(parts) => {
                        return Some((
                            free,
                            Picked { kind: Kind::ReclaimSplit, at: vec![at], parts },
                        ));
                    }
                    None => *why = e,
                },
            }
        }
    }

    // Укрупнение. Ярусная политика сама решает, кого трогать: она считает, во
    // сколько сегментов индексу позволено уложиться, и молчит, пока их не
    // больше — это и есть тормоз против бури слияний.
    //
    // Подписи схем и порядок полей приходят с сегментами готовыми, а не
    // считаются здесь: заход идёт каждые две секунды под замком состава, и это
    // ровно то место, где планировщику нельзя платить за то, что не меняется.
    let mut noplan = merge::NoPlan::default();
    if let Some(at) = merge::plan_by_why(&segs, &policy, &mut noplan) {
        match fits(&at, Kind::Consolidate) {
            Ok(()) => return Some((free, Picked { kind: Kind::Consolidate, at, parts: 1 })),
            Err(e) => {
                // Окно не влезло — это ещё не повод не делать ничего.
                //
                // ## Лестница деградации, и почему у неё именно эти ступени
                //
                // Планировщик набирает окно по выгоде: широкое слияние
                // переписывает меньше байт за жизнь индекса, чем несколько
                // узких. Не влезло — выгода недостижима, но **прогресс**
                // достижим: самая дешёвая пара уменьшает состав на один
                // сегмент, и следующий заход начнёт с меньшего.
                //
                // Ступени «меньше потоков сжатия» здесь нет, и это выбрано, а
                // не забыто. Очередь сжатия ограничена и байтами, и числом
                // кусков (`store`, `BATCH_BYTES` против `threads * 64`), а
                // связывает почти всегда байтовый предел. Урезав потоки, мы
                // укоротили бы очередь, которая и так упирается в байты, —
                // то есть заплатили бы скоростью, ничего не выиграв по памяти.
                //
                // Не влезла и пара — тогда отказ, и в нём число: во сколько
                // обошлась бы самая дешёвая пара. Пока оно выше отведённого,
                // чинить надо память, а не ждать.
                if let Some(pair) = cheapest_pair_at(&segs) {
                    if fits(&pair, Kind::Consolidate).is_ok() {
                        return Some((
                            free,
                            Picked { kind: Kind::Consolidate, at: pair, parts: 1 },
                        ));
                    }
                }
                // Причина невлезшей уборки не затирается причиной укрупнения:
                // из двух надо назвать ту, что не разберётся сама.
                if *why == Blocked::Nothing {
                    *why = e;
                }
                return None;
            }
        }
    }

    // План не сложился. Прежде на этом заход и кончался молча, и снаружи «нечего
    // делать» было не отличить от «работа есть, но не влезает». Разница
    // решающая: во втором случае долг не разберётся никогда. Причину называет
    // сам планировщик — он один знает, на каком потолке окно рассыпалось.
    if *why == Blocked::Nothing {
        *why = match noplan {
            merge::NoPlan::TooFew | merge::NoPlan::WithinAllowed => Blocked::Nothing,
            merge::NoPlan::SchemaSplit => Blocked::SchemaSplit,
            merge::NoPlan::AllFrozen => Blocked::AllFrozen,
            merge::NoPlan::OverOffset => Blocked::OverOffset,
            merge::NoPlan::OverSize => Blocked::OverSize,
            merge::NoPlan::OverPeak { need, have } => Blocked::OverPeak {
                worst: "window",
                need,
                have,
                sources: 2,
                kind: Kind::Consolidate,
                smallest_pair_need: cheapest_pair(),
            },
        };
    }

    // Укрупнять нечего — убираем. Берётся самый грязный сегмент: там байт
    // возвращённого места дешевле всего.
    match dirtiest {
        Some((at, share)) if share >= cfg.dead_fraction => match fits(&[at], Kind::Reclaim) {
            Ok(()) => Some((free, Picked { kind: Kind::Reclaim, at: vec![at], parts: 1 })),
            Err(e) => match split_parts(free[at].1, cfg, have)
                .filter(|&parts| room_for(segs.len(), parts, why))
            {
                Some(parts) => {
                    Some((free, Picked { kind: Kind::ReclaimSplit, at: vec![at], parts }))
                }
                None => {
                    if *why == Blocked::Nothing {
                        *why = e;
                    }
                    None
                }
            },
        },
        _ => None,
    }
}

/// Сколько сегментов сверх допустимого состава ждут укрупнения.
///
/// Это оценка очереди, а не обещание числа будущих jobs: одно широкое слияние
/// убирает сразу несколько лишних сегментов, а новые могут появиться в ходе
/// работы. Для наблюдаемости важен именно растущий долг; точное число заданий
/// без постоянной очереди было бы выдумкой.
/// Сколько сегментов обслуживание **правда** может убрать прямо сейчас.
///
/// ## Зачем отдельно от [`backlog`]
///
/// `backlog` считает превышение над допустимым составом. Это верная мера долга,
/// но она молчит о достижимости, а достижимость бывает нулевой навсегда.
///
/// Замер на десяти миллионах: пятнадцать сегментов по шестьсот шестьдесят шесть
/// тысяч документов при потолке окна в миллион. Любая пара выходит за потолок,
/// значит слить их нельзя **никогда**, — а `backlog` сообщал долг в три
/// сегмента. Узел выглядел не досведённым, будучи полностью в порядке, и именно
/// поэтому `settled` не достигался в большинстве прогонов кампании.
///
/// Здесь спрашивается тот же планировщик, что и берёт работу. Ноль означает
/// «делать нечего», а не «долга нет»: долг может остаться и быть законным.
pub fn schedulable(open: &[&Index], cfg: Config) -> usize {
    // Тот же выбор, каким его делает планировщик, — не своя формула рядом.
    //
    // Пока формула была своя, датчик не знал ни про проверку памяти, ни про
    // повышенный порог грязи у выросшего сегмента, ни про порядок ветвей, и
    // возвращал положительное число там, где `choose` гарантированно отдавал
    // «работы нет». На этом датчике стоит предикат покоя кампании: расхождение
    // означало, что «узел успокоился» не наступает никогда, притом что делать
    // обслуживанию нечего.
    let mut why = Blocked::Nothing;
    match survey(open, cfg, &mut why) {
        // Укрупнение снимает столько сегментов, сколько взяло, минус выход.
        Some((_, picked)) if picked.kind == Kind::Consolidate => picked.at.len().saturating_sub(1),
        // Уборка снимает не сегмент, а мёртвое: заход есть работа, которую
        // можно сделать, и считается он одним.
        Some(_) => 1,
        None => 0,
    }
}

pub fn backlog(open: &[&Index], cfg: Config) -> usize {
    // Живые сегменты в долг не входят: обслуживание их не берёт (см.
    // [`choose`]), и считать их значило бы объявлять долгом работу, которой
    // никто не сделает. На узле с непрерывным приёмом это была бы вечная
    // единица в `compaction_pending` — и метрика, по которой ничего не решишь.
    let segs: Vec<merge::Seg> =
        open.iter().filter(|s| !s.src.is_memory()).map(|s| merge::Seg::of(s)).collect();
    let policy = cfg.merge_policy();
    match &policy {
        merge::MergePolicy::Tiered(t) | merge::MergePolicy::UpdateHeavy(t) => {
            let allowed = merge::allowed_seg_count(&segs, t).floor() as usize;
            segs.len().saturating_sub(allowed)
        }
        merge::MergePolicy::Flat(_) => {
            merge::plan_by(&segs, &policy).map_or(0, |picked| picked.len().saturating_sub(1))
        }
    }
}

/// Сколько отводится, когда память узнать не удалось.
///
/// Не выдуманный потолок машины, а скромное число: не знаем — не обещаем. Его
/// хватает на слияние сегментов в несколько сотен мегабайт, а больше на узле,
/// про который ничего не известно, начинать и не стоит.
const MERGE_BUDGET_UNKNOWN: u64 = 512 << 20;

/// Сколько памяти слиянию позволено занять.
///
/// Переменная среды `SVINDB_MERGE_BUDGET_MB` перекрывает расчёт — тем же
/// приёмом, что и `SVINDB_MERGE_POLICY` у политики слияния. Нужна двоим:
/// проверке, которой надо довести узел до отказа малым числом, и оператору,
/// который знает про свою машину больше, чем `mem::available`.
pub fn merge_budget() -> u64 {
    // Ноль отвергается, а не берётся как есть, и это не придирка к вводу.
    //
    // Ноль разводит два затвора в разные стороны. `Window::fits` при
    // `max_peak == 0` перестаёт проверять память **вовсе** — ноль там значит
    // «предела нет». А `job()` при нулевом бюджете отказывает всему подряд:
    // постоянный расход слияния (`PEAK_FLOOR`) больше нуля всегда. То есть
    // политика набирает окна без оглядки на память, а взять их не может ни
    // одно, и обслуживание выключается насовсем — молча, без причины в
    // `/_health`, потому что причина есть, но её никто не спрашивал.
    //
    // Поэтому ноль и неразобранное значение означают одно: «настройки нет,
    // считай по машине». Заодно бюджет не бывает меньше постоянного расхода —
    // иначе он обещает работу, которой не хватит даже на её собственный пол.
    if let Some(v) = std::env::var_os("SVINDB_MERGE_BUDGET_MB")
        .and_then(|v| v.to_str().and_then(|s| s.trim().parse::<u64>().ok()))
        .filter(|v| *v > 0)
    {
        return (v << 20).max(merge::PEAK_FLOOR);
    }
    // Доля берётся из общего реестра, а не считается здесь своим числом.
    // Пока каждый считал сам, суммы не знал никто: доли складывались как
    // получится, и получалось больше единицы.
    match crate::govern::share(crate::govern::Class::Merge) {
        0 => MERGE_BUDGET_UNKNOWN,
        v => v.max(merge::PEAK_FLOOR),
    }
}

/// Захватывает выбранное и заводит каталог выхода.
///
/// Память здесь уже не проверяется: проверку делает [`survey`], и делает её до
/// захвата — иначе датчик достижимости и планировщик отвечали бы по-разному.
fn take<'a>(
    dir: &str,
    cfg: Config,
    kind: Kind,
    picked: &[(String, &'a Index)],
    parts: usize,
    why: &mut Blocked,
) -> std::io::Result<Option<Job<'a>>> {
    let sources: Vec<&'a Index> = picked.iter().map(|(_, s)| *s).collect();
    let Some(lease) = Lease::take(sources.iter().map(|s| s.dir.clone()).collect()) else {
        // Кто-то занял их между просмотром и этой строкой. Не беда: работа
        // никуда не денется, следующий заход через две секунды.
        //
        // Но назвать это надо: без имени заход выглядит снаружи как «работы
        // нет» — то же самое, что у здорового узла, которому нечего сливать.
        // Отличать их обязан всякий, кто по этому датчику решает, успокоился
        // ли узел.
        *why = Blocked::Race;
        return Ok(None);
    };
    // Копии карт живых снимаются **здесь**, под замком состава: между ними и
    // первым прочитанным байтом слияния не должно быть окна, в котором удаление
    // прошло бы незамеченным ни копией, ни сверкой при публикации.
    let alive: Vec<crate::live::Snapshot> = sources.iter().map(|s| s.live_copy()).collect();
    // Каталоги заводятся сразу, хотя писать в них будет слияние: свободное имя
    // выбирается обходом каталога, и не займи его сейчас — соседний заход выбрал
    // бы то же самое и писал бы в тот же каталог.
    let mut outs = Vec::with_capacity(parts.max(1));
    for _ in 0..parts.max(1) {
        let name = next_name(dir, kind.prefix());
        std::fs::create_dir_all(format!("{dir}/{name}"))?;
        outs.push(name);
    }
    Ok(Some(Job {
        kind,
        docs_in: sources.iter().map(|s| s.docs).sum(),
        names: picked.iter().map(|(n, _)| n.clone()).collect(),
        sources,
        alive,
        outs,
        threads: cfg.threads(),
        started: std::time::Instant::now(),
        _lease: lease,
    }))
}

/// Делает работу. Долго: минуты на крупном сегменте.
///
/// Зовётся **без замка состава** — в этом весь смысл разделения. Пока это идёт,
/// приём дописывает сегменты, а удаления гасят документы, в том числе в
/// источниках. Первое безобидно, второе разбирает [`publish`].
pub fn run(job: &Job, dir: &str) -> std::io::Result<merge::Merged> {
    let mut done = run_all(job, dir)?;
    // Обычная работа отдаёт один выход, и вызывающие ждут именно его.
    // У уборки по частям выходов несколько, и звать эту дверь для неё нельзя.
    done.pop().ok_or_else(|| std::io::Error::other("работа не дала ни одного выхода"))
}

/// Делает работу целиком, включая уборку по частям.
///
/// ## Почему части идут одна за другой, а не разом
///
/// Ради памяти всё и затевалось: одновременные части сложили бы свои расходы, и
/// разделение перестало бы что-либо значить. Последовательные платят по одной.
/// Отрезки номеров документов источника, по одному на часть.
///
/// Одна функция на обе стороны — на сборку частей и на перенос удалений.
/// Разойдись они, часть считала бы своим не тот отрезок, и удаление, пришедшее
/// во время работы, потерялось бы молча.
fn part_ranges(docs: u32, parts: usize) -> Vec<(u32, u32)> {
    if parts <= 1 {
        return vec![(0, docs)];
    }
    let per = docs.div_ceil(parts as u32);
    (0..parts)
        .map(|k| {
            let from = per.saturating_mul(k as u32).min(docs);
            (from, from.saturating_add(per).min(docs))
        })
        .collect()
}

/// Отношение «оценка к измеренному» у последней работы. `None` — не мерили.
///
/// ## Зачем это наружу
///
/// Оценка расхода слияния — обещание, и до сих пор поверить его можно было
/// только тестом на игрушечных корпусах. Обещание же даётся боевому узлу и на
/// боевых сегментах, где схема шире, мёртвых больше, а потоков десятки.
/// Разойдись оценка с действительностью там — узнать было бы не от кого: узел
/// просто снимался бы ядром.
///
/// Считается только в профилировочной сборке (`alloc-stats`): цена счёта на
/// каждом выделении в боевой сборке принята измерительным контрактом и туда не
/// допускается. Ворота выпуска смотрят на эту величину: хоть один отсчёт ниже
/// единицы означает, что оценка перестала быть мажорантой, и это не «неточно»,
/// а «узел будет снят ядром».
pub fn estimate_ratio() -> Option<f64> {
    #[cfg(feature = "alloc-stats")]
    {
        let (est, real) = LAST_PEAK.lock().unwrap_or_else(|e| e.into_inner()).take()?;
        (real > 0).then(|| est as f64 / real as f64)
    }
    #[cfg(not(feature = "alloc-stats"))]
    {
        None
    }
}

#[cfg(feature = "alloc-stats")]
static LAST_PEAK: std::sync::Mutex<Option<(u64, usize)>> = std::sync::Mutex::new(None);

#[cfg(feature = "alloc-stats")]
pub fn run_all(job: &Job, dir: &str) -> std::io::Result<Vec<merge::Merged>> {
    let est = merge::peak_estimate(&job.sources);
    let mut out = None;
    let real = crate::alloc::peak_of(|| out = Some(run_all_inner(job, dir)));
    *LAST_PEAK.lock().unwrap_or_else(|e| e.into_inner()) = Some((est, real));
    out.expect("работа выполнена")
}

#[cfg(not(feature = "alloc-stats"))]
pub fn run_all(job: &Job, dir: &str) -> std::io::Result<Vec<merge::Merged>> {
    run_all_inner(job, dir)
}

fn run_all_inner(job: &Job, dir: &str) -> std::io::Result<Vec<merge::Merged>> {
    let lim = merge::Limits { threads: job.threads };
    if job.outs.len() == 1 {
        let out = format!("{dir}/{}", job.outs[0]);
        return Ok(vec![merge::merge_as(&job.sources, Some(&job.alive), &out, lim)?]);
    }
    // Уборка по частям: источник один, и части режутся по **номерам его
    // документов**. Отрезки не пересекаются и покрывают весь источник, поэтому
    // каждый живой документ попадает ровно в один выход — ни потерянных, ни
    // задвоенных.
    let src = job.sources.first().ok_or_else(|| {
        std::io::Error::new(std::io::ErrorKind::InvalidInput, "уборка без источника")
    })?;
    let snap = &job.alive[0];
    let ranges = part_ranges(src.docs as u32, job.outs.len());
    let mut done = Vec::with_capacity(job.outs.len());
    for (name, &(from, upto)) in job.outs.iter().zip(ranges.iter()) {
        let out = format!("{dir}/{name}");
        done.push(merge::merge_as(&[*src], Some(&[snap.only(from, upto)]), &out, lim)?);
    }
    Ok(done)
}

/// Вносит сделанное в список. Быстро: правка одного файла и сверка карт.
///
/// Зовётся **под замком состава**, тем же, под которым выбиралась работа.
///
/// ## Что сверяется и почему не весь список
///
/// Прежде заход требовал, чтобы переданный состав совпал со списком на диске
/// целиком, и это было верно ровно потому, что публиковал он список,
/// **посчитанный от переданного**: имена переданного минус слитые. Передай ему
/// подмножество — и остальные сегменты молча исчезли бы из индекса.
///
/// Теперь список считается от того, что лежит на диске **сейчас**: он читается
/// заново, из него вырезаются источники и на место первого из них встаёт выход.
/// Всё, чего слияние не касалось, переезжает как есть, — а значит и требовать
/// совпадения незачем: пока шло слияние, приём законно дописал свои сегменты, и
/// отказывать ему в этом было бы странно.
///
/// Требуется другое: источники обязаны быть на месте. Пропажа означает, что их
/// уже вырезал кто-то ещё, и публиковать поверх — значит вернуть в индекс
/// сегменты, которых там больше нет.
///
/// ## Про удаления, случившиеся во время слияния
///
/// Слияние шло по копиям карт живых, снятым при выборе. Документ, погашенный
/// после этого, в слитый сегмент попал живым. Здесь карты сверяются с копиями, и
/// каждый погашенный за это время гасится в выходе — до того, как выход попадёт
/// в список. Иначе удаление, угодившее в окно слияния, воскресало бы.
pub fn publish(dir: &str, job: &Job, out: &merge::Merged, cfg: Config) -> std::io::Result<Action> {
    publish_all(dir, job, std::slice::from_ref(out), cfg)
}

/// То же для работы с несколькими выходами.
///
/// Выходы встают в список подряд, на место источника, и порядок между ними —
/// порядок документов источника. Иначе номера в общем пространстве пошли бы
/// вразрез с возрастом, а курсоры страниц, выданные до уборки, начали бы
/// указывать на другие документы.
pub fn publish_all(
    dir: &str,
    job: &Job,
    outs: &[merge::Merged],
    cfg: Config,
) -> std::io::Result<Action> {
    let listed: Vec<String> = manifest::segments_checked(dir)
        .map_err(std::io::Error::other)?
        .iter()
        .map(|p| manifest::name_of(p))
        .collect();
    let mut at: Vec<usize> = Vec::with_capacity(job.names.len());
    for n in job.names.iter() {
        let Some(k) = listed.iter().position(|x| x == n) else {
            return Err(std::io::Error::new(
                std::io::ErrorKind::InvalidData,
                format!(
                    "{dir}: источник {n} исчез из списка, пока шло слияние — в списке \
                     {listed:?}. Опубликовать слитое значило бы вернуть в индекс то, \
                     что из него уже вырезали"
                ),
            ));
        };
        at.push(k);
    }
    if outs.len() != job.outs.len() {
        return Err(std::io::Error::new(
            std::io::ErrorKind::InvalidInput,
            format!(
                "публикации дано {} итогов на {} заведённых выходов",
                outs.len(),
                job.outs.len()
            ),
        ));
    }
    let mut carried = 0usize;
    let ranges = part_ranges(job.sources.first().map_or(0, |s| s.docs as u32), outs.len());
    for (k, one) in outs.iter().enumerate() {
        let mine = (outs.len() > 1).then(|| ranges[k]);
        carried += carry_deletes(dir, job, &job.outs[k], one, mine)?;
    }
    let made: usize = outs.iter().map(|o| o.docs).sum();

    // Выход встаёт на место первого из источников, а не в конец: список хранит
    // сегменты по старшинству, и свежий выход между новичками приёма испортил бы
    // порядок, по которому набирается окно укрупнения.
    let first = at.iter().copied().min().unwrap_or(0);
    let mut next: Vec<String> = Vec::with_capacity(listed.len());
    for (k, n) in listed.iter().enumerate() {
        // Сегмент, где погашены **все** документы, исчезает целиком, а не
        // становится пустым. Разница не косметическая: пустой сегмент нечитаем —
        // в нём нет ни одного поля с длиной, а значит нечем считать нормировку,
        // — и, попав в список, он валит всё, что этот список читает.
        if k == first {
            // Выход без единого документа в список не идёт: пустой сегмент
            // нечитаем — в нём нет ни одного поля с длиной, а значит нечем
            // считать нормировку, — и, попав в список, он валит всё, что этот
            // список читает.
            for (j, one) in outs.iter().enumerate() {
                if one.docs > 0 {
                    next.push(job.outs[j].clone());
                }
            }
        }
        if at.contains(&k) {
            continue;
        }
        next.push(n.clone());
    }
    let retiring: Vec<String> = job.names.clone();
    manifest::write(dir, &next)?;
    // ID directory намеренно не пересобирается после каждого merge. На
    // production-каталоге в сотни миллионов документов это гигабайтная
    // сортировка после слияния нескольких мегабайт и физическая amplification
    // в сотни раз. Старый каталог безопасно отвергается по generation stamp;
    // maintenance свернёт его один раз после окончания серии merge.
    // Выход без единого документа сносится **сразу**, без отсрочки.
    //
    // Отсрочка нужна тем, кого мог успеть открыть читатель, — а этот выход в
    // список не попадал и попасть не мог: сегмент с нулём документов нечитаем,
    // у него пустой заголовок. Лежащий рядом, он выглядит поломкой для всякого,
    // кто обходит каталог, — и `check --full` честно её и называет. Под потоком
    // замен такие выходы появляются постоянно: сегмент, все версии которого
    // заменены, уборка забирает целиком.
    for (j, one) in outs.iter().enumerate() {
        if one.docs > 0 {
            continue;
        }
        let path = format!("{dir}/{}", job.outs[j]);
        if let Err(e) = std::fs::remove_dir_all(&path) {
            if e.kind() != std::io::ErrorKind::NotFound {
                // Не отказ всей публикации: список уже верен, а каталог подберёт
                // `sweep` на ближайшем подъёме.
                eprintln!("уборка: пустой выход {path} не снёсся: {e}");
            }
        }
    }
    retire(dir, &retiring, cfg.grace_ms);

    let took_ms = job.started.elapsed().as_secs_f64() * 1000.0;
    Ok(match job.kind {
        Kind::Consolidate => {
            Action::Consolidated { segments: job.names.len(), docs: job.docs_in, carried, took_ms }
        }
        Kind::Reclaim | Kind::ReclaimSplit => {
            Action::Reclaimed { was: job.docs_in, now: made, carried, took_ms }
        }
    })
}

/// Гасит в выходе то, что умерло в источниках, пока шло слияние.
///
/// Отдаёт число погашенных. Отказ — если карта живых выхода не открывается: в
/// список он тогда не попадёт вовсе, и это единственный верный ответ. Молча
/// опубликовать сегмент, в котором удалённое ожило, нельзя.
fn carry_deletes(
    dir: &str,
    job: &Job,
    name: &str,
    out: &merge::Merged,
    mine: Option<(u32, u32)>,
) -> std::io::Result<usize> {
    if out.docs == 0 {
        return Ok(0);
    }
    // Дошло ли до источников хоть одно удаление за это время. Признак лежит в
    // самом файле карты, поэтому виден и через чужой экземпляр сегмента.
    if job.sources.iter().enumerate().all(|(i, s)| s.all_live() && job.alive[i].all_live()) {
        return Ok(0);
    }
    let path = format!("{dir}/{name}");
    let Some(live) = crate::live::Live::open(&path, out.docs) else {
        return Err(std::io::Error::new(
            std::io::ErrorKind::InvalidData,
            format!(
                "{path}: карта живых слитого сегмента не открылась, а в источниках есть \
                 погашенные — опубликовать его значило бы воскресить удалённое"
            ),
        ));
    };
    if !live.writable() {
        return Err(std::io::Error::new(
            std::io::ErrorKind::PermissionDenied,
            format!("{path}: карта живых слитого сегмента только для чтения"),
        ));
    }
    let mut killed = 0usize;
    let mut lost: Option<(usize, u32)> = None;
    for (i, s) in job.sources.iter().enumerate() {
        let Some(map) = s.live.as_ref() else { continue };
        job.alive[i].newly_dead(map, |d| match out.out_doc(i, d) {
            // Номер есть и он внутри выхода — гасим. `false` от гашения тут
            // значит «уже мёртв», и это не потеря: считаем только настоящие.
            Some(n) if (n as usize) < out.docs => {
                if live.kill(n) {
                    killed += 1;
                }
            }
            // Документ был жив на миг снятия копии — значит в выход он попал, и
            // номер у него обязан быть, притом внутри выхода. Иначе таблица
            // перенумерации разошлась с картой, и гасить нечего: удаление
            // потерялось бы молча, а это худшее из возможного.
            //
            // У уборки по частям это не так: документ попал ровно в **одну**
            // часть, и для остальных его номера нет по построению. Но «по
            // построению» проверяется, а не подразумевается: отсутствие
            // законно ровно тогда, когда документ лежит вне отрезка этой части.
            // Внутри отрезка отсутствие номера — та же потеря удаления, и
            // молчать о ней нельзя.
            _ if mine.is_some_and(|(from, upto)| d < from || d >= upto) => {}
            _ => lost = lost.or(Some((i, d))),
        });
    }
    if let Some((i, d)) = lost {
        return Err(std::io::Error::new(
            std::io::ErrorKind::InvalidData,
            format!(
                "{path}: документ {d} источника {} погашен во время слияния, а номера в \
                 слитом у него нет — перенести удаление некуда",
                job.sources[i].dir
            ),
        ));
    }
    // На диск — **до** того, как выход попадёт в список. Сегмент, ставший
    // видимым с несброшенной картой, при потере питания воскресил бы удалённое:
    // журнал приёма к тому времени обрезан по отметке, которую двигал сброс.
    live.sync()?;
    Ok(killed)
}

/// Убирает каталоги, дав читателям время закончить.
///
/// Пока каталог кем-то держится (`manifest::Pin` — снимок, копирование), уборка
/// ждёт. Ждёт не бесконечно: держатель может жить минутами, а вечно висящий
/// поток — это утечка. Не дождавшись, уборка просто уходит, и каталоги подберёт
/// `manifest::sweep` следующим заходом. Отложить возврат места безопасно,
/// снести файл из-под копирующего — нет.
fn retire(dir: &str, names: &[String], grace_ms: u64) {
    let dir = dir.to_string();
    let names: Vec<String> = names.to_vec();
    std::thread::spawn(move || {
        std::thread::sleep(std::time::Duration::from_millis(grace_ms));
        for _ in 0..RETIRE_WAITS {
            if manifest::pinned(&dir).is_empty() {
                for n in names {
                    let _ = std::fs::remove_dir_all(format!("{dir}/{n}"));
                }
                return;
            }
            std::thread::sleep(std::time::Duration::from_millis(RETIRE_STEP_MS));
        }
    });
}

/// Сколько раз уборка переспрашивает держателей и с каким шагом: минута сверху.
const RETIRE_WAITS: usize = 300;
const RETIRE_STEP_MS: u64 = 200;

/// Свободное имя с данной приставкой.
fn next_name(dir: &str, prefix: &str) -> String {
    let n = std::fs::read_dir(dir)
        .map(|it| {
            it.filter_map(|e| e.ok())
                .filter_map(|e| {
                    let name = e.file_name().to_string_lossy().to_string();
                    name.strip_prefix(prefix).and_then(|d| d.parse::<usize>().ok()).map(|x| x + 1)
                })
                .max()
                .unwrap_or(0)
        })
        .unwrap_or(0);
    format!("{prefix}{n:04}")
}

