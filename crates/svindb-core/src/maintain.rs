    /// Бюджет слияния не бывает нулевым и не бывает ниже постоянного расхода.
    ///
    /// ## Почему ноль опаснее маленького числа
    ///
    /// Ноль разводит два затвора в разные стороны. `Window::fits` при нулевом
    /// потолке перестаёт проверять память **вовсе** — ноль там значит «предела
    /// нет». А `job()` при нулевом бюджете отказывает всему подряд: постоянный
    /// расход слияния больше нуля всегда. Политика набирает окна без оглядки на
    /// память, взять их не может ни одно, и обслуживание выключается насовсем —
    /// молча, потому что причина есть, но её никто не спрашивал.
    ///
    /// Маленькое число такого не делает: оно отказывает честно и с причиной.
    #[test]
    fn the_merge_budget_never_reaches_zero() {
        assert!(merge_budget() > 0, "расчёт по машине не вправе дать ноль");
        assert!(
            Config::default().budget() >= merge::PEAK_FLOOR,
            "умолчание ниже постоянного расхода слияния"
        );
        // Заданный вручную мизер поднимается до пола, а не остаётся мизером:
        // бюджет, которого не хватает даже на собственный пол слияния, обещает
        // работу, которой не будет.
        let tiny = Config { merge_budget_bytes: 1, ..Config::default() };
        assert_eq!(tiny.budget(), merge::PEAK_FLOOR, "мизер не поднялся до пола");
        // Пол не раздаёт памяти сверх нужного: он ровно постоянный расход, и
        // любая настоящая работа стоит строго больше — отказ остаётся отказом,
        // но с названной причиной.
        assert!(tiny.budget() < 64 << 20, "пол раздал памяти сверх постоянного расхода");
    }

