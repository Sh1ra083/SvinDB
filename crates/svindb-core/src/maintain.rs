    fn corpus(name: &str, docs: u32, per_seg: u32) -> String {
        let dir = std::env::temp_dir().join(format!("svindb-maintain-{name}"));
        let dir = dir.to_string_lossy().to_string();
        std::fs::remove_dir_all(&dir).ok();
        let mut ix =
            Indexer::new(&dir, vec!["title".into(), "body".into()], vec![2.0, 1.0], per_seg);
        for i in 0..docs {
            ix.add(
                &format!("d{i:06}"),
                &[&format!("док{}", i % 97), &format!("общее слово{} тело{}", i % 7, i % 53)],
            );
        }
        ix.flush();
        dir
    }

