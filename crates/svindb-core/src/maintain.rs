            let tier = cfg.tier_of();
            assert!(
                open.iter().all(|s| merge::Seg::of(s).frozen(&tier)),
                "стенд должен состоять только из достигших ресурсной границы сегментов"
            );
            assert!(choose_why(&tight, &open, cfg, &mut why).unwrap().is_none());
