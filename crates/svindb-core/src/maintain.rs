    /// Работа, которой некуда лечь, не начинается и называет причину.
    ///
    /// Слияние пишет выход рядом с источниками и только потом их снимает:
    /// на время работы место нужно и под то, и под другое. Кончится посреди —
    /// часы счёта в мусор, каталог недописанного на диске, а место, которое
